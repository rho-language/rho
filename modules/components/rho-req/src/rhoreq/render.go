// ListText is `rho req list`.
func ListText(reqs []*Requirement, withRepo bool) string {
	var b strings.Builder
	for _, req := range reqs {
		repo := ""
		if withRepo {
			repo = fmt.Sprintf("%-16s ", req.Repo)
		}
		fmt.Fprintf(&b, "%s%-14s %-5s %-12s %-13s %s\n", repo, req.ID, req.Level, req.Status, req.Verification, req.Title)
	}
	return b.String()
}

// ShowText is `rho req show`.
func ShowText(w *Workspace, req *Requirement, row *Row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s  %s\n", req.ID, req.Title)
	fmt.Fprintf(&b, "  level %s, %s, verified by %s   (%s/%s:%d)\n\n", req.Level, req.Status, req.Verification, req.Repo, req.File, req.Line)
	fmt.Fprintf(&b, "  %s\n", strings.TrimSpace(req.Statement))
	if req.Rationale != "" {
		fmt.Fprintf(&b, "\n  rationale: %s\n", strings.TrimSpace(req.Rationale))
	}
	b.WriteString("\nupward:\n")
	up := Upward(w, req.ID)
	if len(up) == 0 {
		b.WriteString("  (satisfies nothing above it)\n")
	}
	for _, line := range up {
		b.WriteString("  " + line + "\n")
	}
	b.WriteString("downward:\n")
	down := Downward(w, req.ID, "  ", map[string]bool{})
	if len(down) == 0 {
		b.WriteString("  (nothing satisfies it)\n")
	}
	for _, line := range down {
		b.WriteString(line + "\n")
	}
	b.WriteString("ADRs:\n")
	if len(row.ADRs) == 0 {
		b.WriteString("  (none)\n")
	}
	for _, ref := range row.ADRs {
		if adr := w.ADR(req.Repo, ref); adr != nil {
			fmt.Fprintf(&b, "  %s  %s (%s)\n", ref, adr.Title, adr.Status)
		}
	}
	b.WriteString("code:\n")
	if len(row.Code) == 0 {
		b.WriteString("  (no @req tag)\n")
	}
	for _, at := range row.Code {
		fmt.Fprintf(&b, "  %s/%s:%d  %s\n", at.Repo, at.File, at.Line, at.Symbol)
	}
	b.WriteString("tests:\n")
	if len(row.Tests) == 0 {
		b.WriteString("  (no @verifies tag)\n")
	}
	for _, t := range row.Tests {
		fmt.Fprintf(&b, "  %-8s %s/%s:%d  %s\n", t.Result, t.Repo, t.File, t.Line, t.Test)
	}
	fmt.Fprintf(&b, "evidence: %s\n", row.Evidence)
	return b.String()
}

// Upward is the chain of requirements one satisfies, transitively.
func Upward(w *Workspace, id string) []string {
	out := []string{}
	seen := map[string]bool{id: true}
	var walk func(id, indent string)
	walk = func(id, indent string) {
		req := w.Requirement(id)
		if req == nil {
			return
		}
		for _, parent := range req.Satisfies {
			found := w.Requirement(parent)
			title := "(missing)"
			if found != nil {
				title = fmt.Sprintf("%s  [%s, %s]", found.Title, found.Level, found.Status)
			}
			out = append(out, indent+parent+"  "+title)
			if !seen[parent] {
				seen[parent] = true
				walk(parent, indent+"  ")
			}
		}
	}
	walk(id, "")
	return out
}

// Downward is the tree of requirements that satisfy one.
func Downward(w *Workspace, id, indent string, seen map[string]bool) []string {
	out := []string{}
	if seen[id] {
		return out
	}
	seen[id] = true
	for _, child := range w.Children(id) {
		out = append(out, fmt.Sprintf("%s%s  %s  [%s, %s]", indent, child.ID, child.Title, child.Level, child.Status))
		out = append(out, Downward(w, child.ID, indent+"  ", seen)...)
	}
	return out
}

// TraceText is `rho req trace`.
func TraceText(matrix *Matrix) string {
	var b strings.Builder
	for _, row := range matrix.Rows {
		fmt.Fprintf(&b, "%-14s %-5s %-12s %-8s children:%d adrs:%d code:%d tests:%d\n", row.ID, row.Level, row.Status, row.Evidence,
			len(row.Children), len(row.ADRs), len(row.Code), len(row.Tests))
		for _, t := range row.Tests {
			fmt.Fprintf(&b, "    %-8s %s  %s:%d\n", t.Result, t.Test, t.File, t.Line)
		}
	}
	if len(matrix.Gaps) > 0 {
		b.WriteString("\ngaps:\n")
		for _, gap := range matrix.Gaps {
			place := ""
			if gap.File != "" {
				place = gap.Repo + "/" + gap.File
				if gap.Line > 0 {
					place += fmt.Sprintf(":%d", gap.Line)
				}
				place += ": "
			}
			fmt.Fprintf(&b, "  %s%s [%s]\n", place, gap.Message, gap.Code)
		}
	}
	return b.String()
}
