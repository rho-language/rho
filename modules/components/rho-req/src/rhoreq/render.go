package rhoreq

import (
	"fmt"
	"sort"
	"strings"
)

// Render is the Markdown document for the reported repositories. A non-empty
// level limits the level sections to that level; the ADR index and the trace
// matrix are always whole.
func Render(w *Workspace, matrix *Matrix, level string) string {
	var b strings.Builder
	names := []string{}
	for _, repo := range w.Reported() {
		names = append(names, repo.Name)
	}
	fmt.Fprintf(&b, "# Requirements: %s\n\n", strings.Join(names, ", "))
	b.WriteString("Generated by `rho req render` from docs/requirements and docs/architecture/adr. Do not edit; edit the sources.\n\n")

	reqs := []*Requirement{}
	for _, repo := range w.Reported() {
		reqs = append(reqs, repo.Requirements()...)
	}
	levels := w.LevelsOf(w.Focus.Name)
	for _, lvl := range levels {
		if level != "" && lvl.Name != level {
			continue
		}
		atLevel := []*Requirement{}
		for _, req := range reqs {
			if req.Level == lvl.Name {
				atLevel = append(atLevel, req)
			}
		}
		if len(atLevel) == 0 {
			continue
		}
		sort.SliceStable(atLevel, func(a, b int) bool { return atLevel[a].ID < atLevel[b].ID })
		fmt.Fprintf(&b, "## %s (%s)\n\n", lvl.Title, lvl.Name)
		b.WriteString("| ID | Title | Status | Verification | Satisfies |\n|---|---|---|---|---|\n")
		for _, req := range atLevel {
			fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s |\n", req.ID, anchor(req.ID), cell(req.Title), req.Status, req.Verification, cell(strings.Join(req.Satisfies, ", ")))
		}
		b.WriteString("\n")
		for _, req := range atLevel {
			fmt.Fprintf(&b, "<a id=\"%s\"></a>\n\n### %s: %s\n\n", anchor(req.ID), req.ID, req.Title)
			fmt.Fprintf(&b, "%s\n\n", strings.TrimSpace(req.Statement))
			if req.Rationale != "" {
				fmt.Fprintf(&b, "*Rationale.* %s\n\n", strings.TrimSpace(req.Rationale))
			}
			facts := []string{
				"Status: " + req.Status,
				"Verification: " + req.Verification,
				fmt.Sprintf("Source: %s/%s:%d", req.Repo, req.File, req.Line),
			}
			if len(req.Satisfies) > 0 {
				facts = append(facts, "Satisfies: "+strings.Join(req.Satisfies, ", "))
			}
			if row := matrix.Row(req.ID); row != nil && len(row.Children) > 0 {
				facts = append(facts, "Satisfied by: "+strings.Join(row.Children, ", "))
			}
			if len(req.DecidedBy) > 0 {
				facts = append(facts, "Decided by: "+strings.Join(req.DecidedBy, ", "))
			}
			if req.Owner != "" {
				facts = append(facts, "Owner: "+req.Owner)
			}
			if req.Changed != "" {
				facts = append(facts, "Changed: "+req.Changed)
			}
			if len(req.Tags) > 0 {
				facts = append(facts, "Tags: "+strings.Join(req.Tags, ", "))
			}
			for _, fact := range facts {
				fmt.Fprintf(&b, "- %s\n", fact)
			}
			b.WriteString("\n")
		}
	}

	adrs := []*ADR{}
	for _, repo := range w.Reported() {
		adrs = append(adrs, repo.ADRs...)
	}
	b.WriteString("## Architecture decisions\n\n")
	if len(adrs) == 0 {
		b.WriteString("None recorded.\n\n")
	} else {
		b.WriteString("| ADR | Title | Status | Date | Requirements | Supersedes | Superseded by |\n|---|---|---|---|---|---|---|\n")
		for _, adr := range adrs {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", adrLabel(w, adr), cell(adr.Title), adr.Status, adr.Date,
				cell(strings.Join(adr.Requirements, ", ")), cell(strings.Join(adr.Supersedes, ", ")), cell(strings.Join(adr.SupersededBy, ", ")))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Trace\n\n")
	b.WriteString("| ID | Status | Children | ADRs | Code | Tests | Evidence |\n|---|---|---|---|---|---|---|\n")
	for _, row := range matrix.Rows {
		code := []string{}
		for _, at := range row.Code {
			place := at.File
			if w.Opts.Workspace {
				place = at.Repo + "/" + place
			}
			code = append(code, fmt.Sprintf("%s:%d", place, at.Line))
		}
		tests := []string{}
		for _, t := range row.Tests {
			name := t.Test
			if name == "" {
				name = fmt.Sprintf("%s:%d", t.File, t.Line)
			}
			tests = append(tests, fmt.Sprintf("%s (%s)", name, t.Result))
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", row.ID, row.Status, cell(strings.Join(row.Children, ", ")), cell(strings.Join(row.ADRs, ", ")),
			cell(strings.Join(code, ", ")), cell(strings.Join(tests, ", ")), row.Evidence)
	}
	b.WriteString("\n## Gaps\n\n")
	if len(matrix.Gaps) == 0 {
		b.WriteString("None.\n")
	} else {
		for _, gap := range matrix.Gaps {
			marker := ""
			if gap.Blocking {
				marker = " (blocks a release)"
			}
			fmt.Fprintf(&b, "- **%s** %s%s\n", gap.Code, gap.Message, marker)
		}
	}
	return b.String()
}

func adrLabel(w *Workspace, adr *ADR) string {
	if w.Opts.Workspace {
		return adr.Ref()
	}
	return adr.ID
}

func anchor(id string) string {
	return strings.ToLower(id)
}

func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(text, "|", `\|`), "\n", " ")
}

