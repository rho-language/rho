/*  ffi.rho                                                                    */
/* -------------------------------------------------------------------------- */

// Rho renders the foreign interface.
func (i *Interface) Rho() string {
	var b strings.Builder
	fmt.Fprintf(&b, Generated, "ffi.rho")
	fmt.Fprintf(&b, "module %s\n\n", i.Module)
	b.WriteString("// The foreign interface of the C library this project links.\n")
	b.WriteString("//\n")
	b.WriteString("// Every declaration below came from a C header, and every one carries the C\n")
	b.WriteString("// symbol it calls. A declaration the reader could not map is reported by the\n")
	b.WriteString("// generator rather than guessed at here.\n\n")

	// The aliases first: a type declared later is still the same type, and a
	// reader arriving at a declaration wants the names it uses to be named.
	b.WriteString("/* -------------------------------------------------------------------------- */\n")
	b.WriteString("/*  Types                                                                    */\n")
	b.WriteString("/* -------------------------------------------------------------------------- */\n\n")
	for _, decl := range i.structs() {
		i.writeStruct(&b, decl)
	}
	for _, decl := range i.enums() {
		i.writeEnum(&b, decl)
	}

	b.WriteString("/* -------------------------------------------------------------------------- */\n")
	b.WriteString("/*  Functions                                                               */\n")
	b.WriteString("/* -------------------------------------------------------------------------- */\n\n")
	for _, decl := range i.functions() {
		i.writeFunction(&b, decl)
	}
	for _, shim := range i.Shims {
		i.writeShimDecl(&b, shim)
	}

	b.WriteString("/* -------------------------------------------------------------------------- */\n")
	b.WriteString("/*  Constants                                                               */\n")
	b.WriteString("/* -------------------------------------------------------------------------- */\n\n")
	for _, decl := range i.constants() {
		i.writeConst(&b, decl)
	}
	return b.String()
}

func (i *Interface) structs() []Decl   { return i.byKind(KindStruct) }
func (i *Interface) unions() []Decl    { return i.byKind(KindUnion) }
func (i *Interface) enums() []Decl     { return i.byKind(KindEnum) }
func (i *Interface) constants() []Decl { return i.byKind(KindConst) }

// byKind is the declarations of one kind, in the order they were read.
func (i *Interface) byKind(kind Kind) []Decl {
	out := []Decl{}
	for _, decl := range i.Header.Decls {
		if decl.Kind == kind {
			out = append(out, decl)
		}
	}
	return out
}

// functions is every function the headers declare, sorted by name: the set is an
// interface, and an interface reads better in one order than in the order of
// the files that happened to be read.
func (i *Interface) functions() []Decl {
	out := []Decl{}
	for _, decl := range i.Header.Decls {
		if decl.Kind == KindFunc {
			out = append(out, decl)
		}
	}
	sort.SliceStable(out, func(a, b int) bool { return out[a].Name < out[b].Name })
	return out
}

// writeStruct documents a structure rather than declaring it.
//
// The structure belongs to the C library, and a Rho struct with the same name
// would be a different type: the compiler would write it as a struct of its own
// (renamed, to keep out of the library's way) and a pointer the library hands
// over would be read through that layout instead of the library's. So the type
// is opaque in the interface, its members are written here where a reader can
// see them, and the layer above this one is what gives a handle its type.
func (i *Interface) writeStruct(b *strings.Builder, decl Decl) {
	if decl.Comment != "" {
		fmt.Fprintf(b, "// %s\n", decl.Comment)
	}
	fmt.Fprintf(b, "// %s: a C structure, and it is the library's. A Rho struct of the same\n", decl.Name)
	b.WriteString("// name would be a different type, so a pointer to it is opaque here and the\n")
	b.WriteString("// members below are what the library laid out.\n")
	for _, field := range decl.Fields {
		if field.Ptr {
			fmt.Fprintf(b, "//   %s(): a C function pointer, reached through the shim of the same name\n", field.Name)
			continue
		}
		// Rho rather than TryRho: a type that has no mapping is recorded, so the
		// generator reports the binding as incomplete instead of quietly writing
		// an opaque pointer.
		mapped := i.Mapper.Rho(field.Type)
		fmt.Fprintf(b, "//   %s: %s\n", field.Name, mapped)
	}
	b.WriteString("\n")
}

// writeEnum documents an enumeration rather than declaring one.
//
// A Rho enum is not a language declaration: the parser has no `enum`, and a
// generated file that does not compile is worse than one that is merely less
// convenient. So the members are written as what they are — the codes a C caller
// compares against — and the names belong to the idiomatic layer, which is where
// a program should be writing them.
func (i *Interface) writeEnum(b *strings.Builder, decl Decl) {
	if decl.Comment != "" {
		fmt.Fprintf(b, "// %s\n", decl.Comment)
	}
	fmt.Fprintf(b, "// %s: the codes a C caller compares against. Carried as the whole\n", decl.Name)
	b.WriteString("// number C uses, because a Rho enum is not a language declaration\n")
	b.WriteString("// yet; the names belong to the layer above this one.\n")
	for _, field := range decl.Fields {
		if field.Comment == "" || field.Comment == "0" {
			fmt.Fprintf(b, "//   %s\n", field.Name)
			continue
		}
		fmt.Fprintf(b, "//   %s = %s\n", field.Name, field.Comment)
	}
	b.WriteString("\n")
}

// writeFunction renders a function declaration as a foreign one.
// optionalReturn makes a returned pointer optional.
//
// Only a return. A pointer a caller passes is the caller's promise that it is
// there, and making that optional would move a check onto every call to say
// nothing a call to C could not already do. What the library hands back is
// different: it is the library saying "here, or nothing", and Rho has to be able
// to see the nothing.
func optionalReturn(rhoType string) string {
	if strings.HasPrefix(rhoType, "Ptr[") && strings.HasSuffix(rhoType, "]") {
		return "Option[" + rhoType + "]"
	}
	return rhoType
}

func (i *Interface) writeFunction(b *strings.Builder, decl Decl) {
	if decl.Comment != "" {
		fmt.Fprintf(b, "// %s\n", decl.Comment)
	}
	result := i.Mapper.Rho(decl.Result)
	if result == "Unit" {
		result = "void"
	}
	// A pointer the library returns may be null. C says so by convention and every
	// real library does it, so a returned pointer becomes `Option[Ptr[T]]`: a
	// pointer, with the absence being the null the library already returned. A
	// program that ignores the result can still hold it as a plain pointer,
	// because the two are the same representation.
	result = optionalReturn(result)
	fmt.Fprintf(b, "extern fn %s(%s) %s\n\n", decl.Name, i.params(decl.Params), result)
}

// writeShimDecl renders the declaration of a shim: a plain foreign function, so
// it is called exactly like one the header declared.
//
// The table the call goes through is the first parameter, because that is what
// the C shim takes. The idiomatic layer above is where the table is a field of
// a handle rather than an argument a caller passes.
func (i *Interface) writeShimDecl(b *strings.Builder, shim Shim) {
	fmt.Fprintf(b, "// %s.%s(): a call through a C function pointer, reached through generated C\n",
		shim.Owner, shim.Member)
	fmt.Fprintf(b, "// because Rho has no type for one.\n")
	result := i.Mapper.Rho(shim.Return)
	if result == "Unit" {
		result = "void"
	}
	// The table is the library's structure, so it is an opaque pointer here for
	// the same reason a parameter of that type is.
	params := append([]Param{{Name: "self", Type: shim.Owner}}, shim.Params...)
	fmt.Fprintf(b, "extern fn %s(%s) %s\n\n", shim.Name, i.params(params), result)
}

// writeConst renders a constant as a comment on its value, because a C constant
// is a compile-time value and a Rho binding cannot bind one to a foreign symbol:
// what it can do is say what the library was compiled with.
func (i *Interface) writeConst(b *strings.Builder, decl Decl) {
	fmt.Fprintf(b, "// %s = %s\n", decl.Name, decl.Value)
}

// params renders a C parameter list in Rho types.
func (i *Interface) params(params []Param) string {
	if len(params) == 0 {
		return ""
	}
	parts := make([]string, 0, len(params))
	for index, param := range params {
		name := param.Name
		if name == "" {
			name = fmt.Sprintf("arg%d", index)
		}
		parts = append(parts, name+": "+i.Mapper.Rho(param.Type))
	}
	return strings.Join(parts, ", ")
}

