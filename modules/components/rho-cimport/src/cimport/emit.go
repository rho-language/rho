//
// @file emit.go
// @brief Writing the two files a foreign interface needs.
//
// A binding from C to Rho is two files, and both exist because of something Rho
// cannot do on its own:
//
//	ffi.rho       the foreign interface: what the headers declare, in Rho's
//	              types, with the C symbol each declaration calls
//	ffi_shim.c/.h  the calls Rho cannot make. A C function pointer has no Rho
//	              type, so a HAL that is a table of function pointers is only
//	              reachable through C that forwards to the table
//
// The shim is not a convenience. A generator that emitted only the interface
// would produce a binding whose HAL could be looked at and not called, which is
// the most misleading thing a generator can do: it looks complete.
//
// Everything written is marked as generated. A file a generator writes is
// rewritten on the next run, so a hand edit in it is a hand edit that is lost —
// which is what Layer 3, the idiomatic API, is for.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: Apache-2.0
//

package cimport

import (
	"fmt"
	"sort"
	"strings"
)

// Generated is the banner every generated file carries.
const Generated = `//
// @file %s
// @brief GENERATED BY rho-cimport. DO NOT EDIT.
//
// Regenerate with:
//
//	rho cimport generate <project>
//
// The idiomatic API in src/lib.rho is the place to write code: this file is
// rewritten on every run, and anything written here is lost with it.
//
`

// Interface is a generated foreign interface: what the headers declare.
type Interface struct {
	// Module is the Rho module the interface is generated as.
	Module string
	// Header is what was read.
	Header Header
	// Mapper is the mapping that was used, which knows what it could not map.
	Mapper *TypeMapper
	// Shims are the C functions that forward to a function pointer the
	// interface declares, one per member.
	Shims []Shim
}

// Shim is a call Rho cannot make: a C function pointer reached through a
// structure member.
type Shim struct {
	// Name is the C name of the shim, named for what it reaches.
	Name string
	// Return is what the C function pointer returns.
	Return string
	// Params are the shim's own parameters: the structure, then the pointer's
	// own parameters with the self argument dropped, because the shim has
	// already been given the table.
	Params []Param
	// Member is the structure member the call goes through.
	Member string
	// Owner is the struct type the member belongs to.
	Owner string
	// PointerParams says which parameters are pointers, which the shim's
	// generated code needs to write correctly.
	PointerParams map[int]bool
}

