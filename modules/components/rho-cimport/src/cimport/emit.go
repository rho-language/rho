// ShimHeader renders the header the generated C is declared in, and
// ShimSource the C itself.
//
// The declared headers are what it includes, not the library: a library is a thing
// a build links, and a name is not a file. The build already puts the library's
// include directories on the compiler's path, so the headers are found by the
// names the header set uses.
func (i *Interface) ShimHeader(headers []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, Generated, "ffi_shim.h")
	b.WriteString("#pragma once\n\n")
	b.WriteString("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
	for _, header := range headers {
		fmt.Fprintf(&b, "#include <%s>\n", header)
	}
	b.WriteString("#include <stddef.h>\n\n")
	b.WriteString("/* Calls through a C function pointer, which Rho has no type for. Each one\n")
	b.WriteString(" * forwards to a member of the table it is given. */\n\n")
	for _, shim := range i.Shims {
		fmt.Fprintf(&b, "%s %s(", cType(shim.Return), shim.Name)
		parts := []string{fmt.Sprintf("%s* self", shim.Owner)}
		for _, param := range shim.Params {
			parts = append(parts, fmt.Sprintf("%s %s", cType(param.Type), param.Name))
		}
		b.WriteString(strings.Join(parts, ", ") + ");\n")
	}
	b.WriteString("\n#ifdef __cplusplus\n}\n#endif\n")
	return b.String()
}

// ShimSource renders the C that forwards to each function pointer.
func (i *Interface) ShimSource() string {
	var b strings.Builder
	fmt.Fprintf(&b, Generated, "ffi_shim.c")
	b.WriteString("#include \"ffi_shim.h\"\n\n")
	for _, shim := range i.Shims {
		// The self argument the pointer itself takes is not passed: the shim has
		// the table, and the table's member is called with it.
		fmt.Fprintf(&b, "%s %s(%s* self", cType(shim.Return), shim.Name, shim.Owner)
		for _, param := range shim.Params {
			fmt.Fprintf(&b, ", %s %s", cType(param.Type), param.Name)
		}
		b.WriteString(")\n{\n")
		call := []string{"self"}
		for _, param := range shim.Params {
			call = append(call, param.Name)
		}
		fmt.Fprintf(&b, "    return self->%s(%s);\n", shim.Member, strings.Join(call, ", "))
		b.WriteString("}\n\n")
	}
	return b.String()
}

// cType spells a C type back out, for the shim: it is C code, so it uses C.
//
// A single word is a type the header declares and is written as it stands; a
// qualified one — `unsigned int`, `const char*` — is already a C spelling and is
// left alone. Prefixing either with `struct` would produce `struct const char`,
// which is not a type.
func cType(name string) string {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return "void"
	}
	fields := strings.Fields(trimmed)
	if len(fields) == 1 && !strings.ContainsAny(trimmed, "*") {
		// One word: a tag the library declares (DeviceSPI) or a primitive.
		return trimmed
	}
	// More than one word, or a pointer: a qualified type, written as C writes it.
	qualified := strings.ReplaceAll(trimmed, "const char*", "const char*")
	qualified = strings.ReplaceAll(qualified, "unsigned ", "unsigned ")
	if len(fields) > 1 && !strings.HasSuffix(trimmed, "*") && !strings.Contains(trimmed, "*") {
		// A struct declared with a tag, spelled `struct Tag`.
		if !strings.HasPrefix(qualified, "struct ") {
			qualified = "struct " + qualified
		}
	}
	return qualified
}
