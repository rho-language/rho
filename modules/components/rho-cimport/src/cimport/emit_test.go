//
// @file emit_test.go
// @brief Tests for writing the two files a foreign interface needs.
//
// A binding is an interface file and a C shim, and the shim exists because Rho has
// no type for a C function pointer: a HAL that is a table of them can be looked at
// from a binding and not called without it. These tests are about what each file
// gets right and what it deliberately leaves out.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: MIT
//

package cimport

import (
	"strings"
	"testing"
)

// bindingFor reads a header and prepares the interface for it.
func bindingFor(t *testing.T, text string) *Interface {
	t.Helper()
	read := header(t, text)
	return &Interface{Module: "ffi", Header: read, Mapper: NewTypeMapper(read), Shims: collectShims(read)}
}

const halHeader = `typedef uint32_t rh_u32;

typedef struct RoboHubGPIO {
    rh_u32 pin;
    int32_t (*write)(struct RoboHubGPIO* self, rh_u32 pin, rh_u32 value);
} RoboHubGPIO;

int32_t robohub_gpio_write(RoboHubGPIO* port, rh_u32 pin, rh_u32 value);
`

func TestTheInterfaceIsMarkedGenerated(t *testing.T) {
	// A file a generator writes is rewritten on the next run, so it says so:
	// anything written here is lost, and the layer above is where code goes.
	rho := bindingFor(t, halHeader).Rho()
	if !strings.Contains(rho, "GENERATED BY rho-cimport") {
		t.Fatal("expected the interface to say it is generated")
	}
	if !strings.Contains(rho, "DO NOT EDIT") {
		t.Fatal("expected the interface to say not to edit it")
	}
	if !strings.Contains(rho, "module ffi") {
		t.Fatalf("expected the module declaration, got:\n%s", rho)
	}
}

func TestAStructureIsDocumentedRatherThanDeclared(t *testing.T) {
	// The structure is the library's. A Rho struct of the same name would be a
	// different type, and a pointer the library hands over would be read through it.
	rho := bindingFor(t, halHeader).Rho()
	if strings.Contains(rho, "struct RoboHubGPIO {") {
		t.Fatalf("expected no Rho struct for a C type, got:\n%s", rho)
	}
	if !strings.Contains(rho, "RoboHubGPIO: a C structure, and it is the library's") {
		t.Fatalf("expected the structure to be documented, got:\n%s", rho)
	}
	if !strings.Contains(rho, "pin: u32") {
		t.Fatalf("expected the members to be listed, got:\n%s", rho)
	}
}

func TestAFunctionBecomesAForeignDeclaration(t *testing.T) {
	rho := bindingFor(t, halHeader).Rho()
	if !strings.Contains(rho, "extern fn robohub_gpio_write(port: Ptr[RoboHubGPIO], pin: u32, value: u32) i32") {
		t.Fatalf("expected the declaration, got:\n%s", rho)
	}
}

func TestAFunctionPointerBecomesAShim(t *testing.T) {
	// Rho has no type for a function pointer, so the member is reached through
	// generated C: the declaration carries the table, which is what the C takes.
	binding := bindingFor(t, halHeader)
	if len(binding.Shims) != 1 {
		t.Fatalf("expected one shim, got %+v", binding.Shims)
	}
	shim := binding.Shims[0]
	if shim.Name != "rho_robohubgpio_write" || shim.Member != "write" || shim.Owner != "RoboHubGPIO" {
		t.Fatalf("unexpected shim: %+v", shim)
	}
	if len(shim.Params) != 2 {
		t.Fatalf("expected the call's own parameters, got %+v", shim.Params)
	}

	rho := binding.Rho()
	if !strings.Contains(rho, "extern fn rho_robohubgpio_write(self: Ptr[RoboHubGPIO], pin: u32, value: u32) i32") {
		t.Fatalf("expected the shim declaration, got:\n%s", rho)
	}
}

func TestTheCShimForwardsToTheTable(t *testing.T) {
	// The shim passes the table the call goes through and then the caller's own
	// arguments, in that order, because that is what the pointer takes.
	binding := bindingFor(t, halHeader)

	header := binding.ShimHeader([]string{"robohub/hal/gpio.h"})
	if !strings.Contains(header, "#include <robohub/hal/gpio.h>") {
		t.Fatalf("expected the declared header to be included, got:\n%s", header)
	}
	// The shim is declared under exactly the name it is called by. It is a C
	// function the header of this generated interface declares, so a call to it
	// carries that name; defining it under anything else is an undefined reference
	// at the link step.
	declared := "int32_t rho_robohubgpio_write(RoboHubGPIO* self, rh_u32 pin, rh_u32 value);"
	if !strings.Contains(header, declared) {
		t.Fatalf("expected %q, got:\n%s", declared, header)
	}

	source := binding.ShimSource()
	if !strings.Contains(source, "return self->write(self, pin, value);") {
		t.Fatalf("expected the call to go through the table, got:\n%s", source)
	}
}

func TestAnEnumerationIsWrittenAsTheCodesItNames(t *testing.T) {
	// The names belong to the layer above, which is where a program should write
	// them; a generated file that declared an enum would not compile.
	binding := bindingFor(t, `typedef enum {
    ROBOT_OK = 0,
    ROBOT_ERR_IO = -8
} RobotError;

int32_t robot_init(void);
`)
	rho := binding.Rho()
	if strings.Contains(rho, "enum RobotError {") {
		t.Fatalf("expected no Rho enum, got:\n%s", rho)
	}
	for _, want := range []string{"ROBOT_OK", "ROBOT_ERR_IO = -8"} {
		if !strings.Contains(rho, want) {
			t.Errorf("expected %s to be documented, got:\n%s", want, rho)
		}
	}
	// The signature carries the integer the enum is.
	if !strings.Contains(rho, "extern fn robot_init() i32") {
		t.Fatalf("expected the integer in the signature, got:\n%s", rho)
	}
}

func TestAConstantIsDocumentedWithItsValue(t *testing.T) {
	// A C constant is a compile-time value, and a Rho binding cannot bind one to a
	// foreign symbol: what it can do is say what the library was built with.
	binding := bindingFor(t, "#define ROBOT_MAX_NAME 32\n\nint32_t robot_init(void);\n")
	if !strings.Contains(binding.Rho(), "ROBOT_MAX_NAME = 32") {
		t.Fatalf("expected the constant and its value, got:\n%s", binding.Rho())
	}
}

func TestTheShimIsOnlyWrittenWhenThereIsSomethingToForward(t *testing.T) {
	// A header of ordinary functions needs no shim, and a file of comments is not
	// a file worth writing.
	binding := bindingFor(t, "int32_t robot_init(void);\n")
	if len(binding.Shims) != 0 {
		t.Fatalf("expected no shims, got %+v", binding.Shims)
	}
	if source := binding.ShimSource(); !strings.Contains(source, "GENERATED BY rho-cimport") || strings.Contains(source, "return self->") {
		t.Fatalf("expected an empty but valid shim, got:\n%s", source)
	}
}
