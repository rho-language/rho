//
// @file deps.go
// @brief The one file that tells CMake where everything is.
//
// A build that links C needs to know two things about each dependency: where
// its headers are, and what has to be defined for them to work. Both facts
// belong to the dependency. A consumer that works them out — by looking for a
// directory called `include`, or by matching the name a build file mentions in
// its error message — is reading a convention rather than a contract, and it
// stops being right the moment a dependency is laid out differently.
//
// So each dependency declares what it exports in its own manifest, and this
// writes those declarations out as CMake. The result is one file, generated
// from what the dependencies said, that a project includes once.
//
// It is generated rather than written by hand because it is a function of the
// dependencies, and a file that is a function of something else should not be
// able to drift from it.
//
// @project Rho
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: MIT
//

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"rho/src/deps"
)

// depsFileName is the generated file a project includes to consume its
// dependencies.
//
// It is one file rather than one per dependency because every consumer wants
// all of them, and a build that had to name each one would be a build where
// adding a dependency meant editing every project that uses it.
const depsFileName = "deps.cmake"

// exportedDependency is one dependency's contribution to the generated file.
type exportedDependency struct {
	// Name is the dependency's module name, which is also the name its target is
	// namespaced under.
	Name string
	// Root is where the dependency is checked out. Every declared path is
	// relative to it, which is what makes a declaration portable.
	Root string
	// Exports is what the dependency declared to a build system.
	Exports deps.CMakeExports
	// Defines are the compile definitions the dependency's own manifest declares,
	// which are as much a contract as its include directories: the vendor HAL's
	// umbrella header includes a driver's header only when that driver is enabled,
	// so a dependency that supports a driver has to say which ones.
	Defines []string
	// Version is what the dependency says it is, for a reader of the file.
	Version string
}

// writeDepsFiles writes the CMake that publishes every resolved dependency.
//
// It is two files, because a dependency's two jobs happen at two different points
// in a configure. The variables and the imported targets are needed before
// anything is configured; an alias is not, because an alias can only be made for
// a target that already exists — and the target a dependency that brings its own
// build defines does not exist until that build has been added.
func writeDepsFiles(projectRoot, destination string) error {
	if err := writeDepsFile(projectRoot, destination); err != nil {
		return err
	}
	return writeAliasFile(projectRoot, strings.TrimSuffix(destination, ".cmake")+"-aliases.cmake")
}

// writeAliasFile bridges each in-tree dependency's own target to the name its
// manifest exported.
//
// A dependency that brings its own build defines its own target —
// `robohub-common` — and its manifest exports a namespaced name for it, because
// two dependencies may both call their library by the same thing and a consumer
// should not have to care which is which. Those are two names for one thing, so
// something has to join them.
//
// An imported target is not the join: defining one would be ignored, because the
// dependency's own build defines the same target moments later, and the consumer
// would link an interface with the right include paths and no library behind it.
// An ALIAS is the join CMake offers for exactly this, and it has to come after
// the `add_subdirectory` that creates the target.
func writeAliasFile(projectRoot, destination string) error {
	var b strings.Builder
	b.WriteString("# Generated by rho-target. The bridges between what a dependency's own build\n")
	b.WriteString("# calls its target and what its manifest says to link it by.\n")
	b.WriteString("#\n")
	b.WriteString("# Included after the dependencies have been added, because an alias cannot be\n")
	b.WriteString("# made for a target that does not exist yet.\n\n")

	bridges := 0
	for _, dependency := range resolvedExports(projectRoot) {
		if dependency.Exports.Target == "" {
			continue
		}
		if _, err := os.Stat(filepath.Join(dependency.Root, "CMakeLists.txt")); err != nil {
			// Not built in-tree, so `deps.cmake` published it as an imported
			// target under this name already and there is nothing to bridge.
			continue
		}
		local := strings.TrimPrefix(dependency.Exports.Target, "rho::")
		if local == dependency.Exports.Target {
			// The manifest already names the local target; nothing to bridge.
			continue
		}
		b.WriteString("if(TARGET " + local + " AND NOT TARGET " + dependency.Exports.Target + ")\n")
		b.WriteString("  add_library(" + dependency.Exports.Target + " ALIAS " + local + ")\n")
		b.WriteString("endif()\n")
		bridges++
	}

	if bridges == 0 {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
		return err
	}
	return os.WriteFile(destination, []byte(b.String()), 0o644)
}

// writeDepsFile writes the CMake that publishes every resolved dependency.
//
// `projectRoot` is the project whose dependencies are read. It is the
// application's own manifest that names them, so nothing is inferred from the
// shape of a directory.
func writeDepsFile(projectRoot, destination string) error {
	dependencies := resolvedExports(projectRoot)

	var b strings.Builder
	b.WriteString("# Generated by rho-target from the manifests of this project's dependencies.\n")
	b.WriteString("#\n")
	b.WriteString("# Do not edit: it is written from what each dependency declared in its own\n")
	b.WriteString("# manifest, and anything written here is replaced on the next build.\n")
	b.WriteString("#\n")
	b.WriteString("# A project includes this once and links what it needs by target name.\n\n")

	if len(dependencies) == 0 {
		b.WriteString("# This project declares no C dependencies.\n")
		return os.MkdirAll(filepath.Dir(destination), 0o755)
	}

	// Sorted by name, because the file is generated and a generated file that
	// changes between two identical builds is one that cannot be diffed.
	sort.Slice(dependencies, func(i, j int) bool { return dependencies[i].Name < dependencies[j].Name })

	for _, dependency := range dependencies {
		fmt.Fprintf(&b, "# %s %s\n", dependency.Name, dependency.Version)
		fmt.Fprintf(&b, "# %s\n\n", dependency.Root)

		// A dependency that brings its own build definition defines its own
		// target, and a target cannot be defined twice. Declaring an imported one
		// here would be ignored, because the dependency's build defines the same
		// target moments later, and the consumer would link an interface with the
		// right include paths and no library behind it — which links to nothing
		// and reports every symbol from that library as undefined.
		//
		// The name its manifest exported is bridged to the target its own build
		// defines by `writeAliasFile`, after that build has been added.
		bringsOwnBuild := false
		if _, err := os.Stat(filepath.Join(dependency.Root, "CMakeLists.txt")); err == nil {
			bringsOwnBuild = true
		}

		// A dependency that builds itself compiles its own sources, and those
		// sources are compiled by a target this file does not own and cannot
		// attach definitions to. They are therefore added to the directory scope,
		// which covers every target configured after this point — including the
		// dependency's own, which is added after.
		//
		// The same set on an imported target would apply only to a consumer of
		// it, which is a different set: a driver a dependency compiles for itself
		// is a driver its consumers need too, and the directory is what says so
		// once rather than twice.
		if bringsOwnBuild && len(dependency.Defines) > 0 {
			b.WriteString("add_compile_definitions(\n")
			for _, define := range dependency.Defines {
				fmt.Fprintf(&b, "    %s\n", cmakeString(define))
			}
			b.WriteString(")\n")
		}

		if dependency.Exports.Target != "" && !bringsOwnBuild {
			// IMPORTED GLOBAL rather than a plain interface library: the
			// dependency is consumed from another directory, and a target that
			// is not global is not visible to the directory that links it.
			fmt.Fprintf(&b, "if(NOT TARGET %s)\n", dependency.Exports.Target)
			fmt.Fprintf(&b, "  add_library(%s INTERFACE IMPORTED GLOBAL)\n", dependency.Exports.Target)
			if dirs := resolveAll(dependency.Root, dependency.Exports.IncludeDirs); len(dirs) > 0 {
				b.WriteString("  target_include_directories(" + dependency.Exports.Target + " INTERFACE\n")
				for _, dir := range dirs {
					fmt.Fprintf(&b, "    %s\n", cmakeString(dir))
				}
				b.WriteString("  )\n")
			}
			if len(dependency.Exports.Defines) > 0 {
				b.WriteString("  target_compile_definitions(" + dependency.Exports.Target + " INTERFACE\n")
				for _, define := range dependency.Exports.Defines {
					fmt.Fprintf(&b, "    %s\n", cmakeString(define))
				}
				b.WriteString("  )\n")
			}
			if len(dependency.Exports.LinkLibraries) > 0 {
				fmt.Fprintf(&b, "  target_link_libraries(%s INTERFACE %s)\n",
					dependency.Exports.Target, strings.Join(dependency.Exports.LinkLibraries, " "))
			}
			b.WriteString("endif()\n\n")
		}

		// The bridge, for a build file that asks for a path by name. Declared
		// here by the dependency that owns the path, so a consumer does not have
		// to know the name and neither does the tool that writes this.
		// The variables are written whether the dependency brings its own build or
		// not: they are for a build file that asks for a path by name rather than
		// linking a target, and such a file may be any of them.
		for _, name := range sortedKeys(dependency.Exports.Vars) {
			value := strings.ReplaceAll(dependency.Exports.Vars[name], deps.PackageDirToken, filepath.ToSlash(dependency.Root))
			fmt.Fprintf(&b, "set(%s %s CACHE PATH %q FORCE)\n", name, cmakeString(value), name+" (declared by "+dependency.Name+")")
		}
		if len(dependency.Exports.Vars) > 0 {
			b.WriteString("\n")
		}
	}

	if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
		return err
	}
	return os.WriteFile(destination, []byte(b.String()), 0o644)
}

// resolvedExports reads what this project's dependencies export, and what those
// dependencies' dependencies export.
//
// The walk is transitive because a platform is usually not where its headers
// are: it declares the board and depends on the library that implements it, and
// a consumer of the platform needs that library's headers too.
func resolvedExports(projectRoot string) []exportedDependency {
	if projectRoot == "" {
		return nil
	}
	found := []exportedDependency{}
	seen := map[string]bool{}

	var walk func(base string, manifest *deps.Manifest, depth int)
	walk = func(base string, manifest *deps.Manifest, depth int) {
		if depth > 16 {
			return
		}
		for _, dep := range manifest.Deps {
			if dep.Type != deps.DepTypeC || dep.Path == "" {
				continue
			}
			root := dep.Path
			if !filepath.IsAbs(root) {
				root = filepath.Join(base, root)
			}
			child, err := deps.LoadManifest(deps.ManifestPath(root))
			if err != nil {
				continue
			}
			if (child.Exports != nil && child.Exports.Cmake != nil || len(child.BuildDefines) > 0) && !seen[child.ModuleName] {
				seen[child.ModuleName] = true
				found = append(found, exportedDependency{
					Name:    child.ModuleName,
					Root:    root,
					Exports: *child.Exports.Cmake,
					Defines: child.BuildDefines,
					Version: child.Version,
				})
			}
			walk(root, child, depth+1)
		}
	}

	if manifest, err := deps.LoadManifest(deps.ManifestPath(projectRoot)); err == nil && manifest != nil {
		walk(projectRoot, manifest, 0)
	}
	return found
}

// resolveAll resolves declared paths against the module that declared them.
func resolveAll(root string, declared []string) []string {
	out := make([]string, 0, len(declared))
	for _, one := range declared {
		if filepath.IsAbs(one) {
			out = append(out, filepath.ToSlash(one))
			continue
		}
		out = append(out, filepath.ToSlash(filepath.Join(root, one)))
	}
	return out
}

func sortedKeys(values map[string]string) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

// cmakeString writes a value as a CMake string literal.
func cmakeString(value string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `"`, `\"`)
	return `"` + replacer.Replace(value) + `"`
}
