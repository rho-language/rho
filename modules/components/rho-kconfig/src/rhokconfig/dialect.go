//
// @file dialect.go
// @brief Writing a configuration in the dialects the tools read.
//
// The same symbols are spelled differently by the tools that read them, and a
// project is built by one of those tools. So a dialect is a writer: it takes a
// resolved configuration and writes the files that tool expects. Three are here
// because three toolchains read a configuration on the platforms Rho targets:
//
//	linux     .config and include/generated/autoconf.h, as the kernel and its
//	          out-of-tree drivers read them
//	espidf    sdkconfig and sdkconfig.h, as the ESP-IDF build reads them
//	freertos  FreeRTOSConfig.h, as a project configures the kernel it runs on
//
// A dialect writes files, not text, because where they go is part of what a
// toolchain expects: autoconf.h belongs under include/generated, and a build
// includes it by that path.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: MIT
//

package rhokconfig

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// File is one written file: where it goes relative to the project, and what is
// in it.
type File struct {
	// Path is the file's path relative to the project root.
	Path string
	// Content is the file.
	Content string
}

// Dialect writes a resolved configuration in the form a toolchain reads.
type Dialect interface {
	// Name is the dialect, as a project names it in its manifest.
	Name() string
	// Files renders the configuration. Nothing is written: a caller decides
	// where the files go, and a build can read them before it writes them.
	Files(configuration Configuration) []File
}

// dialectByName is the dialect a project asked for.
func dialectByName(name string) (Dialect, error) {
	switch name {
	case "", "linux", "kernel":
		return linuxDialect{}, nil
	case "espidf", "esp-idf", "esp32":
		return espIDFDialect{}, nil
	case "freertos", "free-rtos":
		return freeRTOSDialect{}, nil
	}
	return nil, fmt.Errorf("unknown dialect %q; this bridge writes linux, espidf and freertos", name)
}

// DialectNames are the dialects that can be asked for.
func DialectNames() []string { return []string{"linux", "espidf", "freertos"} }

/* -------------------------------------------------------------------------- */
/*  Shared writing                                                            */
/* -------------------------------------------------------------------------- */

// set is the boolean a dialect writes for a symbol. The Linux-style dialects
// write y and n; a C header writes 1 and 0.
func set(config Configuration, name string) bool {
	value, known := config.Get(name)
	if !known {
		return false
	}
	return value.Bool()
}

// macroName is a symbol as a C macro: a name is spelled the same way in a
// header as in a .config, so the only thing to decide is whether a symbol that
// is off is defined as 0 or not defined at all. Every dialect here defines it,
// because `#if CONFIG_X == 0` is the spelling a hand-written driver expects and
// one that silently omits it fails to compile rather than failing visibly.
func macroName(name string) string { return name }

// define renders one macro, with a comment saying where the value came from.
//
// The value is written as a C constant rather than as a config value: a flag is
// 1 or 0 here, and y or n is what the .config says. A driver asks
// `#if CONFIG_SPI_MASTER`, and a header that defined it to y would not compile.
func define(config Configuration, value Value, banner string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "/* %s: %s = %s (from %s) */\n", banner, value.Name, value.Value, value.From)
	fmt.Fprintf(&b, "#define %s %s\n", macroName(value.Name), headerValue(value))
	return b.String()
}

// headerBanner is the top of a generated header.
//
// Everything that is not a directive or an include is inside the comment: a
// stray word outside it reaches the preprocessor, and a header that does not
// compile is a header nothing can use.
func headerBanner(component string, what string) string {
	return fmt.Sprintf("/* Generated by %s. Do not edit: this is written from the Kconfig\n"+
		" * bridge, and the values in it come from the fragments a project declared.\n *\n"+
		" * %s\n */\n"+
		"#pragma once\n\n#ifndef __cplusplus\n#include <stdbool.h>\n#include <stdint.h>\n#endif\n\n",
		component, what)
}

// configurationValue is a symbol as a dialect writes a value: y or n for a flag,
// digits for a number, the text itself for a string.
func configurationValue(value Value) string {
	if value.Type == TypeBool {
		if value.Bool() {
			return "y"
		}
		return "n"
	}
	if value.Value == "" {
		return ""
	}
	return value.Value
}

// headerValue is a symbol as a C macro: 1 or 0 for a flag, a cast for a
// number, the text quoted for a string.
func headerValue(value Value) string {
	switch value.Type {
	case TypeBool:
		if value.Bool() {
			return "1"
		}
		return "0"
	case TypeInt, TypeHex:
		if value.Value == "" {
			return "0"
		}
		return value.Value
	case TypeString:
		if value.Value == "" {
			return "\"\""
		}
		return "\"" + strings.ReplaceAll(value.Value, "\"", "\\\"") + "\""
	}
	return value.Value
}

/* -------------------------------------------------------------------------- */
/*  linux: .config and autoconf.h                                             */
/* -------------------------------------------------------------------------- */

// linuxDialect writes the Linux-style pair: the .config a kernel build reads and
// the header a driver includes.
type linuxDialect struct{}

func (linuxDialect) Name() string { return "linux" }

func (linuxDialect) Files(configuration Configuration) []File {
	return []File{
		{Path: ".config", Content: linuxConfig(configuration)},
		{Path: filepath.Join("include", "generated", "autoconf.h"), Content: linuxHeader(configuration)},
	}
}

// linuxConfig renders the .config: the symbols a kernel build reads, in the order
// a person reads them, with a line per symbol.
func linuxConfig(configuration Configuration) string {
	var b strings.Builder
	b.WriteString("#\n# Automatically generated file; DO NOT EDIT.\n")
	b.WriteString("# Rho Kconfig bridge: the values a project declared.\n#\n\n")
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		fmt.Fprintf(&b, "%s=%s\n", name, configurationValue(value))
	}
	return b.String()
}

// linuxHeader renders autoconf.h, which is the header an out-of-tree driver
// includes to ask what a build was configured with.
func linuxHeader(configuration Configuration) string {
	var b strings.Builder
	b.WriteString(headerBanner("rho-kconfig", "Generated configuration."))
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		if value.Value == "" {
			continue
		}
		b.WriteString(define(configuration, value, "configuration"))
	}
	return b.String()
}

