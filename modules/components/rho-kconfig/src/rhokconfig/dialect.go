// espIDFDialect writes the ESP-IDF pair. The .h is the one an ESP-IDF component
// includes, and the spelling of a symbol there is the same as in the .config:
// `CONFIG_FOO=y` becomes `#define CONFIG_FOO 1`.
type espIDFDialect struct{}

func (espIDFDialect) Name() string { return "espidf" }

func (espIDFDialect) Files(configuration Configuration) []File {
	return []File{
		{Path: "sdkconfig", Content: espIDFConfig(configuration)},
		{Path: filepath.Join("build", "config", "sdkconfig.h"), Content: espIDFHeader(configuration)},
	}
}

func espIDFConfig(configuration Configuration) string {
	var b strings.Builder
	b.WriteString("#\n# Automatically generated file; DO NOT EDIT.\n")
	b.WriteString("# Rho Kconfig bridge, in the ESP-IDF form.\n#\n\n")
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		fmt.Fprintf(&b, "%s=%s\n", name, configurationValue(value))
	}
	return b.String()
}

func espIDFHeader(configuration Configuration) string {
	var b strings.Builder
	b.WriteString(headerBanner("rho-kconfig", "Generated ESP-IDF configuration."))
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		if value.Value == "" {
			continue
		}
		b.WriteString(define(configuration, value, "configuration"))
	}
	return b.String()
}

/* -------------------------------------------------------------------------- */
/*  freertos: FreeRTOSConfig.h                                               */
/* -------------------------------------------------------------------------- */

// freeRTOSDialect writes the one file a FreeRTOS project configures the kernel
// with. FreeRTOS has no .config: its symbols are macros, and a project sets
// them by writing a header. The symbols are usually written without the CONFIG_
// prefix here, so they are written both ways and a FreeRTOSConfig.h written by
// hand stays compatible.
type freeRTOSDialect struct{}

func (freeRTOSDialect) Name() string { return "freertos" }

func (freeRTOSDialect) Files(configuration Configuration) []File {
	return []File{
		{Path: "FreeRTOSConfig.h", Content: freeRTOSHeader(configuration)},
		{Path: ".config", Content: freeRTOSConfig(configuration)},
	}
}

// freeRTOSName is a symbol as FreeRTOS spells it: the name without the CONFIG_
// prefix, which is how FreeRTOSConfig.h is written by hand.
func freeRTOSName(name string) string {
	return strings.TrimPrefix(name, "CONFIG_")
}

func freeRTOSHeader(configuration Configuration) string {
	var b strings.Builder
	b.WriteString(headerBanner("rho-kconfig", "Generated FreeRTOS configuration."))
	// A symbol that is not set is not written: FreeRTOSConfig.h is a list of
	// defines, and a define of 0 is a different statement from no define.
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		if value.Value == "" || (value.Type == TypeBool && !value.Bool()) {
			continue
		}
		fmt.Fprintf(&b, "/* %s: %s = %s (from %s) */\n", "configuration", value.Name, value.Value, value.From)
		fmt.Fprintf(&b, "#define %s %s\n", freeRTOSName(value.Name), headerValue(value))
	}
	return b.String()
}

// freeRTOSConfig renders the .config, which is the record of what the header was
// generated from and what a Rho project's own tooling reads back.
func freeRTOSConfig(configuration Configuration) string {
	var b strings.Builder
	b.WriteString("#\n# Automatically generated file; DO NOT EDIT.\n")
	b.WriteString("# Rho Kconfig bridge, in the FreeRTOS form.\n#\n\n")
	for _, name := range configuration.Names() {
		value, _ := configuration.Get(name)
		fmt.Fprintf(&b, "%s=%s\n", name, configurationValue(value))
	}
	return b.String()
}

