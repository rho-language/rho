/*  Writing                                                                   */
/* -------------------------------------------------------------------------- */

// Write writes the files a dialect produced under a project root.
//
// A file that is already there is kept unless the caller is writing over it,
// which is what a build does: everything this writes is a generated file, and
// the values in it come from the project rather than from the file itself. What
// a person writes belongs in the project, not in what the project generates.
func Write(root string, files []File, overwrite bool) ([]string, []Diagnostic) {
	written := []string{}
	diagnostics := []Diagnostic{}
	for _, file := range files {
		path := filepath.Join(root, filepath.FromSlash(file.Path))
		if _, err := os.Stat(path); err == nil && !overwrite {
			// Keeping a file is not a problem with the configuration, so it is
			// reported as a note rather than a diagnostic: a build that resolved
			// everything it was asked to is not a build that failed.
			diagnostics = append(diagnostics, Diagnostic{
				Path:     file.Path,
				severity: severityNote,
				Message:  "a file is already there and was kept; --force writes over it",
			})
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			diagnostics = append(diagnostics, Diagnostic{Path: file.Path, Message: err.Error()})
			continue
		}
		if err := os.WriteFile(path, []byte(file.Content), 0o644); err != nil {
			diagnostics = append(diagnostics, Diagnostic{Path: file.Path, Message: err.Error()})
			continue
		}
		written = append(written, file.Path)
	}
	sort.Strings(written)
	return written, diagnostics
}
