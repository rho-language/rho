// The mqtt port: publish to an MQTT broker and follow topics on it.
//
// A project of this platform asks for it by name (`ports: [mqtt]`) and reaches it
// as mqtt_publish, mqtt_follow, mqtt_latest and mqtt_topics. It speaks MQTT 3.1.1
// with the standard library — connect, publish at QoS 0 or 1, subscribe, ping —
// because a generated project takes no Go dependency of its own. A broker is
// `host:port`; a broker user's password is read from a file, so it is never on a
// command line or in a manifest.
//
// Following a topic filter holds one connection in the background, reconnects
// when it drops, and keeps the newest message of every topic it hears, which is
// what a page or a poll asks for: what a device last said. Each message can also
// be appended to a file as a JSON line, for a Server-Sent Events stream.
//
// Two more carry a file of lines across the broker unchanged: mqtt_relay
// publishes every line appended to a file to one topic, and mqtt_follow_lines
// appends every payload heard on a filter to a file as it came. Mesh relays its
// live telemetry feed that way, and an application's gateway provider follows
// it into the same file the HTTP stream would have written.
package main

import (
	"bufio"
	"encoding/binary"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net"
	"os"
	"sort"
	"strings"
	"sync"
	"time"
)

// Generated by the mqtt port.

const (
	mqttKeepAlive   = 30 * time.Second
	mqttDialTimeout = 5 * time.Second
	mqttEventsLimit = 1 << 20
)

// mqttMessage is the newest message on one topic.
type mqttMessage struct {
	payload string
	at      time.Time
}

var (
	mqttMu        sync.Mutex
	mqttSeen      = map[string]mqttMessage{}
	mqttFollowing = map[string]bool{}
	mqttPublisher = map[string]*mqttConn{}
)

// mqttConn is one connection to a broker.
type mqttConn struct {
	mu     sync.Mutex
	conn   net.Conn
	reader *bufio.Reader
	nextID uint16
}

func mqttPassword(file string) string {
	if file == "" {
		return ""
	}
	raw, err := os.ReadFile(file)
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(raw))
}

// mqttString is a length-prefixed UTF-8 string.
func mqttString(value string) []byte {
	out := make([]byte, 2+len(value))
	binary.BigEndian.PutUint16(out, uint16(len(value)))
	copy(out[2:], value)
	return out
}

// mqttLength is the remaining-length field of a fixed header.
func mqttLength(n int) []byte {
	out := []byte{}
	for {
		b := byte(n % 128)
		n /= 128
		if n > 0 {
			b |= 0x80
		}
		out = append(out, b)
		if n == 0 {
			return out
		}
	}
}

func mqttPacket(kind byte, body []byte) []byte {
	return append(append([]byte{kind}, mqttLength(len(body))...), body...)
}

// mqttRead reads one packet: its type byte and its body.
func mqttRead(r *bufio.Reader) (byte, []byte, error) {
	kind, err := r.ReadByte()
	if err != nil {
		return 0, nil, err
	}
	length, multiplier := 0, 1
	for i := 0; i < 4; i++ {
		b, err := r.ReadByte()
		if err != nil {
			return 0, nil, err
		}
		length += int(b&0x7f) * multiplier
		if b&0x80 == 0 {
			break
		}
		multiplier *= 128
	}
	if length > 1<<20 {
		return 0, nil, errors.New("mqtt: a packet larger than a megabyte")
	}
	body := make([]byte, length)
	if _, err := io.ReadFull(r, body); err != nil {
		return 0, nil, err
	}
	return kind, body, nil
}

// mqttDial connects and signs in, as a clean session.
func mqttDial(broker string, clientID string, user string, password string) (*mqttConn, error) {
	conn, err := net.DialTimeout("tcp", broker, mqttDialTimeout)
	if err != nil {
		return nil, err
	}
	flags := byte(0x02)
	payload := mqttString(clientID)
	if user != "" {
		flags |= 0x80
		payload = append(payload, mqttString(user)...)
		if password != "" {
			flags |= 0x40
		}
	}
	if user != "" && password != "" {
		payload = append(payload, mqttString(password)...)
	}
	body := append(mqttString("MQTT"), 4, flags)
	keep := make([]byte, 2)
	binary.BigEndian.PutUint16(keep, uint16(mqttKeepAlive/time.Second))
	body = append(append(body, keep...), payload...)
	conn.SetDeadline(time.Now().Add(mqttDialTimeout))
	if _, err := conn.Write(mqttPacket(0x10, body)); err != nil {
		conn.Close()
		return nil, err
	}
	reader := bufio.NewReader(conn)
	kind, ack, err := mqttRead(reader)
	if err != nil {
		conn.Close()
		return nil, err
	}
	if kind>>4 != 2 || len(ack) < 2 {
		conn.Close()
		return nil, errors.New("mqtt: the broker answered something other than CONNACK")
	}
	if ack[1] != 0 {
		conn.Close()
		return nil, fmt.Errorf("mqtt: the broker refused the connection (code %d)", ack[1])
	}
	conn.SetDeadline(time.Time{})
	return &mqttConn{conn: conn, reader: reader, nextID: 1}, nil
}

func (c *mqttConn) id() uint16 {
	c.nextID++
	if c.nextID == 0 {
		c.nextID = 1
	}
	return c.nextID
}

// publish sends one message; at QoS 1 it waits for the broker's PUBACK.
func (c *mqttConn) publish(topic string, payload string, qos byte, retain bool) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	kind := byte(0x30) | qos<<1
	if retain {
		kind |= 0x01
	}
	body := mqttString(topic)
	var id uint16
	if qos > 0 {
		id = c.id()
		body = append(body, byte(id>>8), byte(id))
	}
	body = append(body, payload...)
	c.conn.SetDeadline(time.Now().Add(mqttDialTimeout))
	defer c.conn.SetDeadline(time.Time{})
	if _, err := c.conn.Write(mqttPacket(kind, body)); err != nil {
		return err
	}
	if qos == 0 {
		return nil
	}
	for {
		got, ack, err := mqttRead(c.reader)
		if err != nil {
			return err
		}
		if got>>4 == 4 && len(ack) >= 2 && binary.BigEndian.Uint16(ack) == id {
			return nil
		}
	}
}

func (c *mqttConn) close() {
	c.conn.Write([]byte{0xe0, 0})
	c.conn.Close()
}

// mqttPublish sends one message to a broker and answers whether the broker took
// it. The connection is kept for the next message and made again when it broke.
func mqttPublish(broker string, user string, passwordFile string, topic string, payload string, qos uint32, retain bool) bool {
	if broker == "" || topic == "" || strings.ContainsAny(topic, "#+") {
		return false
	}
	key := broker + "|" + user
	level := byte(0)
	if qos > 0 {
		level = 1
	}
	for attempt := 0; attempt < 2; attempt++ {
		mqttMu.Lock()
		conn := mqttPublisher[key]
		mqttMu.Unlock()
		if conn == nil {
			fresh, err := mqttDial(broker, mqttClientID(user, "pub"), user, mqttPassword(passwordFile))
			if err != nil {
				return false
			}
			conn = fresh
			mqttMu.Lock()
			mqttPublisher[key] = conn
			mqttMu.Unlock()
		}
		if err := conn.publish(topic, payload, level, retain); err == nil {
			return true
		}
		conn.close()
		mqttMu.Lock()
		delete(mqttPublisher, key)
		mqttMu.Unlock()
	}
	return false
}

// mqttClientID is a client id the broker has not seen from another process:
// two connections with one id push each other off.
func mqttClientID(user string, role string) string {
	host, _ := os.Hostname()
	name := user
	if name == "" {
		name = "rho"
	}
	return fmt.Sprintf("%s-%s-%d-%s", name, role, os.Getpid(), host)
}

// mqttFollow follows a topic filter on a broker in the background, once per
// broker, user and filter, and answers whether it is followed. Every message
// becomes the newest of its topic, and — when eventsPath is set — a JSON line in
// that file.
func mqttFollow(broker string, user string, passwordFile string, filter string, eventsPath string) bool {
	return mqttFollowAs(broker, user, passwordFile, filter, eventsPath, false)
}

// mqttFollowLines follows a filter like mqttFollow, and appends each payload to
// linesPath as it came, one per line: the file a publisher's lines were in.
func mqttFollowLines(broker string, user string, passwordFile string, filter string, linesPath string) bool {
	if linesPath == "" {
		return false
	}
	return mqttFollowAs(broker, user, passwordFile, filter, linesPath, true)
}

func mqttFollowAs(broker string, user string, passwordFile string, filter string, eventsPath string, raw bool) bool {
	if broker == "" || filter == "" {
		return false
	}
	key := broker + "|" + user + "|" + filter + "|" + eventsPath
	mqttMu.Lock()
	if mqttFollowing[key] {
		mqttMu.Unlock()
		return true
	}
	mqttFollowing[key] = true
	mqttMu.Unlock()
	go mqttFollowLoop(broker, user, passwordFile, filter, eventsPath, raw)
	return true
}

func mqttFollowLoop(broker string, user string, passwordFile string, filter string, eventsPath string, raw bool) {
	wait := time.Second
	for {
		if mqttFollowOnce(broker, user, passwordFile, filter, eventsPath, raw) {
			wait = time.Second
		}
		time.Sleep(wait)
		if wait < 30*time.Second {
			wait *= 2
		}
	}
}

// mqttFollowOnce holds one subscription until it drops, and reports whether it
// got as far as being subscribed.
func mqttFollowOnce(broker string, user string, passwordFile string, filter string, eventsPath string, raw bool) bool {
	conn, err := mqttDial(broker, mqttClientID(user, "sub"), user, mqttPassword(passwordFile))
	if err != nil {
		return false
	}
	defer conn.conn.Close()
	id := conn.id()
	body := append([]byte{byte(id >> 8), byte(id)}, mqttString(filter)...)
	body = append(body, 0)
	if _, err := conn.conn.Write(mqttPacket(0x82, body)); err != nil {
		return false
	}
	subscribed := false
	pings := time.NewTicker(mqttKeepAlive / 2)
	defer pings.Stop()
	stop := make(chan struct{})
	defer close(stop)
	go func() {
		for {
			select {
			case <-stop:
				return
			case <-pings.C:
				conn.mu.Lock()
				conn.conn.Write([]byte{0xc0, 0})
				conn.mu.Unlock()
			}
		}
	}()
	for {
		conn.conn.SetReadDeadline(time.Now().Add(mqttKeepAlive * 2))
		kind, packet, err := mqttRead(conn.reader)
		if err != nil {
			return subscribed
		}
		switch kind >> 4 {
		case 9:
			subscribed = len(packet) >= 3 && packet[2] != 0x80
			if !subscribed {
				return false
			}
		case 3:
			mqttReceive(conn, kind, packet, eventsPath, raw)
		}
	}
}

// mqttReceive keeps a message and acknowledges it when it asks to be.
func mqttReceive(conn *mqttConn, kind byte, packet []byte, eventsPath string, raw bool) {
	if len(packet) < 2 {
		return
	}
	length := int(binary.BigEndian.Uint16(packet))
	if len(packet) < 2+length {
		return
	}
	topic := string(packet[2 : 2+length])
	rest := packet[2+length:]
	qos := (kind >> 1) & 0x03
	if qos > 0 {
		if len(rest) < 2 {
			return
		}
		conn.mu.Lock()
		conn.conn.Write([]byte{0x40, 2, rest[0], rest[1]})
		conn.mu.Unlock()
		rest = rest[2:]
	}
	payload := string(rest)
	now := time.Now()
	mqttMu.Lock()
	mqttSeen[topic] = mqttMessage{payload: payload, at: now}
	mqttMu.Unlock()
	if eventsPath != "" {
		line, _ := json.Marshal(map[string]any{"topic": topic, "payload": payload, "at": now.Unix()})
		if raw {
			line = []byte(strings.TrimRight(payload, "\r\n"))
		}
		if info, err := os.Stat(eventsPath); err == nil && info.Size() > mqttEventsLimit {
			os.WriteFile(eventsPath, nil, 0o600)
		}
		if f, err := os.OpenFile(eventsPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600); err == nil {
			f.Write(append(line, '\n'))
			f.Close()
		}
	}
}

// mqttRelay publishes every line appended to linesPath to topic, at QoS 0, from
// a goroutine that holds its place in the file; it starts once per file and
// topic and answers whether it runs. Lines already in the file are not sent. A
// file that shrank was truncated by its writer, and is read again from the top.
func mqttRelay(broker string, user string, passwordFile string, linesPath string, topic string) bool {
	if broker == "" || linesPath == "" || topic == "" || strings.ContainsAny(topic, "#+") {
		return false
	}
	key := "relay|" + broker + "|" + user + "|" + linesPath + "|" + topic
	mqttMu.Lock()
	if mqttFollowing[key] {
		mqttMu.Unlock()
		return true
	}
	mqttFollowing[key] = true
	mqttMu.Unlock()
	var offset int64
	if info, err := os.Stat(linesPath); err == nil {
		offset = info.Size()
	}
	go func() {
		pending := ""
		for {
			time.Sleep(250 * time.Millisecond)
			info, err := os.Stat(linesPath)
			if err != nil {
				continue
			}
			if info.Size() < offset {
				offset, pending = 0, ""
			}
			if info.Size() == offset {
				continue
			}
			f, err := os.Open(linesPath)
			if err != nil {
				continue
			}
			f.Seek(offset, io.SeekStart)
			chunk, _ := io.ReadAll(io.LimitReader(f, mqttEventsLimit))
			f.Close()
			offset += int64(len(chunk))
			text := pending + string(chunk)
			end := strings.LastIndex(text, "\n")
			if end < 0 {
				pending = text
				continue
			}
			pending = text[end+1:]
			for _, line := range strings.Split(text[:end], "\n") {
				if strings.TrimSpace(line) != "" {
					mqttPublish(broker, user, passwordFile, topic, line, 0, false)
				}
			}
		}
	}()
	return true
}

// mqttLatest is the newest payload heard on a topic, or "".
func mqttLatest(topic string) string {
	mqttMu.Lock()
	defer mqttMu.Unlock()
	return mqttSeen[topic].payload
}

// mqttTopics is every topic heard under a prefix, newest first, one per line:
// topic, seconds since, payload (tabs and line breaks in it written as spaces).
func mqttTopics(prefix string) string {
	mqttMu.Lock()
	type row struct {
		topic string
		msg   mqttMessage
	}
	rows := []row{}
	for topic, msg := range mqttSeen {
		if strings.HasPrefix(topic, prefix) {
			rows = append(rows, row{topic, msg})
		}
	}
	mqttMu.Unlock()
	sort.Slice(rows, func(i, j int) bool { return rows[i].msg.at.After(rows[j].msg.at) })
	clean := strings.NewReplacer("\t", " ", "\n", " ", "\r", " ")
	var b strings.Builder
	for _, r := range rows {
		fmt.Fprintf(&b, "%s\t%d\t%s\n", r.topic, int(time.Since(r.msg.at).Seconds()), clean.Replace(r.msg.payload))
	}
	return b.String()
}

// The bus provider (robohub-provider-mqtt, module robohub.bus_mqtt) declares these
// functions, and a port defines a foreign function under the name qualified by the
// module that declared it as well as under its own: an application that includes
// the declaration calls the one, and one that imports the provider the other.

func robohubBusMqttMqttPublish(broker string, user string, passwordFile string, topic string, payload string, qos uint32, retain bool) bool {
	return mqttPublish(broker, user, passwordFile, topic, payload, qos, retain)
}

func robohubBusMqttMqttFollow(broker string, user string, passwordFile string, filter string, eventsPath string) bool {
	return mqttFollow(broker, user, passwordFile, filter, eventsPath)
}

func robohubBusMqttMqttLatest(topic string) string {
	return mqttLatest(topic)
}

func robohubBusMqttMqttTopics(prefix string) string {
	return mqttTopics(prefix)
}

func robohubBusMqttMqttRelay(broker string, user string, passwordFile string, linesPath string, topic string) bool {
	return mqttRelay(broker, user, passwordFile, linesPath, topic)
}

func robohubBusMqttMqttFollowLines(broker string, user string, passwordFile string, filter string, linesPath string) bool {
	return mqttFollowLines(broker, user, passwordFile, filter, linesPath)
}

// The Mesh gateway provider (robohub-provider-mesh, module robohub.gateway_mesh)
// follows Mesh's relayed feed itself, when the installation has a broker.

func robohubGatewayMeshMqttFollowLines(broker string, user string, passwordFile string, filter string, linesPath string) bool {
	return mqttFollowLines(broker, user, passwordFile, filter, linesPath)
}
