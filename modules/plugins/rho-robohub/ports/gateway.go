// The gateway port: serial, UDP, time, shared state and tx correlation.
//
// A Rho program has no heap, no globals and no I/O. A gateway that reads a
// serial link, streams over UDP and answers HTTP needs all three, and the parts
// it cannot express are exactly the parts only a host can do: open a tty, write
// a datagram, read a clock, and hold the little state two goroutines share.
//
// This port supplies those and nothing else. The frame grammar stays in the Rho
// program that asked for the port. Configuration is the environment, because it
// is deployment that changes it: SERIAL_PORT, SERIAL_BAUD, PLOTJUGGLER_ADDR,
// REST_PORT, GATEWAY_MODE and GATEWAY_AREA.
//
// A project of this platform asks for it by name (`ports: [gateway]`).
package main

