// telemetryFaultNew returns the faults newer than one id as tab-separated lines.
func telemetryFaultNew(project string, afterID uint32, limit uint32) string {
	if !telemetryOpen("") {
		return ""
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return ""
	}
	if limit == 0 {
		limit = 100
	}
	rows, err := handle.Query(
		"SELECT id, severity, created_ms, message FROM telemetry_fault "+
			"WHERE project = ? AND id > ? ORDER BY id ASC LIMIT ?", project, int64(afterID), int64(limit))
	if err != nil {
		return ""
	}
	var rowsAny any = rows
	typed, ok := rowsAny.(interface {
		Next() bool
		Scan(...any) error
		Close() error
	})
	if !ok {
		return ""
	}
	defer typed.Close()
	var out strings.Builder
	for typed.Next() {
		var id, created int64
		var severity, message string
		if err := typed.Scan(&id, &severity, &created, &message); err != nil {
			continue
		}
		out.WriteString(strconv.FormatInt(id, 10))
		out.WriteString("\t")
		out.WriteString(severity)
		out.WriteString("\t")
		out.WriteString(strconv.FormatInt(created, 10))
		out.WriteString("\t")
		out.WriteString(strings.ReplaceAll(message, "\t", " "))
		out.WriteString("\n")
	}
	return out.String()
}

// telemetryFaultClear removes one acknowledged fault.
func telemetryFaultClear(project string, id uint32) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	result, err := handle.Exec("DELETE FROM telemetry_fault WHERE project = ? AND id = ?", project, int64(id))
	if err != nil {
		return telemetryError("the fault could not be cleared")
	}
	removed, _ := result.RowsAffected()
	return telemetryJSON(map[string]any{"ok": true, "removed": removed})
}

// telemetryFaultPrune keeps actionable faults for the configured window.
func telemetryFaultPrune(project string, days uint32) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	if days == 0 {
		days = 365
	}
	before := time.Now().Add(-time.Duration(days) * 24 * time.Hour).UnixMilli()
	result, err := handle.Exec("DELETE FROM telemetry_fault WHERE project = ? AND created_ms < ?", project, before)
	if err != nil {
		return telemetryError("the fault retention pass failed")
	}
	removed, _ := result.RowsAffected()
	_ = telemetryCheckpoint("PASSIVE")
	return telemetryJSON(map[string]any{"ok": true, "removed": removed, "before_ms": before})
}

// telemetrySleep waits between polls without asking Rho for a clock.
func telemetrySleep(milliseconds uint32) {
	time.Sleep(time.Duration(milliseconds) * time.Millisecond)
}

// telemetryEventLimit is the size a project's live feed is allowed to reach
// before it starts again. A reader follows it by offset and starts over when it
// shrinks; the store, not the feed, is what keeps history.
const telemetryEventLimit = 256 << 10

// telemetryEventLine is one reading as a named Server-Sent Event line: the data
// is the reading as JSON, the shape every reader of the feed parses.
func telemetryEventLine(project string, source string, area uint32, node uint32, field string, value string, status int64, receivedMs int64) string {
	data, _ := json.Marshal(map[string]any{
		"project": project, "source": source, "area": area, "node": node, "field": field,
		"value": value, "status": status, "received_ms": receivedMs,
	})
	line, _ := json.Marshal(map[string]string{"event": "telemetry", "data": string(data)})
	return string(line) + "\n"
}

// telemetryEventAppend adds lines to a project's live feed, readable by its
// owner only, starting it again when it has grown past its limit.
func telemetryEventAppend(path string, lines string) bool {
	if lines == "" {
		return true
	}
	_ = os.MkdirAll(filepath.Dir(path), 0o700)
	if info, err := os.Stat(path); err == nil && info.Size() > telemetryEventLimit {
		_ = os.Truncate(path, 0)
	}
	file, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		return false
	}
	_, werr := file.WriteString(lines)
	cerr := file.Close()
	return werr == nil && cerr == nil
}

// telemetryFeedRecord is the live-feed half of recording a reading Mesh read
// itself (an HTTP device): the same line the gateway path writes.
func telemetryFeedRecord(path string, project string, source string, field string, value string, status uint32) bool {
	return telemetryEventAppend(path, telemetryEventLine(project, source, 0, 0, field, value, int64(status), time.Now().UnixMilli()))
}

// telemetryLatestEvents is a project's current values as feed lines, the
// snapshot a stream sends before it follows the live feed, so a page that
// connects starts from the present rather than waiting for the next change.
func telemetryLatestEvents(project string) string {
	if !telemetryOpen("") {
		return ""
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return ""
	}
	rows, err := handle.Query("SELECT l.source, COALESCE(s.area_id, 0), COALESCE(s.node_id, 0), "+
		"l.field, l.value, l.status, l.received_ms FROM telemetry_latest l "+
		"LEFT JOIN telemetry_source s ON s.project = l.project AND s.source = l.source "+
		"WHERE l.project = ? ORDER BY l.source, l.field", project)
	if err != nil {
		return ""
	}
	defer rows.Close()
	var b strings.Builder
	for rows.Next() {
		var source, field string
		var area, node int64
		var value float64
		var status, received int64
		if rows.Scan(&source, &area, &node, &field, &value, &status, &received) != nil {
			continue
		}
		if area < 0 || node < 0 {
			area, node = 0, 0
		}
		b.WriteString(telemetryEventLine(project, source, uint32(area), uint32(node), field,
			strconv.FormatFloat(value, 'f', -1, 64), status, received))
	}
	return b.String()
}
