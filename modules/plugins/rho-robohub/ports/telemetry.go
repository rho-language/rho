// telemetryFaultPrune keeps actionable faults for the configured window.
func telemetryFaultPrune(project string, days uint32) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	if days == 0 {
		days = 365
	}
	before := time.Now().Add(-time.Duration(days) * 24 * time.Hour).UnixMilli()
	result, err := handle.Exec("DELETE FROM telemetry_fault WHERE project = ? AND created_ms < ?", project, before)
	if err != nil {
		return telemetryError("the fault retention pass failed")
	}
	removed, _ := result.RowsAffected()
	_ = telemetryCheckpoint("PASSIVE")
	return telemetryJSON(map[string]any{"ok": true, "removed": removed, "before_ms": before})
}

