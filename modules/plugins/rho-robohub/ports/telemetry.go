// The telemetry port: ingest a gateway outbox into the project's store.
//
// The gateway is the edge recorder; a service is where a series is kept and
// queried. This port is the seam between them: it asks a robohub-gateway for the
// readings after a cursor, writes the batch in one transaction, advances the
// cursor and acks the gateway. It is written against the sql port, which embeds
// the project's schema and opens the database.
//
// A project of this platform asks for it by name (`ports: [telemetry]`).
package main

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"syscall"
	"time"
)

// Generated by the telemetry port.
//
// The statements below are the storage contract: telemetry_reading holds the
// readings, telemetry_latest the newest value per signal, and telemetry_gateway
// the cursor each gateway's feed has reached. The schema that creates them is
// the project's own, applied by the sql port before the first poll.

var (
	telemetryMu         sync.Mutex
	telemetryDB         SqlDb
	telemetryReady      bool
	telemetryDBPath     string
	telemetryLastPrune  int64
	telemetryLastCheck  int64
	telemetryLastVacuum int64
)

// telemetryOpen opens the project's telemetry database and applies its schema.
func telemetryOpen(path string) bool {
	telemetryMu.Lock()
	defer telemetryMu.Unlock()
	if telemetryReady {
		return true
	}
	if path == "" {
		path = strings.TrimSpace(os.Getenv("RHO_TELEMETRY_DB"))
	}
	if path == "" {
		path = strings.TrimSpace(os.Getenv("ROBOHUB_MESH_TELEMETRY_DB"))
	}
	if path == "" {
		if home, err := os.UserHomeDir(); err == nil {
			path = filepath.Join(home, ".rho", "mesh", "telemetry.db")
		}
	}
	if path == "" {
		path = "telemetry.db"
	}
	if directory := filepath.Dir(path); directory != "" && directory != "." {
		_ = os.MkdirAll(directory, 0o755)
	}
	opened := stdSqlSqlOpen(path)
	if !opened.isOk {
		return false
	}
	telemetryDBPath = path
	telemetryDB = opened.ok
	stdSqlSqlApply(telemetryDB, "")
	telemetryReady = true
	return true
}

func telemetryNumber(value any) float64 {
	switch typed := value.(type) {
	case float64:
		return typed
	case int64:
		return float64(typed)
	case json.Number:
		parsed, _ := typed.Float64()
		return parsed
	}
	return 0
}

func telemetryUint(value any) uint32 {
	number := telemetryNumber(value)
	if number <= 0 {
		return 0
	}
	return uint32(number)
}

func telemetryInt(value any) int64 {
	return int64(telemetryNumber(value))
}

func telemetryText(value any) string {
	if text, ok := value.(string); ok {
		return text
	}
	return ""
}

func telemetryJSON(value any) string {
	data, err := json.Marshal(value)
	if err != nil {
		return "{\"ok\":false,\"error\":\"encoding\"}"
	}
	return string(data)
}

func telemetryError(message string) string {
	return telemetryJSON(map[string]any{"ok": false, "error": message})
}

func telemetryCursor(gatewayID string) uint32 {
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return 0
	}
	var sequence int64
	if err := handle.QueryRow(
		"SELECT last_seq FROM telemetry_gateway WHERE id = ?", gatewayID).Scan(&sequence); err != nil {
		return 0
	}
	if sequence <= 0 {
		return 0
	}
	return uint32(sequence)
}

func telemetryAck(gatewayURL string, sequence uint32, token string) {
	body := fmt.Sprintf("{\"seq\":%d}", sequence)
	request, err := http.NewRequest(http.MethodPost,
		strings.TrimRight(gatewayURL, "/")+"/api/v1/telemetry/ack", strings.NewReader(body))
	if err != nil {
		return
	}
	request.Header.Set("Content-Type", "application/json")
	if token != "" {
		request.Header.Set("Authorization", "Bearer "+token)
	}
	client := &http.Client{Timeout: 5 * time.Second}
	response, err := client.Do(request)
	if err != nil {
		return
	}
	_, _ = io.Copy(io.Discard, response.Body)
	_ = response.Body.Close()
}

// telemetryPoll reads one page of a gateway's outbox and writes it in one
// transaction. A page is at most five hundred readings; the gateway's cursor
// is advanced only after the commit, and the ack follows the commit, so a
// failure leaves the page to be read again.
func telemetryPoll(project string, gatewayID string, gatewayURL string, token string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	base := strings.TrimRight(gatewayURL, "/")
	cursor := telemetryCursor(gatewayID)
	address := fmt.Sprintf("%s/api/v1/telemetry/outbox?after=%d&limit=500", base, cursor)
	request, err := http.NewRequest(http.MethodGet, address, nil)
	if err != nil {
		return telemetryError("the gateway address was not a URL")
	}
	if token != "" {
		request.Header.Set("Authorization", "Bearer "+token)
	}
	client := &http.Client{Timeout: 5 * time.Second}
	response, err := client.Do(request)
	if err != nil {
		return telemetryError("the gateway did not answer")
	}
	body, readErr := io.ReadAll(io.LimitReader(response.Body, 1<<20))
	_ = response.Body.Close()
	if readErr != nil {
		return telemetryError("the gateway response could not be read")
	}
	var records []map[string]any
	if err := json.Unmarshal(body, &records); err != nil {
		return telemetryError("the gateway response was not a reading page")
	}
	if len(records) == 0 {
		return telemetryJSON(map[string]any{"ok": true, "fetched": 0, "last_seq": cursor})
	}

	readings := make([][]any, 0, len(records))
	latest := make([][]any, 0, len(records))
	faults := make([][]any, 0, 4)
	maxSequence := cursor
	for _, record := range records {
		sequence := telemetryUint(record["seq"])
		area := telemetryUint(record["area_id"])
		node := telemetryUint(record["node_id"])
		field := telemetryText(record["field"])
		if sequence == 0 || field == "" {
			continue
		}
		value := telemetryNumber(record["value"])
		status := telemetryInt(record["status"])
		received := telemetryInt(record["received_ms"])
		readings = append(readings, []any{
			project, gatewayID, int64(sequence), int64(area), int64(node),
			field, value, status, received,
		})
		if status == 0 {
			latest = append(latest, []any{
				project, int64(area), int64(node), field, value, status, received,
			})
		} else {
			severity := "WARNING"
			if status >= 2 {
				severity = "ERROR"
			}
			faults = append(faults, []any{
				project, gatewayID, int64(area), int64(node), field,
				status, severity, "gateway reading reported status " + strconv.FormatInt(status, 10), received,
			})
		}
		if sequence > maxSequence {
			maxSequence = sequence
		}
	}
	if len(readings) == 0 {
		return telemetryJSON(map[string]any{"ok": true, "fetched": 0, "last_seq": cursor})
	}
	gateways := [][]any{{
		gatewayID, project, base, int64(maxSequence), time.Now().UnixMilli(),
	}}
	batches := []rhoSqlStatementBatch{
		{
			SQL: "INSERT OR IGNORE INTO telemetry_reading " +
				"(project, gateway_id, seq, area_id, node_id, field, value, status, received_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
			Rows: readings,
		},
		{
			SQL: "INSERT INTO telemetry_latest " +
				"(project, area_id, node_id, field, value, status, received_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?) " +
				"ON CONFLICT(project, area_id, node_id, field) DO UPDATE SET " +
				"value = excluded.value, status = excluded.status, received_ms = excluded.received_ms",
			Rows: latest,
		},
		{
			SQL: "INSERT INTO telemetry_gateway (id, project, url, last_seq, updated_ms) " +
				"VALUES (?, ?, ?, ?, ?) " +
				"ON CONFLICT(id) DO UPDATE SET project = excluded.project, url = excluded.url, " +
				"last_seq = excluded.last_seq, updated_ms = excluded.updated_ms",
			Rows: gateways,
		},
	}
	if len(faults) > 0 {
		batches = append(batches, rhoSqlStatementBatch{
			SQL: "INSERT INTO telemetry_fault " +
				"(project, gateway_id, area_id, node_id, field, status, severity, message, created_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
			Rows: faults,
		})
	}
	ok := rhoSqlExecBatch(telemetryDB, "telemetry ingest", batches)
	if ok == 0 {
		return telemetryError("the batch was rolled back: " + rhoSqlLastErrMsg)
	}
	rolled := telemetryRollup(project)
	telemetryAck(base, maxSequence, token)
	return telemetryJSON(map[string]any{
		"ok": true, "fetched": len(readings), "last_seq": maxSequence,
		"rollup": strings.Contains(rolled, "\"ok\":true"),
	})
}

// telemetryStatus reports what the store has for one project.
func telemetryStatus(project string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	var rows int64
	var last int64
	if err := handle.QueryRow(
		"SELECT COUNT(*), COALESCE(MAX(received_ms), 0) FROM telemetry_reading WHERE project = ?",
		project).Scan(&rows, &last); err != nil {
		return telemetryError("the store could not be read")
	}
	var gateways int64
	_ = handle.QueryRow(
		"SELECT COUNT(*) FROM telemetry_gateway WHERE project = ?", project).Scan(&gateways)
	return telemetryJSON(map[string]any{
		"ok": true, "rows": rows, "last_ms": last, "gateways": gateways,
	})
}

// telemetryLatest answers the newest value of one signal.
func telemetryLatest(project string, area uint32, node uint32, field string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	var value float64
	var status int64
	var received int64
	if err := handle.QueryRow(
		"SELECT value, status, received_ms FROM telemetry_latest "+
			"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ?",
		project, int64(area), int64(node), field).Scan(&value, &status, &received); err != nil {
		return telemetryJSON(map[string]any{"ok": false})
	}
	return telemetryJSON(map[string]any{
		"ok": true, "value": value, "status": status, "received_ms": received,
	})
}

// telemetryLatestText answers the newest value as text, for the live value a
// source page shows. An empty string means the store has no reading yet, and
// the caller falls back to the gateway's live state.
func telemetryLatestText(project string, area uint32, node uint32, field string) string {
	if !telemetryOpen("") {
		return ""
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return ""
	}
	var value float64
	if err := handle.QueryRow(
		"SELECT value FROM telemetry_latest "+
			"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? AND status = 0",
		project, int64(area), int64(node), field).Scan(&value); err != nil {
		return ""
	}
	return strconv.FormatFloat(value, 'f', -1, 64)
}

// telemetryJSONValue walks a decoded document by slash-separated segments.
func telemetryJSONValue(document any, path string) (any, bool) {
	current := document
	for _, segment := range strings.Split(path, "/") {
		switch node := current.(type) {
		case map[string]any:
			next, ok := node[segment]
			if !ok {
				return nil, false
			}
			current = next
		case []any:
			index, err := strconv.Atoi(segment)
			if err != nil || index < 0 || index >= len(node) {
				return nil, false
			}
			current = node[index]
		default:
			return nil, false
		}
	}
	return current, true
}

// telemetryJSONNumber answers a number at a JSON path, scaled, as text. An
// empty string means the path was absent, which is not the same as zero.
func telemetryJsonNumber(document string, path string, scaleText string) string {
	var decoded any
	if err := json.Unmarshal([]byte(document), &decoded); err != nil {
		return ""
	}
	value, ok := telemetryJSONValue(decoded, path)
	if !ok {
		return ""
	}
	number, ok := value.(float64)
	if !ok {
		return ""
	}
	scale := 1.0
	if parsed, err := strconv.ParseFloat(strings.TrimSpace(scaleText), 64); err == nil && parsed != 0 {
		scale = parsed
	}
	return strconv.FormatFloat(number*scale, 'f', -1, 64)
}

// telemetryJSONBool answers a boolean at a JSON path as "true" or "false".
func telemetryJsonBool(document string, path string) string {
	var decoded any
	if err := json.Unmarshal([]byte(document), &decoded); err != nil {
		return ""
	}
	value, ok := telemetryJSONValue(decoded, path)
	if !ok {
		return ""
	}
	flag, ok := value.(bool)
	if !ok {
		return ""
	}
	if flag {
		return "true"
	}
	return "false"
}

// telemetryRecord writes one reading a service read itself, rather than one a
// gateway delivered. The synthetic feed is per field so the reading's unique
// key stays meaningful, and the sequence is the receive time.
func telemetryRecord(project string, area uint32, node uint32, field string, valueText string, status uint32) uint32 {
	if !telemetryOpen("") {
		return 0
	}
	value, err := strconv.ParseFloat(strings.TrimSpace(valueText), 64)
	if err != nil {
		return 0
	}
	received := time.Now().UnixMilli()
	feed := fmt.Sprintf("mesh:%s:%d:%d:%s", project, area, node, field)
	reading := [][]any{{
		project, feed, received, int64(area), int64(node), field, value,
		int64(status), received,
	}}
	latest := [][]any{{
		project, int64(area), int64(node), field, value, int64(status), received,
	}}
	batches := []rhoSqlStatementBatch{
		{
			SQL: "INSERT OR IGNORE INTO telemetry_reading " +
				"(project, gateway_id, seq, area_id, node_id, field, value, status, received_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
			Rows: reading,
		},
		{
			SQL: "INSERT INTO telemetry_latest " +
				"(project, area_id, node_id, field, value, status, received_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?) " +
				"ON CONFLICT(project, area_id, node_id, field) DO UPDATE SET " +
				"value = excluded.value, status = excluded.status, received_ms = excluded.received_ms",
			Rows: latest,
		},
	}
	if status != 0 {
		severity := "WARNING"
		if status >= 2 {
			severity = "ERROR"
		}
		batches = append(batches, rhoSqlStatementBatch{
			SQL: "INSERT INTO telemetry_fault " +
				"(project, gateway_id, area_id, node_id, field, status, severity, message, created_ms) " +
				"VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
			Rows: [][]any{{
				project, feed, int64(area), int64(node), field, int64(status),
				severity, "telemetry report status " + strconv.FormatUint(uint64(status), 10), received,
			}},
		})
	}
	return rhoSqlExecBatch(telemetryDB, "telemetry record", batches)
}

// telemetrySeries answers a time range, raw when step is zero and averaged into
// buckets when it is not. The bucket arithmetic is done by the database so a
// long range is not walked one row at a time in this process.
func telemetrySeries(project string, area uint32, node uint32, field string, fromText string, toText string, stepText string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	fromText = strings.TrimSpace(fromText)
	toText = strings.TrimSpace(toText)
	stepText = strings.TrimSpace(stepText)
	from := int64(0)
	to := int64(0)
	step := int64(0)
	if fromText != "" {
		// A relative window ("2h", "30m", "90s") means "from now minus
		// that window", so a chart can ask for the last two hours without
		// computing a millisecond timestamp in Rho.
		if parsed, err := time.ParseDuration(fromText); err == nil {
			from = time.Now().Add(-parsed).UnixMilli()
		} else {
			from, _ = strconv.ParseInt(fromText, 10, 64)
		}
	}
	if toText != "" {
		if parsed, err := time.ParseDuration(toText); err == nil {
			to = time.Now().Add(-parsed).UnixMilli()
		} else {
			to, _ = strconv.ParseInt(toText, 10, 64)
		}
	}
	if stepText != "" {
		step, _ = strconv.ParseInt(stepText, 10, 64)
	}
	if to <= 0 {
		to = time.Now().UnixMilli()
	}
	if fromText == "" {
		from = to - 24*60*60*1000
	}
	if step < 0 {
		step = 0
	}
	// A recent range reads raw rows, where every sample is present. An older
	// range reads the rollups, which are kept after the raw rows are pruned.
	// The two-hour boundary keeps a live chart on raw data while the hourly
	// rollup is still catching up with the current hour.
	useRollups := step >= 60000 && from < time.Now().UnixMilli()-2*60*60*1000
	var rows any
	var err error
	switch {
	case useRollups && step >= 3600000:
		rows, err = handle.Query(
			"SELECT (bucket_ms / ?) * ? AS bucket, AVG(value_avg) FROM telemetry_rollup_1h "+
				"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? "+
				"AND bucket_ms >= ? AND bucket_ms <= ? GROUP BY bucket ORDER BY bucket LIMIT 5000",
			step, step, project, int64(area), int64(node), field, from, to)
	case useRollups:
		rows, err = handle.Query(
			"SELECT (bucket_ms / ?) * ? AS bucket, AVG(value_avg) FROM telemetry_rollup_1m "+
				"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? "+
				"AND bucket_ms >= ? AND bucket_ms <= ? GROUP BY bucket ORDER BY bucket LIMIT 5000",
			step, step, project, int64(area), int64(node), field, from, to)
	case step == 0:
		rows, err = handle.Query(
			"SELECT received_ms, value FROM telemetry_reading "+
				"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? "+
				"AND received_ms >= ? AND received_ms <= ? AND status = 0 ORDER BY received_ms LIMIT 5000",
			project, int64(area), int64(node), field, from, to)
	default:
		rows, err = handle.Query(
			"SELECT (received_ms / ?) * ? AS bucket, AVG(value) FROM telemetry_reading "+
				"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? "+
				"AND received_ms >= ? AND received_ms <= ? AND status = 0 GROUP BY bucket ORDER BY bucket LIMIT 5000",
			step, step, project, int64(area), int64(node), field, from, to)
	}
	if err != nil {
		return telemetryError("the series could not be read")
	}
	// The driver returns an interface whose rows are closed by its own close
	// method; the type is named through the interface to keep the port free of
	// a database import.
	type rowSet interface {
		Next() bool
		Scan(...any) error
		Close() error
	}
	typed, ok := rows.(rowSet)
	if !ok {
		return telemetryError("the series could not be read")
	}
	defer typed.Close()
	out := make([]map[string]any, 0, 256)
	for typed.Next() {
		var timestamp int64
		var value float64
		if err := typed.Scan(&timestamp, &value); err != nil {
			continue
		}
		out = append(out, map[string]any{"t": timestamp, "v": value})
	}
	// A store that has just started has no rollups for a range that predates
	// them. Falling back to the raw rows keeps a chart from going blank while
	// the first rollup pass catches up.
	if len(out) == 0 && useRollups {
		var fallback any
		var fallbackErr error
		fallback, fallbackErr = handle.Query(
			"SELECT (received_ms / ?) * ? AS bucket, AVG(value) FROM telemetry_reading "+
				"WHERE project = ? AND area_id = ? AND node_id = ? AND field = ? "+
				"AND received_ms >= ? AND received_ms <= ? AND status = 0 GROUP BY bucket ORDER BY bucket LIMIT 5000",
			step, step, project, int64(area), int64(node), field, from, to)
		if fallbackErr == nil {
			if fallbackRows, ok := fallback.(rowSet); ok {
				defer fallbackRows.Close()
				for fallbackRows.Next() {
					var timestamp int64
					var value float64
					if err := fallbackRows.Scan(&timestamp, &value); err != nil {
						continue
					}
					out = append(out, map[string]any{"t": timestamp, "v": value})
				}
			}
		}
	}
	return telemetryJSON(map[string]any{"ok": true, "points": out})
}

// telemetryRollup folds completed raw readings into one-minute buckets and
// completed minute buckets into hours. It is called after each ingest and
// before a retention pass, so a chart over an old range still has a series.
func telemetryRollup(project string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	now := time.Now().UnixMilli()
	minuteCutoff := now - 60000
	minuteBoundary := (now / 60000) * 60000
	lastMinute := int64(0)
	_ = handle.QueryRow(
		"SELECT COALESCE(MAX(bucket_ms), 0) FROM telemetry_rollup_1m WHERE project = ?",
		project).Scan(&lastMinute)
	// Only a newly completed minute is worth writing. Re-running the same
	// bucket every two seconds would put the eMMC back where the raw insert
	// started.
	if lastMinute < minuteBoundary-60000 {
		if _, err := handle.Exec(
			"INSERT OR REPLACE INTO telemetry_rollup_1m "+
				"(project, area_id, node_id, field, bucket_ms, value_min, value_max, value_avg, samples) "+
				"SELECT project, area_id, node_id, field, (received_ms / 60000) * 60000, "+
				"MIN(value), MAX(value), AVG(value), COUNT(*) FROM telemetry_reading "+
				"WHERE project = ? AND received_ms >= ? AND received_ms < ? AND status = 0 "+
				"GROUP BY project, area_id, node_id, field, (received_ms / 60000) * 60000",
			project, lastMinute, minuteCutoff); err != nil {
			return telemetryError("the minute rollup failed")
		}
	}
	hourCutoff := (now / 3600000) * 3600000
	lastHour := int64(0)
	_ = handle.QueryRow(
		"SELECT COALESCE(MAX(bucket_ms), 0) FROM telemetry_rollup_1h WHERE project = ?",
		project).Scan(&lastHour)
	if lastHour < hourCutoff-3600000 {
		if _, err := handle.Exec(
			"INSERT OR REPLACE INTO telemetry_rollup_1h "+
				"(project, area_id, node_id, field, bucket_ms, value_min, value_max, value_avg, samples) "+
				"SELECT project, area_id, node_id, field, (bucket_ms / 3600000) * 3600000, "+
				"MIN(value_min), MAX(value_max), AVG(value_avg), SUM(samples) FROM telemetry_rollup_1m "+
				"WHERE project = ? AND bucket_ms >= ? AND bucket_ms < ? "+
				"GROUP BY project, area_id, node_id, field, (bucket_ms / 3600000) * 3600000",
			project, lastHour, hourCutoff); err != nil {
			return telemetryError("the hourly rollup failed")
		}
	}
	return telemetryJSON(map[string]any{"ok": true})
}

// telemetryPrune rolls the project up and then removes each window's oldest
// rows. Raw readings go first; the minute and hour rollups outlive them.
func telemetryPrune(project string, rawDays uint32, minuteDays uint32, hourDays uint32) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	if rawDays == 0 {
		rawDays = 14
	}
	if minuteDays == 0 {
		minuteDays = 90
	}
	if hourDays == 0 {
		hourDays = 1825
	}
	_ = telemetryRollup(project)
	now := time.Now()
	rawBefore := now.Add(-time.Duration(rawDays) * 24 * time.Hour).UnixMilli()
	minuteBefore := now.Add(-time.Duration(minuteDays) * 24 * time.Hour).UnixMilli()
	hourBefore := now.Add(-time.Duration(hourDays) * 24 * time.Hour).UnixMilli()
	deleteBefore := func(table string, column string, before int64) (int64, error) {
		var total int64
		for {
			result, err := handle.Exec(
				"DELETE FROM "+table+" WHERE rowid IN ("+
					"SELECT rowid FROM "+table+" WHERE project = ? AND "+column+" < ? LIMIT 5000)",
				project, before)
			if err != nil {
				return total, err
			}
			removed, _ := result.RowsAffected()
			total = total + removed
			_ = telemetryCheckpoint("PASSIVE")
			if removed < 5000 {
				break
			}
		}
		return total, nil
	}
	rawRemoved, err := deleteBefore("telemetry_reading", "received_ms", rawBefore)
	if err != nil {
		return telemetryError("the raw retention pass failed")
	}
	minuteRemoved, err := deleteBefore("telemetry_rollup_1m", "bucket_ms", minuteBefore)
	if err != nil {
		return telemetryError("the minute retention pass failed")
	}
	hourRemoved, err := deleteBefore("telemetry_rollup_1h", "bucket_ms", hourBefore)
	if err != nil {
		return telemetryError("the hourly retention pass failed")
	}
	telemetryLastPrune = time.Now().UnixMilli()
	return telemetryJSON(map[string]any{
		"ok":      true,
		"removed": rawRemoved + minuteRemoved + hourRemoved,
		"raw":     rawRemoved, "minute": minuteRemoved, "hour": hourRemoved,
		"before_ms": rawBefore,
	})
}

// telemetryCheckpoint moves WAL frames into the database. PASSIVE is the
// routine call; TRUNCATE is for a maintenance window when the WAL should go
// back to zero.
func telemetryCheckpoint(mode string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	mode = strings.ToUpper(strings.TrimSpace(mode))
	switch mode {
	case "", "PASSIVE":
		mode = "PASSIVE"
	case "FULL", "RESTART", "TRUNCATE":
	default:
		return telemetryError("unknown checkpoint mode")
	}
	var busy, log, checkpointed int64
	if err := handle.QueryRow("PRAGMA wal_checkpoint("+mode+")").Scan(&busy, &log, &checkpointed); err != nil {
		return telemetryError("the WAL checkpoint failed")
	}
	telemetryLastCheck = time.Now().UnixMilli()
	return telemetryJSON(map[string]any{
		"ok": true, "mode": mode, "busy": busy, "log": log, "checkpointed": checkpointed,
	})
}

// telemetryVacuum reclaims free pages. Incremental is the routine call on
// flash; full rewrites the database and belongs to a rare maintenance window.
func telemetryVacuum(mode string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	mode = strings.ToLower(strings.TrimSpace(mode))
	before := int64(0)
	if info, err := os.Stat(telemetryDBPath); err == nil {
		before = info.Size()
	}
	_, _ = handle.Exec("PRAGMA optimize")
	switch mode {
	case "", "incremental":
		if _, err := handle.Exec("PRAGMA incremental_vacuum"); err != nil {
			return telemetryError("the incremental vacuum failed")
		}
	case "full":
		if _, err := handle.Exec("VACUUM"); err != nil {
			return telemetryError("the vacuum failed")
		}
	default:
		return telemetryError("unknown vacuum mode")
	}
	after := int64(0)
	if info, err := os.Stat(telemetryDBPath); err == nil {
		after = info.Size()
	}
	telemetryLastVacuum = time.Now().UnixMilli()
	return telemetryJSON(map[string]any{
		"ok": true, "mode": mode, "before_bytes": before, "after_bytes": after,
	})
}

// telemetryStorageStatus is what the Storage tab and a warning loop read:
// database and WAL sizes, free space, row counts, and the last maintenance.
func telemetryStorageStatus(project string) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	var dbBytes, walBytes, freeBytes int64
	if info, err := os.Stat(telemetryDBPath); err == nil {
		dbBytes = info.Size()
	}
	if info, err := os.Stat(telemetryDBPath + "-wal"); err == nil {
		walBytes = info.Size()
	}
	var stat syscall.Statfs_t
	if err := syscall.Statfs(filepath.Dir(telemetryDBPath), &stat); err == nil {
		freeBytes = int64(stat.Bavail) * int64(stat.Bsize)
	}
	count := func(query string) int64 {
		var value int64
		_ = handle.QueryRow(query, project).Scan(&value)
		return value
	}
	return telemetryJSON(map[string]any{
		"ok":       true,
		"db_bytes": dbBytes, "wal_bytes": walBytes, "free_bytes": freeBytes,
		"raw_rows":           count("SELECT COUNT(*) FROM telemetry_reading WHERE project = ?"),
		"minute_rows":        count("SELECT COUNT(*) FROM telemetry_rollup_1m WHERE project = ?"),
		"hour_rows":          count("SELECT COUNT(*) FROM telemetry_rollup_1h WHERE project = ?"),
		"fault_rows":         count("SELECT COUNT(*) FROM telemetry_fault WHERE project = ?"),
		"last_prune_ms":      telemetryLastPrune,
		"last_checkpoint_ms": telemetryLastCheck,
		"last_vacuum_ms":     telemetryLastVacuum,
	})
}

// telemetryFaultRecord inserts an actionable fault that did not come from a
// gateway reading, such as a local safety rule or a device poll failure.
func telemetryFaultRecord(project string, gateway string, field string, severity string,
	message string, area uint32, node uint32, status uint32, createdText string) uint32 {
	if !telemetryOpen("") {
		return 0
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return 0
	}
	created, err := strconv.ParseInt(strings.TrimSpace(createdText), 10, 64)
	if err != nil || created == 0 {
		created = time.Now().UnixMilli()
	}
	if severity == "" {
		severity = "ERROR"
	}
	if _, err := handle.Exec(
		"INSERT INTO telemetry_fault "+
			"(project, gateway_id, area_id, node_id, field, status, severity, message, created_ms) "+
			"VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
		project, gateway, int64(area), int64(node), field, int64(status), severity, message, created); err != nil {
		return 0
	}
	return 1
}

// telemetryFaultList answers the actionable faults a UI shows.
func telemetryFaultList(project string, sinceText string, limit uint32) string {
	if !telemetryOpen("") {
		return telemetryError("the telemetry database could not be opened")
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return telemetryError("the telemetry database is not open")
	}
	since, _ := strconv.ParseInt(strings.TrimSpace(sinceText), 10, 64)
	if limit == 0 {
		limit = 100
	}
	rows, err := handle.Query(
		"SELECT id, gateway_id, area_id, node_id, field, status, severity, message, created_ms "+
			"FROM telemetry_fault WHERE project = ? AND created_ms >= ? ORDER BY created_ms DESC LIMIT ?",
		project, since, int64(limit))
	if err != nil {
		return telemetryError("the fault list could not be read")
	}
	type rowSet interface {
		Next() bool
		Scan(...any) error
		Close() error
	}
	var rowsAny any = rows
	typed, ok := rowsAny.(rowSet)
	if !ok {
		return telemetryError("the fault list could not be read")
	}
	defer typed.Close()
	out := make([]map[string]any, 0, 32)
	for typed.Next() {
		var id, area, node, status, created int64
		var gateway, field, severity, message string
		if err := typed.Scan(&id, &gateway, &area, &node, &field, &status, &severity, &message, &created); err != nil {
			continue
		}
		out = append(out, map[string]any{
			"id": id, "gateway_id": gateway, "area_id": area, "node_id": node,
			"field": field, "status": status, "severity": severity,
			"message": message, "created_ms": created,
		})
	}
	return telemetryJSON(map[string]any{"ok": true, "faults": out})
}

// telemetryFaultRows is the same list as tab-separated lines, which a Rho
// template can turn into rows without a JSON parser.
func telemetryFaultRows(project string, limit uint32) string {
	if !telemetryOpen("") {
		return ""
	}
	handle, ok := rhoSqlHandle(telemetryDB.raw)
	if !ok {
		return ""
	}
	if limit == 0 {
		limit = 100
	}
	rows, err := handle.Query(
		"SELECT id, severity, created_ms, message FROM telemetry_fault "+
			"WHERE project = ? ORDER BY created_ms DESC LIMIT ?", project, int64(limit))
	if err != nil {
		return ""
	}
	type rowSet interface {
		Next() bool
		Scan(...any) error
		Close() error
	}
	var rowsAny any = rows
	typed, ok := rowsAny.(rowSet)
	if !ok {
		return ""
	}
	defer typed.Close()
	var out strings.Builder
	for typed.Next() {
		var id, created int64
		var severity, message string
		if err := typed.Scan(&id, &severity, &created, &message); err != nil {
			continue
		}
		out.WriteString(strconv.FormatInt(id, 10))
		out.WriteString("\t")
		out.WriteString(severity)
		out.WriteString("\t")
		out.WriteString(strconv.FormatInt(created, 10))
		out.WriteString("\t")
		out.WriteString(strings.ReplaceAll(message, "\t", " "))
		out.WriteString("\n")
	}
	return out.String()
}

// telemetryFaultMaxID is the newest fault id, used to start a live feed at the
// current state instead of replaying every fault the store has ever held.
