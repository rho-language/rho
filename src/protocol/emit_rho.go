// EmitRho renders the schema as Rho: the same little-endian payloads the C and
// Go emitters write, and the robohub transport frame that carries a payload on
// the wire — COBS, a Fletcher-16 check and the six-byte header. The output is
// Rho a program includes, so the bytes on the wire are code a reader can follow
// rather than a hand-rolled copy that drifts from the firmware.
//
// It returns an error for a field the emitter cannot lay out (an array, or a
// type it does not know), because a Rho struct cannot hold a fixed array and a
// silent omission would write a payload shorter than the C side reads.
func (s *Schema) EmitRho() (string, error) {
	l := s.newLayout()
	p := s.prefix()
	module := namespaceOr(s.Namespace, "protocol")

	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by rho protocol from namespace %s. Do not edit.\n",
		namespaceOr(s.Namespace, "(none)"))
	fmt.Fprintf(&b, "module %s\n\n", module)

	// The version byte every message begins with, and the wire helpers.
	fmt.Fprintf(&b, "// The schema version every message begins with.\nconst %s_SCHEMA_VERSION: u32 = %d\n\n",
		strings.ToUpper(p), s.Version)
	emitRhoWireHelpers(&b, p)

	// Enum variants are unsigned constants: the wire is a 32-bit value, and Rho
	// has no enum-to-number cast, so a field of enum type is a u32.
	for _, e := range s.Enums {
		fmt.Fprintf(&b, "// %s values.\n", e.Name)
		for _, v := range e.Variants {
			fmt.Fprintf(&b, "const %s: u32 = %d\n", macroName(e.Name+"_"+v.Name), v.Value)
		}
		b.WriteString("\n")
	}

	messages := s.AllMessages()
	for _, m := range messages {
		for _, f := range m.Fields {
			if err := rhoFieldSupported(l, f); err != nil {
				return "", fmt.Errorf("message %s field %s: %w", m.Name, f.Name, err)
			}
		}
		fmt.Fprintf(&b, "// %s is %s on the wire, the version byte included.\n", m.Name, m.Name)
		fmt.Fprintf(&b, "struct %s {\n", m.Name)
		for _, f := range m.Fields {
			fmt.Fprintf(&b, "    %s: %s\n", snake(f.Name), l.rhoType(f))
		}
		b.WriteString("}\n\n")

		emitRhoValid(&b, l, m, s.Version)
		emitRhoMarshal(&b, l, p, m, s.Version)
		emitRhoUnmarshal(&b, l, p, m)
	}

	emitRhoTransport(&b, p)
	return b.String(), nil
}

// rhoFieldSupported rejects a field the Rho layout cannot hold.
func rhoFieldSupported(l *layout, f ast.Field) error {
	if f.TypeExpr.ArrayLen != nil {
		return fmt.Errorf("an array cannot be a Rho struct field yet")
	}
	switch l.kind(f.TypeExpr.Name) {
	case "scalar", "enum", "message", "string":
		return nil
	}
	return fmt.Errorf("unknown type %s", f.TypeExpr.Name)
}

// rhoScalarMap is the Rho spelling of each scalar. It matches the schema name
// except where a schema writes a shorthand the language does not use.
// Rho has no i8 or i16, and the wire cannot tell: a signed value of a given
// width is its unsigned value in two's complement. Those two are therefore read
// and written through the u8 and u16 helpers, and a Rho reader sees the bits.
// i32 and i64 do exist and keep their signedness.
var rhoScalars = map[string]string{
	"u8": "u8", "u16": "u16", "u32": "u32", "u64": "u64",
	"i8": "u8", "i16": "u16", "i32": "i32", "i64": "i64",
	"f32": "f32", "f64": "f64", "bool": "bool",
}

// rhoType is the Rho type of a field: a scalar as itself, an enum as the u32
// its wire value is, a message as itself, a string as a string.
func (l *layout) rhoType(f ast.Field) string {
	if scalar, ok := rhoScalars[f.TypeExpr.Name]; ok {
		return scalar
	}
	if f.TypeExpr.Name == "string" {
		return "string"
	}
	if l.kind(f.TypeExpr.Name) == "enum" {
		return "u32"
	}
	if l.kind(f.TypeExpr.Name) == "message" {
		return f.TypeExpr.Name
	}
	return "u8 /* unknown type " + f.TypeExpr.Name + " */"
}

// rhoCell is the helper a field's bytes go through: an enum travels as the u32
// its value is, everything else as its own type.
func rhoCell(l *layout, f ast.Field) string {
	if l.kind(f.TypeExpr.Name) == "enum" {
		return "u32"
	}
	// i8 and i16 have no Rho type, and travel as their unsigned width.
	if f.TypeExpr.Name == "i8" {
		return "u8"
	}
	if f.TypeExpr.Name == "i16" {
		return "u16"
	}
	return f.TypeExpr.Name
}

func emitRhoValid(b *strings.Builder, l *layout, m ast.MessageDecl, version int) {
	name := snake(m.Name)
	fmt.Fprintf(b, "// %s_valid reports whether a payload is a whole %s of this version.\n", name, m.Name)
	fmt.Fprintf(b, "fn %s_valid(data: string) bool {\n", name)
	fmt.Fprintf(b, "    if strlen(data) < %d {\n        return false\n    }\n", l.messageSize(m.Name))
	fmt.Fprintf(b, "    return u32(str_at(data, 0)) == %d\n}\n\n", version)
}

func emitRhoMarshal(b *strings.Builder, l *layout, p string, m ast.MessageDecl, version int) {
	name := snake(m.Name)
	fmt.Fprintf(b, "// %s_marshal writes a %s: the version byte and its fields.\n", name, m.Name)
	fmt.Fprintf(b, "fn %s_marshal(value: %s) string {\n", name, m.Name)
	fmt.Fprintf(b, "    var out: string = str_from_byte(u8(%d))\n", version)
	for _, f := range m.Fields {
		field := "value." + snake(f.Name)
		if l.kind(f.TypeExpr.Name) == "message" {
			fmt.Fprintf(b, "    out = out + %s_marshal(%s)\n", snake(f.TypeExpr.Name), field)
			continue
		}
		fmt.Fprintf(b, "    out = out + %s_put_%s(%s)\n", p, rhoCell(l, f), field)
	}
	b.WriteString("    return out\n}\n\n")
}

func emitRhoUnmarshal(b *strings.Builder, l *layout, p string, m ast.MessageDecl) {
	name := snake(m.Name)
	fmt.Fprintf(b, "// %s_unmarshal reads a payload this schema's %s_valid accepted.\n", name, name)
	fmt.Fprintf(b, "fn %s_unmarshal(data: string) %s {\n", name, m.Name)

	offset := 1
	locals := make([]string, 0, len(m.Fields))
	if len(m.Fields) > 0 {
		b.WriteString("    var off: u32 = 1\n")
	}
	for i, f := range m.Fields {
		local := snake(f.Name)
		locals = append(locals, local)
		if l.kind(f.TypeExpr.Name) == "message" {
			fmt.Fprintf(b, "    let %s: %s = %s_unmarshal(str_slice(data, off, %d))\n",
				local, f.TypeExpr.Name, snake(f.TypeExpr.Name), l.messageSize(f.TypeExpr.Name))
		} else {
			fmt.Fprintf(b, "    let %s: %s = %s_get_%s(data, off)\n",
				local, l.rhoType(f), p, rhoCell(l, f))
		}
		offset += l.sizeOfField(f)
		if i < len(m.Fields)-1 {
			fmt.Fprintf(b, "    off = off + %d\n", l.sizeOfField(f))
		}
	}
	fmt.Fprintf(b, "    return %s { %s }\n}\n\n", m.Name, strings.Join(locals, ", "))
}

// emitRhoTransport writes the robohub transport: the framing a node's
// robohub-transport library writes, as Rho, so both ends of the link agree byte
// for byte and neither side carries a hand-rolled copy.
//
// The prefix is substituted rather than formatted, because the body is a Rho
// program with its own percent signs and a format string would have to escape
// them.
func emitRhoTransport(b *strings.Builder, p string) {
	body := `// TransportFrame is one decoded frame: the header, and the payload the
// schema deserializes. ok is false when the frame was malformed or the check
// did not match, so a caller reads the fields only when it is true.
struct TransportFrame {
    ok: bool
    msg_id: u32
    tx_id: u32
    payload: string
}

// @P@_fletcher16 is the check robohub-transport writes: two sums modulo 255,
// concatenated high byte first.
fn @P@_fletcher16(data: string, length: u32) u32 {
    var sum1: u32 = 0
    var sum2: u32 = 0
    var i: u32 = 0
    while i < length {
        sum1 = (sum1 + u32(str_at(data, i)) % 255) % 255
        sum2 = (sum2 + sum1) % 255
        i = i + 1
    }
    return (sum2 << 8) | sum1
}

// @P@_cobs_encode adds the Consistent Overhead Byte Stuffing a frame is sent
// with, without the delimiter the link appends.
fn @P@_cobs_encode(input: string) string {
    let length: u32 = strlen(input)
    var out: string = ""
    var run: string = ""
    var run_length: u32 = 0
    var i: u32 = 0
    while i < length {
        let byte: u8 = str_at(input, i)
        if byte == u8(0) {
            out = out + str_from_byte(u8(run_length + 1)) + run
            run = ""
            run_length = 0
        } else {
            run = run + str_from_byte(byte)
            run_length = run_length + 1
            if run_length == 254 {
                out = out + str_from_byte(u8(255)) + run
                run = ""
                run_length = 0
            }
        }
        i = i + 1
    }
    return out + str_from_byte(u8(run_length + 1)) + run
}

// @P@_cobs_decode reverses it, or returns "" when the frame is malformed.
fn @P@_cobs_decode(input: string) string {
    let length: u32 = strlen(input)
    var out: string = ""
    var read: u32 = 0
    while read < length {
        let code: u32 = u32(str_at(input, read))
        read = read + 1
        if code == 0 {
            return ""
        }
        var i: u32 = 1
        while i < code {
            if read >= length {
                return ""
            }
            out = out + str_from_byte(str_at(input, read))
            read = read + 1
            i = i + 1
        }
        if code < 255 && read < length {
            out = out + str_from_byte(u8(0))
        }
    }
    return out
}

// @P@_frame wraps a payload in the header and the check, then the stuffing.
// The link appends the 0x00 delimiter.
fn @P@_frame(msg_id: u32, tx_id: u32, payload: string) string {
    var body: string = @P@_put_u16(u16(msg_id)) + @P@_put_u16(u16(tx_id)) + @P@_put_u16(u16(strlen(payload))) + payload
    let check: u32 = @P@_fletcher16(body, strlen(body))
    return @P@_cobs_encode(body + @P@_put_u16(u16(check)))
}

// @P@_unframe decodes a frame and verifies it: the header, the length, and the
// Fletcher-16 check over everything before it.
fn @P@_unframe(encoded: string) TransportFrame {
    var frame: TransportFrame
    frame.ok = false
    let body: string = @P@_cobs_decode(encoded)
    let total: u32 = strlen(body)
    if total < 8 {
        return frame
    }
    let msg_id: u32 = u32(@P@_get_u16(body, 0))
    let tx_id: u32 = u32(@P@_get_u16(body, 2))
    let payload_len: u32 = u32(@P@_get_u16(body, 4))
    if 6 + payload_len + 2 != total {
        return frame
    }
    let expected: u32 = u32(@P@_get_u16(body, 6 + payload_len))
    let actual: u32 = @P@_fletcher16(body, 6 + payload_len)
    if expected != actual {
        return frame
    }
    frame.msg_id = msg_id
    frame.tx_id = tx_id
    frame.payload = str_slice(body, 6, payload_len)
    frame.ok = true
    return frame
}

`
	b.WriteString(strings.ReplaceAll(body, "@P@", p))
}

// emitRhoWireHelpers writes the little-endian put/get the payload fields use.
func emitRhoWireHelpers(b *strings.Builder, p string) {
	fmt.Fprintf(b, "// Little-endian codecs, one pair per width, so a field's bytes are written a\n")
	fmt.Fprintf(b, "// field at a time as the C and Go emitters do.\n")
	fmt.Fprintf(b, "fn %s_put_u8(value: u8) string { return str_from_byte(value) }\n", p)
	fmt.Fprintf(b, "fn %s_get_u8(data: string, off: u32) u8 { return str_at(data, off) }\n", p)
	fmt.Fprintf(b, "fn %s_put_bool(value: bool) string {\n", p)
	fmt.Fprintf(b, "    if value {\n        return str_from_byte(u8(1))\n    }\n    return str_from_byte(u8(0))\n}\n")
	fmt.Fprintf(b, "fn %s_get_bool(data: string, off: u32) bool { return %s_get_u8(data, off) != u8(0) }\n", p, p)
	fmt.Fprintf(b, "fn %s_put_u16(value: u16) string { return str_from_byte(u8(value & 0xFF)) + str_from_byte(u8((value >> 8) & 0xFF)) }\n", p)
	fmt.Fprintf(b, "fn %s_get_u16(data: string, off: u32) u16 { return u16(str_at(data, off)) | (u16(str_at(data, off + 1)) << 8) }\n", p)
	fmt.Fprintf(b, "fn %s_put_u32(value: u32) string { return str_from_byte(u8(value & 0xFF)) + str_from_byte(u8((value >> 8) & 0xFF)) + str_from_byte(u8((value >> 16) & 0xFF)) + str_from_byte(u8((value >> 24) & 0xFF)) }\n", p)
	fmt.Fprintf(b, "fn %s_get_u32(data: string, off: u32) u32 { return u32(str_at(data, off)) | (u32(str_at(data, off + 1)) << 8) | (u32(str_at(data, off + 2)) << 16) | (u32(str_at(data, off + 3)) << 24) }\n", p)
	fmt.Fprintf(b, "fn %s_put_u64(value: u64) string { return str_from_byte(u8(value & 0xFF)) + str_from_byte(u8((value >> 8) & 0xFF)) + str_from_byte(u8((value >> 16) & 0xFF)) + str_from_byte(u8((value >> 24) & 0xFF)) + str_from_byte(u8((value >> 32) & 0xFF)) + str_from_byte(u8((value >> 40) & 0xFF)) + str_from_byte(u8((value >> 48) & 0xFF)) + str_from_byte(u8((value >> 56) & 0xFF)) }\n", p)
	fmt.Fprintf(b, "fn %s_get_u64(data: string, off: u32) u64 { return u64(str_at(data, off)) | (u64(str_at(data, off + 1)) << 8) | (u64(str_at(data, off + 2)) << 16) | (u64(str_at(data, off + 3)) << 24) | (u64(str_at(data, off + 4)) << 32) | (u64(str_at(data, off + 5)) << 40) | (u64(str_at(data, off + 6)) << 48) | (u64(str_at(data, off + 7)) << 56) }\n", p)
	// The signed widths Rho has travel as the bits of the same width, so a
	// reader gets the two's-complement byte back. i8 and i16 are not Rho types
	// and use the u8/u16 helpers directly (see rhoScalars).
	fmt.Fprintf(b, "fn %s_put_i32(value: i32) string { return %s_put_u32(u32(value)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_get_i32(data: string, off: u32) i32 { return i32(%s_get_u32(data, off)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_put_i64(value: i64) string { return %s_put_u64(u64(value)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_get_i64(data: string, off: u32) i64 { return i64(%s_get_u64(data, off)) }\n", p, p)
	// Floats go as their IEEE-754 bits, which the runtime casts.
	fmt.Fprintf(b, "fn %s_put_f32(value: f32) string { return %s_put_u32(f32_to_bits(value)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_get_f32(data: string, off: u32) f32 { return f32_from_bits(%s_get_u32(data, off)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_put_f64(value: f64) string { return %s_put_u64(f64_to_bits(value)) }\n", p, p)
	fmt.Fprintf(b, "fn %s_get_f64(data: string, off: u32) f64 { return f64_from_bits(%s_get_u64(data, off)) }\n", p, p)
	// A bare string is a fixed 64 bytes, zero-padded, which is the width the C
	// and Go emitters give it.
	fmt.Fprintf(b, "fn %s_put_string(value: string) string {\n", p)
	fmt.Fprintf(b, "    var out: string = \"\"\n    var i: u32 = 0\n    let length: u32 = strlen(value)\n")
	fmt.Fprintf(b, "    while i < 64 {\n        if i < length {\n            out = out + str_from_byte(str_at(value, i))\n        } else {\n            out = out + str_from_byte(u8(0))\n        }\n        i = i + 1\n    }\n    return out\n}\n")
	fmt.Fprintf(b, "fn %s_get_string(data: string, off: u32) string { return str_slice(data, off, 64) }\n\n", p)
}
