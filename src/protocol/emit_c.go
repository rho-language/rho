// EmitC renders the schema as a C header and source. The wire is little-endian
// and written a field at a time: a message is its version byte and its fields in
// declaration order, each at a width the schema fixes. Reading and writing it
// allocates nothing.
//
// Little-endian, explicitly, rather than the host's bytes: a node may be a
// big-endian part, and a protocol whose layout is the host's is a protocol two
// hosts cannot share. The cost is a few shifts per field.
func (s *Schema) EmitC() (string, string) {
	h := &strings.Builder{}
	c := &strings.Builder{}
	l := s.newLayout()
	pfx := s.prefix()

	fmt.Fprintf(h, "/* Generated by rho protocol from namespace %s. Do not edit. */\n",
		namespaceOr(s.Namespace, "(none)"))
	h.WriteString("#pragma once\n\n")
	h.WriteString("#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n#include <string.h>\n\n")
	// A C++ translation unit includes this header to reach the same wire, so the
	// declarations are inside an extern "C" guard: without it every symbol would
	// be name-mangled and a C++ program would not link against the C that frames
	// the bytes.
	h.WriteString("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
	fmt.Fprintf(h, "#define %s_SCHEMA_VERSION %d\n\n", namespaceMacro(s.Namespace), s.Version)
	emitCWireHelpers(h, pfx)

	c.WriteString("/* Generated by rho protocol. Do not edit. */\n")
	c.WriteString("#include \"protocol.h\"\n\n")

	for _, e := range s.Enums {
		h.WriteString("typedef enum {\n")
		for _, v := range e.Variants {
			fmt.Fprintf(h, "    %s = %d,\n", macroName(e.Name+"_"+v.Name), v.Value)
		}
		fmt.Fprintf(h, "} %s;\n\n", e.Name)
	}

	messages := s.AllMessages()
	for _, m := range messages {
		fmt.Fprintf(h, "/* message %s */\ntypedef struct __attribute__((packed)) {\n", m.Name)
		if len(m.Fields) == 0 {
			h.WriteString("    uint8_t reserved;\n")
		}
		for _, f := range m.Fields {
			fmt.Fprintf(h, "    %s;\n", l.cDeclaration(f))
		}
		fmt.Fprintf(h, "} %s;\n\n", m.Name)
		fmt.Fprintf(h, "#define %s_WIRE_SIZE %d\n", macroName(m.Name), l.messageSize(m.Name))
		fmt.Fprintf(h, "size_t %s_serialize(const %s* value, uint8_t* out, size_t capacity);\n", m.Name, m.Name)
		fmt.Fprintf(h, "bool %s_deserialize(const uint8_t* data, size_t length, %s* out);\n\n", m.Name, m.Name)
	}

	for _, r := range s.Rpcs {
		fmt.Fprintf(h, "/* rpc %s */\n", r.Name)
		fmt.Fprintf(h, "#define %s_REQUEST_EVENT_ID (0x%04Xu)\n", macroName(r.Name), s.Version)
		fmt.Fprintf(h, "#define %s_RESPONSE_EVENT_ID (0x%04Xu)\n", macroName(r.Name), s.Version+1)
		fmt.Fprintf(h, "typedef int (*%s_handler)(const %sRequest* request, %sResponse* response);\n\n",
			r.Name, r.Name, r.Name)
	}

	h.WriteString("#ifdef __cplusplus\n}\n#endif\n")

	for _, m := range messages {
		emitCSerialize(c, l, pfx, m, s.Version)
	}

	return h.String(), c.String()
}

// EmitCBus renders the rpc transport over robohub-core's event bus: a publish
// for each side of a call and a subscribe that unwraps an event into a handler.
// It is a second pair of files so a schema can be generated for a node that has
// the runtime and for one that only needs the bytes.
func (s *Schema) EmitCBus() (string, string) {
	h := &strings.Builder{}
	c := &strings.Builder{}
	pfx := s.prefix()

	fmt.Fprintf(h, "/* Generated by rho protocol from namespace %s. Do not edit. */\n",
		namespaceOr(s.Namespace, "(none)"))
	h.WriteString("#pragma once\n\n#include \"protocol.h\"\n#include \"robohub/core/event.h\"\n#include \"error.h\"\n\n")
	h.WriteString("#ifndef RHPROTO_MAX_SUBSCRIBERS\n#define RHPROTO_MAX_SUBSCRIBERS 4\n#endif\n\n")
	h.WriteString("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")

	c.WriteString("/* Generated by rho protocol. Do not edit. */\n")
	c.WriteString("#include \"protocol_bus.h\"\n\n")

	for _, r := range s.Rpcs {
		req := r.Name + "Request"
		resp := r.Name + "Response"

		fmt.Fprintf(h, "/* rpc %s on the event bus */\n", r.Name)
		fmt.Fprintf(h, "RoboHubError %s_publish_request(const %s* request);\n", r.Name, req)
		fmt.Fprintf(h, "RoboHubError %s_publish_response(const %s* response);\n", r.Name, resp)
		fmt.Fprintf(h, "typedef struct { %s_handler handler; void* user; } %s_subscription;\n", r.Name, r.Name)
		fmt.Fprintf(h, "RoboHubError %s_subscribe(%s_handler handler, void* user);\n", r.Name, r.Name)
		fmt.Fprintf(h, "RoboHubError %s_unsubscribe(%s_handler handler, void* user);\n\n", r.Name, r.Name)

		fmt.Fprintf(c, "static uint8_t %s_request_bytes[%s_WIRE_SIZE];\n", pfx, macroName(req))
		fmt.Fprintf(c, "static uint8_t %s_response_bytes[%s_WIRE_SIZE];\n", pfx, macroName(resp))
		fmt.Fprintf(c, "static %s_subscription %s_subscribers[RHPROTO_MAX_SUBSCRIBERS];\n\n", r.Name, pfx)

		fmt.Fprintf(c, "RoboHubError %s_publish_request(const %s* request)\n{\n", r.Name, req)
		fmt.Fprintf(c, "    size_t length = %s_serialize(request, %s_request_bytes, sizeof(%s_request_bytes));\n", req, pfx, pfx)
		fmt.Fprintf(c, "    if (length == 0u) {\n        return ROBOHUB_ERR_INVALID_ARG;\n    }\n")
		fmt.Fprintf(c, "    return robohub_core_event_publish(%s_REQUEST_EVENT_ID, %s_request_bytes, (rh_size)length);\n}\n\n", macroName(r.Name), pfx)

		fmt.Fprintf(c, "RoboHubError %s_publish_response(const %s* response)\n{\n", r.Name, resp)
		fmt.Fprintf(c, "    size_t length = %s_serialize(response, %s_response_bytes, sizeof(%s_response_bytes));\n", resp, pfx, pfx)
		fmt.Fprintf(c, "    if (length == 0u) {\n        return ROBOHUB_ERR_INVALID_ARG;\n    }\n")
		fmt.Fprintf(c, "    return robohub_core_event_publish(%s_RESPONSE_EVENT_ID, %s_response_bytes, (rh_size)length);\n}\n\n", macroName(r.Name), pfx)

		fmt.Fprintf(c, "static RoboHubError %s_on_request(robohub_event_id id, const void* payload, rh_size size, void* user)\n{\n", pfx)
		fmt.Fprintf(c, "    (void)id;\n")
		fmt.Fprintf(c, "    %s request;\n", req)
		fmt.Fprintf(c, "    if (!%s_deserialize((const uint8_t*)payload, (size_t)size, &request)) {\n        return ROBOHUB_ERR_PROTOCOL;\n    }\n", req)
		fmt.Fprintf(c, "    %s_subscription* subscription = (%s_subscription*)user;\n", r.Name, r.Name)
		fmt.Fprintf(c, "    %s response;\n    memset(&response, 0, sizeof(response));\n", resp)
		fmt.Fprintf(c, "    if (subscription->handler(&request, &response) != 0) {\n        return ROBOHUB_OK;\n    }\n")
		fmt.Fprintf(c, "    return %s_publish_response(&response);\n}\n\n", r.Name)

		fmt.Fprintf(c, "RoboHubError %s_subscribe(%s_handler handler, void* user)\n{\n", r.Name, r.Name)
		fmt.Fprintf(c, "    if (handler == 0) {\n        return ROBOHUB_ERR_INVALID_ARG;\n    }\n")
		fmt.Fprintf(c, "    for (size_t i = 0; i < RHPROTO_MAX_SUBSCRIBERS; i++) {\n")
		fmt.Fprintf(c, "        if (%s_subscribers[i].handler == 0) {\n", pfx)
		fmt.Fprintf(c, "            %s_subscribers[i].handler = handler;\n            %s_subscribers[i].user = user;\n", pfx, pfx)
		fmt.Fprintf(c, "            return robohub_core_event_subscribe(%s_REQUEST_EVENT_ID, %s_on_request, &%s_subscribers[i]);\n", macroName(r.Name), pfx, pfx)
		fmt.Fprintf(c, "        }\n    }\n    return ROBOHUB_ERR_NO_MEM;\n}\n\n")

		fmt.Fprintf(c, "RoboHubError %s_unsubscribe(%s_handler handler, void* user)\n{\n", r.Name, r.Name)
		fmt.Fprintf(c, "    for (size_t i = 0; i < RHPROTO_MAX_SUBSCRIBERS; i++) {\n")
		fmt.Fprintf(c, "        if (%s_subscribers[i].handler == handler && %s_subscribers[i].user == user) {\n", pfx, pfx)
		fmt.Fprintf(c, "            RoboHubError err = robohub_core_event_unsubscribe(%s_REQUEST_EVENT_ID, %s_on_request, &%s_subscribers[i]);\n", macroName(r.Name), pfx, pfx)
		fmt.Fprintf(c, "            %s_subscribers[i].handler = 0;\n            %s_subscribers[i].user = 0;\n            return err;\n", pfx, pfx)
		fmt.Fprintf(c, "        }\n    }\n    return ROBOHUB_OK;\n}\n\n")
	}

	h.WriteString("#ifdef __cplusplus\n}\n#endif\n")

	return h.String(), c.String()
}

func emitCWireHelpers(h *strings.Builder, p string) {
	fmt.Fprintf(h, "static inline void %s_put_u8(uint8_t* out, uint8_t v) { out[0] = v; }\n", p)
	fmt.Fprintf(h, "static inline uint8_t %s_get_u8(const uint8_t* in) { return in[0]; }\n", p)
	fmt.Fprintf(h, "static inline void %s_put_u16(uint8_t* out, uint16_t v) { out[0] = (uint8_t)(v & 0xFFu); out[1] = (uint8_t)((v >> 8) & 0xFFu); }\n", p)
	fmt.Fprintf(h, "static inline uint16_t %s_get_u16(const uint8_t* in) { return (uint16_t)((uint16_t)in[0] | ((uint16_t)in[1] << 8)); }\n", p)
	fmt.Fprintf(h, "static inline void %s_put_u32(uint8_t* out, uint32_t v) { for (int i = 0; i < 4; i++) { out[i] = (uint8_t)((v >> (8 * i)) & 0xFFu); } }\n", p)
	fmt.Fprintf(h, "static inline uint32_t %s_get_u32(const uint8_t* in) { uint32_t v = 0; for (int i = 0; i < 4; i++) { v |= (uint32_t)in[i] << (8 * i); } return v; }\n", p)
	fmt.Fprintf(h, "static inline void %s_put_u64(uint8_t* out, uint64_t v) { for (int i = 0; i < 8; i++) { out[i] = (uint8_t)((v >> (8 * i)) & 0xFFu); } }\n", p)
	fmt.Fprintf(h, "static inline uint64_t %s_get_u64(const uint8_t* in) { uint64_t v = 0; for (int i = 0; i < 8; i++) { v |= (uint64_t)in[i] << (8 * i); } return v; }\n", p)
	fmt.Fprintf(h, "static inline void %s_put_f32(uint8_t* out, float v) { uint32_t bits; memcpy(&bits, &v, 4); %s_put_u32(out, bits); }\n", p, p)
	fmt.Fprintf(h, "static inline float %s_get_f32(const uint8_t* in) { uint32_t bits = %s_get_u32(in); float v; memcpy(&v, &bits, 4); return v; }\n", p, p)
	fmt.Fprintf(h, "static inline void %s_put_f64(uint8_t* out, double v) { uint64_t bits; memcpy(&bits, &v, 8); %s_put_u64(out, bits); }\n", p, p)
	fmt.Fprintf(h, "static inline double %s_get_f64(const uint8_t* in) { uint64_t bits = %s_get_u64(in); double v; memcpy(&v, &bits, 8); return v; }\n\n", p, p)
}

func emitCSerialize(c *strings.Builder, l *layout, pfx string, m ast.MessageDecl, version int) {
	size := macroName(m.Name) + "_WIRE_SIZE"

	fmt.Fprintf(c, "size_t %s_serialize(const %s* value, uint8_t* out, size_t capacity)\n{\n", m.Name, m.Name)
	fmt.Fprintf(c, "    if (value == 0 || out == 0 || capacity < %s) {\n        return 0u;\n    }\n", size)
	fmt.Fprintf(c, "    size_t off = 0u;\n")
	fmt.Fprintf(c, "    %s_put_u8(out + off, (uint8_t)%d);\n    off += 1u;\n", pfx, version)
	for _, f := range m.Fields {
		emitCWrite(c, l, pfx, f, "value->"+snake(f.Name), "    ")
	}
	fmt.Fprintf(c, "    return off;\n}\n\n")

	fmt.Fprintf(c, "bool %s_deserialize(const uint8_t* data, size_t length, %s* out)\n{\n", m.Name, m.Name)
	fmt.Fprintf(c, "    if (data == 0 || out == 0 || length < %s) {\n        return false;\n    }\n", size)
	fmt.Fprintf(c, "    if (data[0] != (uint8_t)%d) {\n        return false;\n    }\n", version)
	fmt.Fprintf(c, "    size_t off = 1u;\n")
	for _, f := range m.Fields {
		emitCRead(c, l, pfx, f, "out->"+snake(f.Name), "    ")
	}
	fmt.Fprintf(c, "    return true;\n}\n\n")
}

func emitCWrite(b *strings.Builder, l *layout, pfx string, f ast.Field, access, indent string) {
	if f.TypeExpr.ArrayLen != nil {
		fmt.Fprintf(b, "%sfor (size_t i = 0; i < %du; i++) {\n", indent, *f.TypeExpr.ArrayLen)
		writeCElement(b, l, pfx, f.TypeExpr.Name, access+"[i]", indent+"    ")
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}
	if f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%smemcpy(out + off, %s, %du);\n%soff += %du;\n", indent, access, stringWire, indent, stringWire)
		return
	}
	writeCElement(b, l, pfx, f.TypeExpr.Name, access, indent)
}

func writeCElement(b *strings.Builder, l *layout, pfx, typeName, expr, indent string) {
	switch {
	case typeName == "string" || typeName == "u8" || typeName == "i8" || typeName == "bool":
		fmt.Fprintf(b, "%s%s_put_u8(out + off, (uint8_t)%s);\n%soff += 1u;\n", indent, pfx, expr, indent)
	case typeName == "u16" || typeName == "i16":
		fmt.Fprintf(b, "%s%s_put_u16(out + off, (uint16_t)%s);\n%soff += 2u;\n", indent, pfx, expr, indent)
	case typeName == "f32":
		fmt.Fprintf(b, "%s%s_put_f32(out + off, %s);\n%soff += 4u;\n", indent, pfx, expr, indent)
	case typeName == "u32" || typeName == "i32" || l.kind(typeName) == "enum":
		fmt.Fprintf(b, "%s%s_put_u32(out + off, (uint32_t)%s);\n%soff += 4u;\n", indent, pfx, expr, indent)
	case typeName == "f64":
		fmt.Fprintf(b, "%s%s_put_f64(out + off, %s);\n%soff += 8u;\n", indent, pfx, expr, indent)
	case typeName == "u64" || typeName == "i64":
		fmt.Fprintf(b, "%s%s_put_u64(out + off, (uint64_t)%s);\n%soff += 8u;\n", indent, pfx, expr, indent)
	case l.kind(typeName) == "message":
		fmt.Fprintf(b, "%sif (%s_serialize(&%s, out + off, capacity - off) == 0u) {\n%s    return 0u;\n%s}\n",
			indent, typeName, expr, indent, indent)
		fmt.Fprintf(b, "%soff += %s_WIRE_SIZE;\n", indent, macroName(typeName))
	default:
		fmt.Fprintf(b, "%s/* unknown type %s */\n", indent, typeName)
	}
}

func emitCRead(b *strings.Builder, l *layout, pfx string, f ast.Field, access, indent string) {
	if f.TypeExpr.ArrayLen != nil {
		fmt.Fprintf(b, "%sfor (size_t i = 0; i < %du; i++) {\n", indent, *f.TypeExpr.ArrayLen)
		readCElement(b, l, pfx, f.TypeExpr.Name, access+"[i]", indent+"    ")
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}
	if f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%smemcpy(%s, data + off, %du);\n%soff += %du;\n", indent, access, stringWire, indent, stringWire)
		return
	}
	readCElement(b, l, pfx, f.TypeExpr.Name, access, indent)
}

func readCElement(b *strings.Builder, l *layout, pfx, typeName, expr, indent string) {
	switch {
	case typeName == "string" || typeName == "u8":
		fmt.Fprintf(b, "%s%s = %s_get_u8(data + off);\n%soff += 1u;\n", indent, expr, pfx, indent)
	case typeName == "i8":
		fmt.Fprintf(b, "%s%s = (int8_t)%s_get_u8(data + off);\n%soff += 1u;\n", indent, expr, pfx, indent)
	case typeName == "bool":
		fmt.Fprintf(b, "%s%s = %s_get_u8(data + off) != 0u;\n%soff += 1u;\n", indent, expr, pfx, indent)
	case typeName == "u16":
		fmt.Fprintf(b, "%s%s = %s_get_u16(data + off);\n%soff += 2u;\n", indent, expr, pfx, indent)
	case typeName == "i16":
		fmt.Fprintf(b, "%s%s = (int16_t)%s_get_u16(data + off);\n%soff += 2u;\n", indent, expr, pfx, indent)
	case typeName == "f32":
		fmt.Fprintf(b, "%s%s = %s_get_f32(data + off);\n%soff += 4u;\n", indent, expr, pfx, indent)
	case typeName == "u32":
		fmt.Fprintf(b, "%s%s = %s_get_u32(data + off);\n%soff += 4u;\n", indent, expr, pfx, indent)
	case typeName == "i32":
		fmt.Fprintf(b, "%s%s = (int32_t)%s_get_u32(data + off);\n%soff += 4u;\n", indent, expr, pfx, indent)
	case l.kind(typeName) == "enum":
		fmt.Fprintf(b, "%s%s = (%s)%s_get_u32(data + off);\n%soff += 4u;\n", indent, expr, typeName, pfx, indent)
	case typeName == "f64":
		fmt.Fprintf(b, "%s%s = %s_get_f64(data + off);\n%soff += 8u;\n", indent, expr, pfx, indent)
	case typeName == "u64":
		fmt.Fprintf(b, "%s%s = %s_get_u64(data + off);\n%soff += 8u;\n", indent, expr, pfx, indent)
	case typeName == "i64":
		fmt.Fprintf(b, "%s%s = (int64_t)%s_get_u64(data + off);\n%soff += 8u;\n", indent, expr, pfx, indent)
	case l.kind(typeName) == "message":
		fmt.Fprintf(b, "%sif (!%s_deserialize(data + off, length - off, &%s)) {\n%s    return false;\n%s}\n",
			indent, typeName, expr, indent, indent)
		fmt.Fprintf(b, "%soff += %s_WIRE_SIZE;\n", indent, macroName(typeName))
	default:
		fmt.Fprintf(b, "%s/* unknown type %s */\n", indent, typeName)
	}
}
