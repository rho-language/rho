// EmitGo renders the schema as Go: a struct per message with the JSON tags an
// edge or cloud service already speaks, and MarshalBinary/UnmarshalBinary that
// write the same little-endian wire the C side reads, so one schema has one
// layout on both ends. Each rpc gets a Register that puts its handler on a mux.
func (s *Schema) EmitGo(packageName string) string {
	if packageName == "" {
		packageName = "protocol"
	}
	l := s.newLayout()
	messages := s.AllMessages()

	hasMessages := len(messages) > 0
	usesFloat := false
	for _, m := range messages {
		if messageUsesFloat(m) {
			usesFloat = true
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by rho protocol from namespace %s. Do not edit.\n",
		namespaceOr(s.Namespace, "(none)"))
	fmt.Fprintf(&b, "package %s\n\n", packageName)

	imports := []string{}
	if len(s.Rpcs) > 0 {
		imports = append(imports, "\"encoding/json\"", "\"net/http\"")
	}
	if hasMessages {
		imports = append(imports, "\"encoding/binary\"", "\"errors\"")
	}
	if usesFloat {
		imports = append(imports, "\"math\"")
	}
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, one := range imports {
			fmt.Fprintf(&b, "\t%s\n", one)
		}
		b.WriteString(")\n\n")
	}

	fmt.Fprintf(&b, "// SchemaVersion is the version byte every message begins with.\nconst SchemaVersion = %d\n\n", s.Version)

	for _, e := range s.Enums {
		fmt.Fprintf(&b, "type %s int32\n\nconst (\n", e.Name)
		for _, v := range e.Variants {
			fmt.Fprintf(&b, "\t%s%s %s = %d\n", e.Name, v.Name, e.Name, v.Value)
		}
		b.WriteString(")\n\n")
	}

	for _, m := range messages {
		fmt.Fprintf(&b, "// %sWireSize is %s on the wire, version byte included.\n", m.Name, m.Name)
		fmt.Fprintf(&b, "const %sWireSize = %d\n\n", m.Name, l.messageSize(m.Name))

		fmt.Fprintf(&b, "type %s struct {\n", m.Name)
		for _, f := range m.Fields {
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", exported(f.Name), l.goType(f), snake(f.Name))
		}
		b.WriteString("}\n\n")

		fmt.Fprintf(&b, "func (m *%s) MarshalBinary() ([]byte, error) {\n", m.Name)
		fmt.Fprintf(&b, "\tout := make([]byte, %sWireSize)\n", m.Name)
		b.WriteString("\tout[0] = SchemaVersion\n\toff := 1\n")
		for _, f := range m.Fields {
			emitGoWrite(&b, l, f, "m."+exported(f.Name), "\t")
		}
		b.WriteString("\treturn out, nil\n}\n\n")

		fmt.Fprintf(&b, "func (m *%s) UnmarshalBinary(data []byte) error {\n", m.Name)
		fmt.Fprintf(&b, "\tif len(data) < %sWireSize {\n\t\treturn errors.New(\"%s: short message\")\n\t}\n", m.Name, m.Name)
		b.WriteString("\tif data[0] != SchemaVersion {\n\t\treturn errors.New(\"protocol: schema version mismatch\")\n\t}\n")
		b.WriteString("\toff := 1\n")
		for _, f := range m.Fields {
			emitGoRead(&b, l, f, "m."+exported(f.Name), "\t")
		}
		b.WriteString("\treturn nil\n}\n\n")
	}

	for _, r := range s.Rpcs {
		fmt.Fprintf(&b, "// %sFunc serves rpc %s. Its body is the application's.\n", r.Name, r.Name)
		fmt.Fprintf(&b, "type %sFunc func(request %sRequest) (%sResponse, error)\n\n", r.Name, r.Name, r.Name)

		fmt.Fprintf(&b, "// Register%s puts rpc %s on a mux at the given path.\n", r.Name, r.Name)
		fmt.Fprintf(&b, "func Register%s(mux *http.ServeMux, path string, handler %sFunc) {\n", r.Name, r.Name)
		b.WriteString("\tmux.HandleFunc(path, func(w http.ResponseWriter, r *http.Request) {\n")
		fmt.Fprintf(&b, "\t\tvar request %sRequest\n", r.Name)
		b.WriteString("\t\tif err := json.NewDecoder(r.Body).Decode(&request); err != nil {\n")
		b.WriteString("\t\t\thttp.Error(w, err.Error(), http.StatusBadRequest)\n\t\t\treturn\n\t\t}\n")
		b.WriteString("\t\tresponse, err := handler(request)\n")
		b.WriteString("\t\tif err != nil {\n\t\t\thttp.Error(w, err.Error(), http.StatusInternalServerError)\n\t\t\treturn\n\t\t}\n")
		b.WriteString("\t\tw.Header().Set(\"Content-Type\", \"application/json\")\n")
		b.WriteString("\t\t_ = json.NewEncoder(w).Encode(response)\n\t})\n}\n\n")
	}

	return b.String()
}

func messageUsesFloat(m ast.MessageDecl) bool {
	for _, f := range m.Fields {
		if f.TypeExpr.Name == "f32" || f.TypeExpr.Name == "f64" {
			return true
		}
	}
	return false
}

func emitGoWrite(b *strings.Builder, l *layout, f ast.Field, access, indent string) {
	if f.TypeExpr.ArrayLen != nil && f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%scopy(out[off:off+%d], %s[:])\n%soff += %d\n", indent, *f.TypeExpr.ArrayLen, access, indent, *f.TypeExpr.ArrayLen)
		return
	}
	if f.TypeExpr.ArrayLen != nil {
		fmt.Fprintf(b, "%sfor i := 0; i < %d; i++ {\n", indent, *f.TypeExpr.ArrayLen)
		writeGoElement(b, l, f.TypeExpr.Name, access+"[i]", indent+"\t")
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}
	if f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%scopy(out[off:off+%d], %s)\n%soff += %d\n", indent, stringWire, access, indent, stringWire)
		return
	}
	writeGoElement(b, l, f.TypeExpr.Name, access, indent)
}

func writeGoElement(b *strings.Builder, l *layout, typeName, expr, indent string) {
	switch typeName {
	case "u8":
		fmt.Fprintf(b, "%sout[off] = %s\n%soff += 1\n", indent, expr, indent)
	case "i8":
		fmt.Fprintf(b, "%sout[off] = byte(%s)\n%soff += 1\n", indent, expr, indent)
	case "bool":
		fmt.Fprintf(b, "%sif %s {\n%s\tout[off] = 1\n%s} else {\n%s\tout[off] = 0\n%s}\n%soff += 1\n", indent, expr, indent, indent, indent, indent, indent)
	case "u16":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint16(out[off:], %s)\n%soff += 2\n", indent, expr, indent)
	case "i16":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint16(out[off:], uint16(%s))\n%soff += 2\n", indent, expr, indent)
	case "u32":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint32(out[off:], %s)\n%soff += 4\n", indent, expr, indent)
	case "i32":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint32(out[off:], uint32(%s))\n%soff += 4\n", indent, expr, indent)
	case "f32":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint32(out[off:], math.Float32bits(%s))\n%soff += 4\n", indent, expr, indent)
	case "u64":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint64(out[off:], %s)\n%soff += 8\n", indent, expr, indent)
	case "i64":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint64(out[off:], uint64(%s))\n%soff += 8\n", indent, expr, indent)
	case "f64":
		fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint64(out[off:], math.Float64bits(%s))\n%soff += 8\n", indent, expr, indent)
	default:
		if l.kind(typeName) == "enum" {
			fmt.Fprintf(b, "%sbinary.LittleEndian.PutUint32(out[off:], uint32(%s))\n%soff += 4\n", indent, expr, indent)
			return
		}
		if l.kind(typeName) == "message" {
			fmt.Fprintf(b, "%snested, err := %s.MarshalBinary()\n%sif err != nil {\n%s\treturn nil, err\n%s}\n", indent, expr, indent, indent, indent)
			fmt.Fprintf(b, "%scopy(out[off:], nested)\n%soff += %sWireSize\n", indent, indent, typeName)
			return
		}
		fmt.Fprintf(b, "%s// unknown type %s\n", indent, typeName)
	}
}

func emitGoRead(b *strings.Builder, l *layout, f ast.Field, access, indent string) {
	if f.TypeExpr.ArrayLen != nil && f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%scopy(%s[:], data[off:off+%d])\n%soff += %d\n", indent, access, *f.TypeExpr.ArrayLen, indent, *f.TypeExpr.ArrayLen)
		return
	}
	if f.TypeExpr.ArrayLen != nil {
		fmt.Fprintf(b, "%sfor i := 0; i < %d; i++ {\n", indent, *f.TypeExpr.ArrayLen)
		readGoElement(b, l, f.TypeExpr.Name, access+"[i]", indent+"\t")
		fmt.Fprintf(b, "%s}\n", indent)
		return
	}
	if f.TypeExpr.Name == "string" {
		fmt.Fprintf(b, "%s%s = string(data[off : off+%d])\n%soff += %d\n", indent, access, stringWire, indent, stringWire)
		return
	}
	readGoElement(b, l, f.TypeExpr.Name, access, indent)
}

func readGoElement(b *strings.Builder, l *layout, typeName, expr, indent string) {
	switch typeName {
	case "u8":
		fmt.Fprintf(b, "%s%s = data[off]\n%soff += 1\n", indent, expr, indent)
	case "i8":
		fmt.Fprintf(b, "%s%s = int8(data[off])\n%soff += 1\n", indent, expr, indent)
	case "bool":
		fmt.Fprintf(b, "%s%s = data[off] != 0\n%soff += 1\n", indent, expr, indent)
	case "u16":
		fmt.Fprintf(b, "%s%s = binary.LittleEndian.Uint16(data[off:])\n%soff += 2\n", indent, expr, indent)
	case "i16":
		fmt.Fprintf(b, "%s%s = int16(binary.LittleEndian.Uint16(data[off:]))\n%soff += 2\n", indent, expr, indent)
	case "u32":
		fmt.Fprintf(b, "%s%s = binary.LittleEndian.Uint32(data[off:])\n%soff += 4\n", indent, expr, indent)
	case "i32":
		fmt.Fprintf(b, "%s%s = int32(binary.LittleEndian.Uint32(data[off:]))\n%soff += 4\n", indent, expr, indent)
	case "f32":
		fmt.Fprintf(b, "%s%s = math.Float32frombits(binary.LittleEndian.Uint32(data[off:]))\n%soff += 4\n", indent, expr, indent)
	case "u64":
		fmt.Fprintf(b, "%s%s = binary.LittleEndian.Uint64(data[off:])\n%soff += 8\n", indent, expr, indent)
	case "i64":
		fmt.Fprintf(b, "%s%s = int64(binary.LittleEndian.Uint64(data[off:]))\n%soff += 8\n", indent, expr, indent)
	case "f64":
		fmt.Fprintf(b, "%s%s = math.Float64frombits(binary.LittleEndian.Uint64(data[off:]))\n%soff += 8\n", indent, expr, indent)
	default:
		if l.kind(typeName) == "enum" {
			fmt.Fprintf(b, "%s%s = %s(binary.LittleEndian.Uint32(data[off:]))\n%soff += 4\n", indent, expr, typeName, indent)
			return
		}
		if l.kind(typeName) == "message" {
			fmt.Fprintf(b, "%sif err := %s.UnmarshalBinary(data[off:]); err != nil {\n%s\treturn err\n%s}\n", indent, expr, indent, indent)
			fmt.Fprintf(b, "%soff += %sWireSize\n", indent, typeName)
			return
		}
		fmt.Fprintf(b, "%s// unknown type %s\n", indent, typeName)
	}
}
