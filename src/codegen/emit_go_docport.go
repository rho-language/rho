//
// @file emit_go_docport.go
// @brief The documentation port.
//
// The rho-doc library is the interface a caller sees, the way a header is: it
// declares the functions a service calls and nothing more. This is the
// implementation behind it, supplied by the backend so a project that depends
// on the component gets the generator without carrying it.
//
// A project asks for the port by name:
//
//	targets:
//	  - id: go
//	    ports:
//	      - docemit
//
// The implementation calls the component rather than inlining a generator. That
// is late binding, the same way the CLI reaches a component at run time: the
// component is a separate process, so a project that documents itself and a
// command that builds a site run the same code, and neither holds a copy of it.
// Documentation is not a hot path, so a call per request is the right trade for
// one implementation instead of two.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: MIT
//

package codegen

import (
	"rho/src/ir"
)

// emitDocPort renders the implementation of the documentation port.
func emitDocPort(m ir.ModuleIR) ([]string, string) {
	imports := []string{
		`"fmt"`,
		`"os"`,
		`"os/exec"`,
		`"strings"`,
	}
	return imports, `// Generated by the docemit port. The documentation generator is a
// component, so it is reached as a process rather than compiled in: the page a
// service renders and the page a build writes come from one implementation.

// rhoDocBinary is the generator a ported project calls.
//
// The Rho CLI is preferred, because it is what publishes the component's
// command and therefore what a reader would type. A project that reached this
// code from a copy of the component directly still has RHO_BIN set to it, so
// one of the two is always there.
func rhoDocBinary() string {
	if binary := strings.TrimSpace(os.Getenv("RHO_BIN")); binary != "" {
		return binary
	}
	for _, candidate := range []string{"rho", "rho-doc"} {
		if resolved, err := exec.LookPath(candidate); err == nil {
			return resolved
		}
	}
	return ""
}

// rhoDocCall runs the generator and returns what it answered.
//
// A generator that cannot be reached is not a crash: the caller gets an empty
// answer, because a service that cannot document itself should still serve
// whatever else it has. The reason goes to standard error, where whoever
// started the process can see it.
func rhoDocCall(arguments ...string) (string, error) {
	binary := rhoDocBinary()
	if binary == "" {
		return "", fmt.Errorf("no documentation generator found; install the rho-doc component")
	}
	command := exec.Command(binary, append([]string{"doc", "--fragment"}, arguments...)...)
	command.Stdin = strings.NewReader("")
	var stdout, stderr strings.Builder
	command.Stdout = &stdout
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		return "", fmt.Errorf("%s doc: %v: %s", binary, err, strings.TrimSpace(stderr.String()))
	}
	return stdout.String(), nil
}

// rhoDocRender renders a doc-as-code source and returns the page it becomes.
//
// The names here are the ones the Go backend calls: a library's externs are
// wrapped as <library><name>, so a port supplies those and the wrapper around
// them is generated.
func rhoDocRender(source string, path string) string {
	binary := rhoDocBinary()
	if binary == "" {
		fmt.Fprintln(os.Stderr, "rho doc: no documentation generator found; install the rho-doc component")
		return ""
	}
	// The source arrives on standard input: a page can be larger than a command
	// line comfortably carries.
	command := exec.Command(binary, "doc", "--fragment", "render", path)
	command.Stdin = strings.NewReader(source)
	var stdout, stderr strings.Builder
	command.Stdout = &stdout
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		fmt.Fprintf(os.Stderr, "rho doc: %v: %s\n", err, strings.TrimSpace(stderr.String()))
		return ""
	}
	return stdout.String()
}

// rhoDocBuildSite documents a tree and returns its index, as tab-separated lines.
func rhoDocBuildSite(root string, title string) string {
	answer, err := rhoDocCall("site", root, title)
	if err != nil {
		fmt.Fprintf(os.Stderr, "rho doc: %v\n", err)
		return ""
	}
	return answer
}

// rhoDocGenerateApi returns the API reference of a tree, as tab-separated lines.
func rhoDocGenerateApi(root string) string {
	answer, err := rhoDocCall("api", root)
	if err != nil {
		fmt.Fprintf(os.Stderr, "rho doc: %v\n", err)
		return ""
	}
	return answer
}

// rhoDocCheck returns the problems a documentation build found, one per line.
func rhoDocCheck(root string) string {
	answer, err := rhoDocCall("diagnostics", root)
	if err != nil {
		fmt.Fprintf(os.Stderr, "rho doc: %v\n", err)
		return ""
	}
	return answer
}

// rhoDocWriteSite builds a site into a directory and returns the number of pages
// written, or 0 when the build failed. rhoDocCheck says why.
func rhoDocWriteSite(root string, out string, title string) uint32 {
	answer, err := rhoDocCall("write", root, out, title)
	if err != nil {
		fmt.Fprintf(os.Stderr, "rho doc: %v\n", err)
		return 0
	}
	pages := 0
	for _, r := range strings.TrimSpace(answer) {
		if r < '0' || r > '9' {
			return 0
		}
		pages = pages*10 + int(r-'0')
	}
	return uint32(pages)
}
`
}
