//
// @file emit_go_openapiport.go
// @brief The port that puts a service's own API description into it.
//
// A service that publishes an API contract should publish it from the same
// place a client can read it: at its own address, as a file, at the one path
// everybody looks for. `GET /openapi.json` is what a portal, a client
// generator or a curious reader reaches for, and a service that answers it is a
// service that describes itself where it is.
//
// The description is written at generation time rather than at start-up, and
// embedded as a constant. That is deliberate: the routes of a running service
// are the routes it was built with, so a document computed at start-up would be
// the same document computed more slowly — and a start-up that reads and parses
// Rho sources is a start-up that can fail for a reason nobody can fix at
// runtime.
//
// The component that writes it is reached the way the documentation generator
// is reached: as a process, at generation time. A build host needs the
// component installed, and a build host that has it gets a service which
// describes itself; one that does not gets a service that answers with a
// sentence saying so, because a service that cannot describe itself should
// still serve everything else it has.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: Apache-2.0
//

package codegen

import (
	"fmt"
	"os/exec"
	"strings"
)

// OpenAPICommand is the command that writes a service's API description.
const OpenAPICommand = "openapi"

// emitOpenAPIPort renders the description a target asked for, as a constant the
// service serves.
//
// The document is produced by asking the component, which reads the project the
// same way the build did. Asking the component rather than writing the document
// here keeps one reader of the sources: a second one in the core would be a
// second dialect, and the two would eventually disagree about a service that
// compiles.
func emitOpenAPIPort(ctx PortContext) ([]string, string) {
	document, err := renderOpenAPI(ctx)
	// The description is written as a Go raw string, and a raw string cannot
	// hold a backtick. A document never contains one — it is JSON — but a
	// description a person wrote could, so the quoting is not assumed.
	body := quotedGoString(document)

	var b strings.Builder
	b.WriteString(`// Generated by the openapiemit port. The description is written when the
// project is generated, from the routes the compiler reads, and served as it
// was written: what a service says about itself is what it was built with.

// openapiDocument is this service's OpenAPI 3.1 description.
`)
	if err != nil {
		// A service whose description could not be written still serves. What
		// it answers with is the reason, so a reader learns why rather than
		// finding nothing at all.
		fmt.Fprintf(&b, "const openapiDescriptionUnavailable = %q\n\n",
			fmt.Sprintf("no OpenAPI description was generated: %v", err))
		b.WriteString(`// openapiDocument returns the description, or the reason there is none.
func openapiDocument() string { return openapiDescriptionUnavailable }
`)
		return []string{}, b.String()
	}

	fmt.Fprintf(&b, "const openapiDescription = %s\n", body)
	b.WriteString(`
// openapiDocument returns the description.
func openapiDocument() string { return openapiDescription }
`)
	return []string{}, b.String()
}

// renderOpenAPI asks the component for a project's API description.
func renderOpenAPI(ctx PortContext) (string, error) {
	root := ctx.ProjectRoot
	if root == "" {
		root = "."
	}
	// The address a service answers at is a deployment fact, so it is not
	// written into the document. A reader who has the document has the service's
	// address already: it is where the document came from.
	command := exec.Command("rho", OpenAPICommand, "generate", root)
	var stdout, stderr strings.Builder
	command.Stdout = &stdout
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		detail := strings.TrimSpace(stderr.String())
		if detail != "" {
			return "", fmt.Errorf("%v: %s", err, detail)
		}
		return "", err
	}
	document := stdout.String()
	if strings.TrimSpace(document) == "" {
		return "", fmt.Errorf("the %s command wrote nothing", OpenAPICommand)
	}
	return document, nil
}

// quotedGoString writes a string as a Go literal, which is an interpreted
// string rather than a raw one: a document is JSON and holds no backtick today,
// and a quoting that does not care is one less thing that can be wrong
// tomorrow.
func quotedGoString(value string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range value {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
