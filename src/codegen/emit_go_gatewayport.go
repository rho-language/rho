//
// @file emit_go_gatewayport.go
// @brief The gateway port: serial, UDP, time, shared state and tx correlation.
//
// A Rho program has no heap, no globals and no I/O. A gateway that reads a
// serial link, streams over UDP and answers HTTP needs all three, and the parts
// it cannot express are exactly the parts only a host can do: open a tty, write
// a datagram, read a clock, and hold the little state two goroutines share.
//
// This port supplies those, and nothing else. The frame grammar — COBS
// delineation, the Fletcher-16 check, the header — stays in the Rho program
// that asked for the port, so what crosses the wire is something a reader of
// the gateway can see rather than something buried in generated Go.
//
// A project asks for the port by name:
//
//	targets:
//	  - id: go-server
//	    ports:
//	      - gateway
//
// Configuration is the environment, because it is deployment that changes it:
// SERIAL_PORT, SERIAL_BAUD and PLOTJUGGLER_ADDR.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: Apache-2.0
//

package codegen

// emitGatewayPort renders the gateway port: the host primitives a Rho gateway
// declares as `extern fn` and nothing more.
func emitGatewayPort(ctx PortContext) ([]string, string) {
	imports := []string{
		`"bytes"`,
		`"fmt"`,
		`"net"`,
		`"os"`,
		`"strconv"`,
		`"strings"`,
		`"sync"`,
		`"syscall"`,
		`"time"`,
		`"unsafe"`,
	}
	return imports, `// Generated by the gateway port.

// The defaults a deployment overrides. A gateway on another machine names its
// own device and its own collector; the defaults are the lab setup.
const (
	gatewayDefaultSerial = "/dev/ttyACM0"
	gatewayDefaultBaud   = 115200
	gatewayDefaultPlot   = "127.0.0.1:9870"
)

var (
	// The serial link, opened once. A read and a write that race to open it
	// reach the same file because the open is behind a sync.Once.
	gatewaySerialOnce sync.Once
	gatewaySerial     *os.File
	gatewaySerialOK   bool
	// bytes that arrived without a delimiter yet, so a frame split across two
	// reads is still one frame.
	gatewayRx []byte

	// The UDP collector, opened once.
	gatewayUDPOnce   sync.Once
	gatewayUDPSocket net.Conn

	// The state two goroutines share: the serial reader writes it, an HTTP
	// handler reads it. It is a string map so the port stays generic; the Rho
	// program decides what the keys mean.
	gatewayStateMu sync.RWMutex
	gatewayState   = map[string]string{}

	// Active RPC transactions. A handler registers a tx_id and waits on its
	// channel; the reader signals it when the matching response frame arrives.
	gatewayRpcMu      sync.Mutex
	gatewayRpcWaiters = map[uint32]chan string{}

	// The node ids a gateway has heard from, in the order they first sent, so a
	// listing can name the boards without the Rho program keeping its own set.
	gatewayNodesMu sync.Mutex
	gatewayNodes   []uint32

	// A monotonic origin, so a timestamp is a duration and not a wall clock
	// that can step backwards.
	gatewayStart = time.Now()
)

// gatewayNodeSeen records a node id once, in arrival order.
func gatewayNodeSeen(id uint32) {
	if id == 0 {
		return
	}
	gatewayNodesMu.Lock()
	for _, seen := range gatewayNodes {
		if seen == id {
			gatewayNodesMu.Unlock()
			return
		}
	}
	if len(gatewayNodes) < 64 {
		gatewayNodes = append(gatewayNodes, id)
	}
	gatewayNodesMu.Unlock()
}

// gatewayNodeCount and gatewayNodeAt are the read side of that set.
func gatewayNodeCount() uint32 {
	gatewayNodesMu.Lock()
	count := len(gatewayNodes)
	gatewayNodesMu.Unlock()
	return uint32(count)
}

func gatewayNodeAt(index uint32) uint32 {
	gatewayNodesMu.Lock()
	defer gatewayNodesMu.Unlock()
	if int(index) >= len(gatewayNodes) {
		return 0
	}
	return gatewayNodes[index]
}

// gatewayConfig maps the names a RoboHub deployment sets onto the ones the
// generated service reads. REST_PORT is the gateway's name for the listener;
// the generated server reads RHO_HTTP_ADDR, so init() calls this before the
// address is chosen.
func gatewayConfig() {
	if os.Getenv("RHO_HTTP_ADDR") == "" {
		if port := strings.TrimSpace(os.Getenv("REST_PORT")); port != "" {
			os.Setenv("RHO_HTTP_ADDR", ":"+port)
		}
	}
}

// gatewayOpenSerial opens SERIAL_PORT at SERIAL_BAUD, once.
func gatewayOpenSerial() bool {
	gatewaySerialOnce.Do(func() {
		path := strings.TrimSpace(os.Getenv("SERIAL_PORT"))
		if path == "" {
			path = gatewayDefaultSerial
		}
		baud := uint32(gatewayDefaultBaud)
		if raw := strings.TrimSpace(os.Getenv("SERIAL_BAUD")); raw != "" {
			if parsed, err := strconv.Atoi(raw); err == nil && parsed > 0 {
				baud = uint32(parsed)
			}
		}
		file, err := os.OpenFile(path, os.O_RDWR|syscall.O_NOCTTY|syscall.O_NONBLOCK, 0)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gateway: cannot open %s: %v\n", path, err)
			return
		}
		if err := gatewayConfigureTTY(file, baud); err != nil {
			fmt.Fprintf(os.Stderr, "gateway: cannot configure %s: %v\n", path, err)
			file.Close()
			return
		}
		gatewaySerial = file
		gatewaySerialOK = true
	})
	return gatewaySerialOK
}

// gatewayConfigureTTY sets the line to 8N1 at the given speed, raw.
func gatewayConfigureTTY(file *os.File, baud uint32) error {
	var tio syscall.Termios
	if _, _, errno := syscall.Syscall6(syscall.SYS_IOCTL, file.Fd(),
		syscall.TCGETS, uintptr(unsafe.Pointer(&tio)), 0, 0, 0); errno != 0 {
		return errno
	}
	speed := gatewayBaudConstant(baud)
	// Raw: no canonical line assembly, no echo, no output post-processing. A
	// COBS frame is delimited by 0x00 and is not a line, so a tty left in
	// canonical mode would hold it until a newline that never comes.
	tio.Iflag = 0
	tio.Oflag = 0
	tio.Lflag = 0
	tio.Cflag = syscall.CS8 | syscall.CREAD | syscall.CLOCAL | speed
	tio.Ispeed = speed
	tio.Ospeed = speed
	tio.Cc[syscall.VMIN] = 1
	tio.Cc[syscall.VTIME] = 0
	if _, _, errno := syscall.Syscall6(syscall.SYS_IOCTL, file.Fd(),
		syscall.TCSETS, uintptr(unsafe.Pointer(&tio)), 0, 0, 0); errno != 0 {
		return errno
	}
	return nil
}

// gatewayBaudConstant maps a number to the termios speed constant.
func gatewayBaudConstant(baud uint32) uint32 {
	switch baud {
	case 9600:
		return syscall.B9600
	case 19200:
		return syscall.B19200
	case 38400:
		return syscall.B38400
	case 57600:
		return syscall.B57600
	case 230400:
		return syscall.B230400
	default:
		return syscall.B115200
	}
}

// gatewaySerialStart asks for the link, for a program to report at startup.
func gatewaySerialStart() bool { return gatewayOpenSerial() }

// gatewaySerialRead returns one COBS frame: the bytes between two delimiters,
// the delimiter consumed. It waits at most timeoutMs and returns "" on timeout
// or when the link is not open, so a caller never sees a frame it did not get.
func gatewaySerialRead(timeoutMs uint32) string {
	if !gatewayOpenSerial() {
		return ""
	}
	deadline := time.Now().Add(time.Duration(timeoutMs) * time.Millisecond)
	buf := make([]byte, 256)
	for {
		if index := bytes.IndexByte(gatewayRx, 0x00); index >= 0 {
			frame := string(gatewayRx[:index])
			rest := append([]byte(nil), gatewayRx[index+1:]...)
			gatewayRx = rest
			return frame
		}
		n, err := gatewaySerial.Read(buf)
		if n > 0 {
			gatewayRx = append(gatewayRx, buf[:n]...)
			// A line that never delimits is a line that is not speaking this
			// protocol; drop it rather than grow without bound.
			if len(gatewayRx) > 8192 {
				gatewayRx = gatewayRx[:0]
			}
			continue
		}
		if err != nil && err != syscall.EAGAIN && err != syscall.EWOULDBLOCK && err != syscall.EINTR {
			return ""
		}
		if timeoutMs == 0 || !time.Now().Before(deadline) {
			return ""
		}
		time.Sleep(time.Millisecond)
	}
}

// gatewaySerialWrite writes a frame and its delimiter. A write that would block
// is retried until the line drains, because a caller has nowhere to put it.
func gatewaySerialWrite(data string) bool {
	if !gatewayOpenSerial() {
		return false
	}
	out := make([]byte, 0, len(data)+1)
	out = append(out, data...)
	out = append(out, 0x00)
	for len(out) > 0 {
		n, err := gatewaySerial.Write(out)
		if n > 0 {
			out = out[n:]
			continue
		}
		if err != nil && err != syscall.EAGAIN && err != syscall.EWOULDBLOCK && err != syscall.EINTR {
			return false
		}
		time.Sleep(time.Millisecond)
	}
	return true
}

// gatewayUdpStart opens the collector socket, once.
func gatewayUdpStart() bool {
	gatewayUDPOnce.Do(func() {
		addr := strings.TrimSpace(os.Getenv("PLOTJUGGLER_ADDR"))
		if addr == "" {
			addr = gatewayDefaultPlot
		}
		conn, err := net.Dial("udp", addr)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gateway: cannot reach %s: %v\n", addr, err)
			return
		}
		gatewayUDPSocket = conn
	})
	return gatewayUDPSocket != nil
}

// gatewayUdpSend writes one datagram, fire and forget.
func gatewayUdpSend(text string) bool {
	if !gatewayUdpStart() {
		return false
	}
	_, err := gatewayUDPSocket.Write([]byte(text))
	return err == nil
}

// gatewayNowMs is milliseconds since the gateway started.
func gatewayNowMs() uint32 { return uint32(time.Since(gatewayStart).Milliseconds()) }

// gatewayF32Str renders a float with the two decimals a telemetry frame carries.
func gatewayF32Str(value float32) string {
	return strconv.FormatFloat(float64(value), 'f', 2, 32)
}

// gatewayStateSet stores a value under a key.
func gatewayStateSet(key string, value string) {
	gatewayStateMu.Lock()
	gatewayState[key] = value
	gatewayStateMu.Unlock()
}

// gatewayStateGet reads a value, or "" when the key is unset.
func gatewayStateGet(key string) string {
	gatewayStateMu.RLock()
	value := gatewayState[key]
	gatewayStateMu.RUnlock()
	return value
}

// gatewayStateSetU32 and gatewayStateGetU32 are the typed views a handler uses.
func gatewayStateSetU32(key string, value uint32) {
	gatewayStateSet(key, strconv.FormatUint(uint64(value), 10))
}

func gatewayStateGetU32(key string) uint32 {
	parsed, _ := strconv.ParseUint(gatewayStateGet(key), 10, 32)
	return uint32(parsed)
}

func gatewayStateSetF32(key string, value float32) {
	gatewayStateSet(key, gatewayF32Str(value))
}

func gatewayStateGetF32(key string) float32 {
	parsed, _ := strconv.ParseFloat(gatewayStateGet(key), 32)
	return float32(parsed)
}

// gatewayRpcRegister creates the channel a response will be delivered to.
func gatewayRpcRegister(tx uint32) {
	gatewayRpcMu.Lock()
	if gatewayRpcWaiters[tx] == nil {
		gatewayRpcWaiters[tx] = make(chan string, 1)
	}
	gatewayRpcMu.Unlock()
}

// gatewayRpcWait blocks until the response frame arrives or the timeout passes.
func gatewayRpcWait(tx uint32, timeoutMs uint32) string {
	gatewayRpcMu.Lock()
	waiter := gatewayRpcWaiters[tx]
	gatewayRpcMu.Unlock()
	if waiter == nil {
		return ""
	}
	select {
	case payload := <-waiter:
		gatewayRpcMu.Lock()
		delete(gatewayRpcWaiters, tx)
		gatewayRpcMu.Unlock()
		return payload
	case <-time.After(time.Duration(timeoutMs) * time.Millisecond):
		gatewayRpcMu.Lock()
		delete(gatewayRpcWaiters, tx)
		gatewayRpcMu.Unlock()
		return ""
	}
}

// gatewayRpcSignal delivers a response to its waiter. It reports whether one was
// waiting, so the reader can log a response nobody asked for.
func gatewayRpcSignal(tx uint32, payload string) bool {
	gatewayRpcMu.Lock()
	waiter := gatewayRpcWaiters[tx]
	gatewayRpcMu.Unlock()
	if waiter == nil {
		return false
	}
	select {
	case waiter <- payload:
		return true
	default:
		return false
	}
}
`
}
