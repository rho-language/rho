//
// @file emit_go_sqlport.go
// @brief The sql port: a database for a generated Go project.
//
// A project that declares SQL gets a `queries.rho` of `extern fn`
// declarations, one per statement, and nothing implements them. This is what
// implements them.
//
// The boundary is drawn at the statement rather than at the driver. Everything
// below is `database/sql` and the standard library, so a project generated
// against sqlite runs unchanged against anything that driver registers — the
// name of the driver is a runtime fact read from the environment, and a program
// that was generated on a workstation and deployed to a service does not carry
// the workstation's driver with it.
//
// Nothing here allocates on the Rho side. A generated function takes a slice
// the caller owns and answers how many rows it wrote, which is what lets the
// same file run on a device with 2 KB of RAM and in a service with a garbage
// collector.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: Apache-2.0
//

package codegen

import (
	"fmt"
	"strings"
)

// emitSQLPort renders the implementation of the `std.sql` externs, which is the
// whole of the database surface a Rho program uses.
//
// The generated statements are not implemented here: each one is emitted by the
// rho-sql component alongside the Rho that declares it, so that a statement's
// text and the code that runs it are written from one reading. This port
// supplies the vocabulary — opening a database, preparing a statement, binding
// a value, reading a column — that those generated functions are written in.
func emitSQLPort(ctx PortContext) ([]string, string) {
	imports := []string{
		`"database/sql"`,
		`"fmt"`,
		`"os"`,
		`"strings"`,
		`"sync"`,
		`"time"`,
		`"unsafe"`,
	}
	// The driver is imported for what it does rather than for what it names: a
	// Go package registers itself with the standard library in its own
	// initialiser, and nothing about the driver is otherwise used here. A
	// project that asked for a driver this build does not know about gets no
	// import and the message below instead — a build that failed on a guessed
	// module path would be a failure the project cannot act on.
	if driver := ctx.SQLDriverPackage; driver != "" {
		imports = append(imports, `_ "`+driver+`"`)
	}
	return imports, sqlPortBody(ctx)
}

// sqlPortDriverEnv names the driver a generated project opens its database
// with, and sqlPortDatabaseEnv names the database itself.
//
// Both are the environment rather than generated constants because both are
// deployment facts. The same binary built once serves a development database
// and a production one, and a driver compiled into it would be a driver it
// could not be run without.
const (
	sqlPortDriverEnv   = "RHO_SQL_DRIVER"
	sqlPortDatabaseEnv = "RHO_SQL_DATABASE"
)

func sqlPortBody(ctx PortContext) string {
	var b strings.Builder
	b.WriteString(sqlPortHeader)
	b.WriteString(sqlPortSchema(ctx))
	b.WriteString(sqlPortRuntime)
	b.WriteString(sqlPortQueries(ctx))
	return b.String()
}

const sqlPortHeader = `// Generated by the Rho sql port.
//
// The database surface std.sql declares, implemented over database/sql. A
// project that generated its statements against one engine runs them against
// whatever driver the environment names, because the engine is a deployment
// decision and a compiled-in one would be a decision this build made for it.

`

// sqlPortSchema embeds the project's own DDL, so a service can create the
// tables its statements assume before it takes a request rather than on every
// one. Applying it twice is a service that was restarted against a database it
// created last time: the second application finds the tables and changes
// nothing.
//
// A project that generated no schema gets an empty one rather than a constant
// the compiler would reject, so a project that asked for the port without asking
// for SQL still builds.
func sqlPortSchema(ctx PortContext) string {
	schema := strings.TrimSpace(ctx.SQLSchema)
	if schema == "" {
		schema = "-- This project declared no schema.\n"
	}
	return "// rhoSqlSchema is the schema this project declared, written by rho sql.\n" +
		"const rhoSqlSchema = " + goQuoted(schema) + "\n\n"
}

const sqlPortRuntime = `
// rhoSqlStatement is a statement a caller prepared: the statement that takes
// values and the rows it produces, which are the two halves of running one.
//
// They are held together because a Rho caller holds one handle for both. A
// driver keeps them apart, and splitting them across two handles would mean a
// caller could hold a row set whose statement had been released — which is a
// use-after-free written in a language that cannot see it.
type rhoSqlStatement struct {
	stmt *sql.Stmt
	rows *sql.Rows
	// text is what was prepared, kept so a rewind can prepare it again: a
	// driver will not rewind a statement it has already run.
	text string
	// db is the handle it was prepared against, needed for the same reason.
	db uint64
	// args are the values bound to its parameters, by position, and are what
	// the next run executes it with.
	args []SqlValue
}

// The handles a Rho program holds, keyed by the raw address it was given.
//
// A handle is a pointer to nothing — an address Rho cannot look inside — so the
// only way to reach a database is to be handed one. That is the whole of the
// safety property: a program cannot forge a connection, so it cannot reach a
// database it was not given.
//
// The map is keyed by a number rather than by a pointer for the ordinary
// reason: a Go map cannot have a pointer key that it can also range over
// safely without holding the value's lifetime, and the address is what the Rho
// side carries anyway.
var (
	rhoSqlMu      sync.Mutex
	rhoSqlHandles = map[uint64]*sql.DB{}
	rhoSqlRows    = map[uint64]*rhoSqlStatement{}
	rhoSqlNextID  uint64
)

// rhoSqlLastMessage is the engine's own account of the last failure.
//
// A caller that gets a non-zero status and nothing else reads this, because a
// translated message would be a guess at which of a constraint, a missing
// column or an unopenable file actually happened.
var (
	rhoSqlMuMessage  sync.Mutex
	rhoSqlLastErrMsg string
)

func rhoSqlFail(err error) int32 {
	if err == nil {
		return 0
	}
	rhoSqlMuMessage.Lock()
	rhoSqlLastErrMsg = err.Error()
	rhoSqlMuMessage.Unlock()
	return 1
}

// rhoSqlMessage is the engine's own account of a failure, which is what a
// caller that cannot open its database is told.
func rhoSqlMessage(err error) string {
	if err == nil {
		return ""
	}
	return err.Error()
}

func rhoSqlRemember(err error) int32 {
	return rhoSqlFail(err)
}

// rhoSqlDriverName is the driver this process opens databases with.
func rhoSqlDriverName() string {
	if name := strings.TrimSpace(os.Getenv("` + sqlPortDriverEnv + `")); name != "" {
		return name
	}
	// sqlite is the default because it is the one driver that needs no server
	// to be running, which is what makes a generated program runnable on a
	// machine that has nothing but Go installed. A deployment that means
	// something else sets the variable.
	return "sqlite"
}

// rhoSqlDatabaseName is the database this process opens.
func rhoSqlDatabaseName() string {
	if name := strings.TrimSpace(os.Getenv("` + sqlPortDatabaseEnv + `")); name != "" {
		return name
	}
	return "registry.db"
}

// rhoSqlReportDriver reports, once, that the driver a deployment named is not
// registered in this binary.
//
// A driver is a Go package, and importing one into the port would put it in
// every generated project that asked for the port — whether or not it runs
// there. So the port looks a driver up by name and the program that has it
// registers it through the standard sql.Register.
//
// That makes a missing driver a message rather than a panic at the first
// statement: a service that cannot reach its database says which driver it
// wanted and stops, rather than answering requests with a failure nobody can
// interpret.
var rhoSqlDriverWarned sync.Map

// rhoSqlRebindDB is the handle a rewind re-prepares against. It is set
// immediately before the call that reads it, under the same lock discipline as
// the handle map itself.
var rhoSqlRebindDB uint64

func rhoSqlWarnDriver(name string) {
	if _, warned := rhoSqlDriverWarned.LoadOrStore(name, true); warned {
		return
	}
	fmt.Fprintf(os.Stderr,
		"rho: no driver named %q is registered in this program; the generated "+
			"database calls need the package that registers it, imported by the "+
			"main package of the generated project\n", name)
}

// stdSqlSqlOpen opens a database and hands Rho an opaque address for it.
//
// The address is a number Rho carries and cannot interpret, so the only way to
// name a connection is to be given one.
// stdSqlSqlOpen opens a database and answers the handle for it.
//
// The answer is a Result as an ordinary value, which is what a Rho caller reads:
// a database either opened or it did not, and the failure carries the engine's
// own message rather than a status a caller has to look up afterwards.
func stdSqlSqlOpen(path string) ResultSqlDbString {
	// A Result is a struct, so a failure is written rather than returned
	// alongside a value: the flag says which of the two fields a caller should
	// read, and the other holds the zero.
	opened := func(failure error) ResultSqlDbString {
		rhoSqlFail(failure)
		return ResultSqlDbString{isOk: false, ok: SqlDb{}, err: rhoSqlMessage(failure)}
	}
	rhoSqlMu.Lock()
	defer rhoSqlMu.Unlock()
	handle, err := sql.Open(rhoSqlDriverName(), path)
	if err != nil {
		rhoSqlWarnDriver(rhoSqlDriverName())
		return opened(err)
	}
	// A connection is checked here rather than at the first statement, so a
	// service that cannot reach its database finds out when it starts rather
	// than when a client happens to ask for a row.
	if err := handle.Ping(); err != nil {
		handle.Close()
		return opened(err)
	}
	rhoSqlNextID++
	rhoSqlHandles[rhoSqlNextID] = handle
	return ResultSqlDbString{isOk: true, ok: SqlDb{raw: rhoSqlNextID}, err: ""}
}

func stdSqlSqlClose(db SqlDb) {
	rhoSqlMu.Lock()
	defer rhoSqlMu.Unlock()
	if handle, ok := rhoSqlHandles[db.raw]; ok {
		handle.Close()
		delete(rhoSqlHandles, db.raw)
	}
}

func stdSqlSqlLastMessage(db SqlDb) string {
	rhoSqlMuMessage.Lock()
	defer rhoSqlMuMessage.Unlock()
	return rhoSqlLastErrMsg
}

// stdSqlSqlApply creates the tables the schema declares, and answers how many it
// made.
func stdSqlSqlApply(db SqlDb, schema string) uint32 {
	rhoSqlMu.Lock()
	handle, ok := rhoSqlHandles[db.raw]
	rhoSqlMu.Unlock()
	if !ok {
		return 0
	}
	if strings.TrimSpace(schema) == "" {
		schema = rhoSqlSchema
	}
	created := uint32(0)
	for _, statement := range rhoSqlStatements(schema) {
		if _, err := handle.Exec(statement); err != nil {
			// A table that already exists is what a restart looks like, not a
			// failure: the second application finds the tables and changes
			// nothing. Anything else is reported.
			if strings.Contains(err.Error(), "already exists") {
				continue
			}
			rhoSqlFail(err)
			return created
		}
		created++
	}
	return created
}

// rhoSqlStatements splits a schema into the statements it is made of.
//
// A schema is a sequence of CREATE statements, and a driver takes one at a
// time. Splitting is done on the statement boundary rather than on a semicolon
// alone so that a semicolon inside a string literal does not end a statement
// early — which is a real possibility in a default value.
func rhoSqlStatements(schema string) []string {
	out := []string{}
	current := strings.Builder{}
	inString := false
	for i := 0; i < len(schema); i++ {
		c := schema[i]
		switch {
		case c == '\'':
			inString = !inString
			current.WriteByte(c)
		case c == ';' && !inString:
			if statement := strings.TrimSpace(current.String()); statement != "" {
				out = append(out, statement)
			}
			current.Reset()
		default:
			current.WriteByte(c)
		}
	}
	if statement := strings.TrimSpace(current.String()); statement != "" {
		out = append(out, statement)
	}
	return out
}

// stdSqlSqlPrepare compiles a statement and hands Rho an opaque address for it.
//
// Preparing is separate from running because it is the only way to read a
// statement's shape, which is how a caller types a result rather than guessing
// at one from the select list.
func stdSqlSqlPrepare(db SqlDb, query string, stmt *SqlStmt) uint32 {
	rhoSqlMu.Lock()
	handle, ok := rhoSqlHandle(db.raw)
	if !ok {
		return 0
	}
	prepared, err := handle.Prepare(query)
	if err != nil {
		rhoSqlFail(err)
		return 0
	}
	// Preparing and running are one step on a driver: a prepared statement has
	// no rows of its own, it has to be queried for them. The handle a Rho
	// caller holds is therefore the row set, and stdSqlSqlRun steps it — which is what
	// the declared signature describes: prepare, then run, once per row.
	held := &rhoSqlStatement{stmt: prepared, text: query, db: db.raw}
	rhoSqlMu.Lock()
	rhoSqlNextID++
	rhoSqlRows[rhoSqlNextID] = held
	stmt.raw = rhoSqlNextID
	rhoSqlMu.Unlock()
	return 1
}

// stdSqlSqlRun steps a prepared statement once, answering whether it has another row,
// so a caller can walk a result a row at a time without holding every row in
// memory at once.
func stdSqlSqlRun(stmt SqlStmt, more PtrU32) uint32 {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok {
		return 0
	}
	// The first run executes the statement; later runs step the rows it
	// produced. Doing it here rather than at prepare time is what lets a caller
	// bind every value before the first row exists.
	if held.rows == nil {
		rows, err := held.stmt.Query(rhoSqlArgsOf(held.args)...)
		if err != nil {
			rhoSqlFail(err)
			rhoSqlSetMore(more, 0)
			return 1
		}
		held.rows = rows
	}
	if !held.rows.Next() {
		if err := held.rows.Err(); err != nil {
			// The walk is over either way; a failure is reported through the
			// message rather than by pretending another row is there.
			rhoSqlFail(err)
		}
		rhoSqlSetMore(more, 0)
		return 1
	}
	rhoSqlSetMore(more, 1)
	return 1
}

// rhoSqlSetMore answers whether another row is there.
//
// The answer is written through the address the caller gave rather than
// returned, because that is the shape the declaration has: a caller cannot read
// a Go pointer out of a Rho value, and a value it allocated is the only place a
// result can land.
func rhoSqlSetMore(more PtrU32, value uint32) {
	// The address is the caller's own, so writing through it is what the
	// declaration means. A zero address is a caller that asked for an answer
	// and gave nowhere to put it, which is not a failure worth reporting.
	if more.raw == 0 {
		return
	}
	*(*uint32)(unsafe.Pointer(uintptr(more.raw))) = value
}

// stdSqlSqlReset rewinds a prepared statement so it can be run again with new values,
// which is what makes a prepared statement worth preparing.
//
// The rows already produced are released, because a statement that has been
// rewound has not produced them yet.
func stdSqlSqlReset(stmt SqlStmt) uint32 {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok {
		return 0
	}
	if held.rows != nil {
		held.rows.Close()
		held.rows = nil
	}
	// A driver has no rewind for a statement that was already queried, so the
	// statement is re-prepared. That is what a rewind means at this boundary:
	// the same text, executed again, reading whatever the values now say.
	statement := held.text
	rhoSqlMu.Lock()
	rhoSqlRebindDB = held.db
	rhoSqlMu.Unlock()
	prepared, err := rhoSqlReprepare(statement)
	if err != nil {
		return uint32(rhoSqlFail(err))
	}
	held.stmt.Close()
	held.stmt = prepared
	return 1
}

func stdSqlSqlFinalize(stmt SqlStmt) {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	delete(rhoSqlRows, stmt.raw)
	rhoSqlMu.Unlock()
	if !ok {
		return
	}
	if held.rows != nil {
		held.rows.Close()
	}
	held.stmt.Close()
}

func stdSqlSqlColumnCount(stmt SqlStmt) uint32 {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok || held.rows == nil {
		return 0
	}
	// A statement that returns no columns is a write, and a write has none.
	columns, err := held.rows.Columns()
	if err != nil {
		rhoSqlFail(err)
		return 0
	}
	return uint32(len(columns))
}

func stdSqlSqlColumnName(stmt SqlStmt, index uint32) string {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok || held.rows == nil {
		return ""
	}
	columns, err := held.rows.Columns()
	if err != nil || int(index) >= len(columns) {
		return ""
	}
	return columns[index]
}

func stdSqlSqlColumnType(stmt SqlStmt, index uint32) string {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok || held.rows == nil {
		return ""
	}
	types, err := held.rows.ColumnTypes()
	if err != nil || int(index) >= len(types) {
		return ""
	}
	return types[index].DatabaseTypeName()
}

// stdSqlSqlExec runs a statement that changes rows, and answers how many it changed.
func stdSqlSqlExec(db SqlDb, name string, query string, values SliceSqlValue, affected PtrU32) uint32 {
	rhoSqlMu.Lock()
	handle, ok := rhoSqlHandle(db.raw)
	if !ok {
		return 0
	}
	result, err := handle.Exec(query, rhoSqlArgs(values)...)
	if err != nil {
		rhoSqlFail(err)
		return 0
	}
	// A driver that cannot say how many rows changed answers -1, which is a
	// fact about the statement rather than a failure, and the caller is told 0
	// rather than a number it would report as a change that did not happen.
	if rows, err := result.RowsAffected(); err == nil && rows > 0 {
		affected.raw = uint64(rows)
	}
	return 1
}

// stdSqlSqlReadColumn reads one column of the current row into a value.
//
// The value a caller passes is an address, so the row is read into storage of
// the port's own and copied across: the caller's memory is a raw address that
// this side cannot safely write through, and a read that faulted would take the
// process rather than report a value.
func stdSqlSqlReadColumn(stmt SqlStmt, index uint32, value PtrSqlValue) uint32 {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok || held.rows == nil {
		return 0
	}
	heldValue := SqlValue{}
	status := rhoSqlScanInto(held.rows, index, &heldValue)
	if status == 1 {
		// The handle carries the address of the caller's value; filling it is
		// the one place the port writes to memory Rho owns, so it happens
		// exactly once and only on success.
		*(*SqlValue)(unsafe.Pointer(uintptr(value.raw))) = heldValue
	}
	return uint32(status)
}

// stdSqlSqlBind binds a value to a parameter of a prepared statement, by position.
//
// The standard database/sql package has no bind-then-execute step: arguments
// are handed over at the moment the statement runs. So a bind records the value
// against the statement, and the run passes the recorded ones along. That is the
// same contract the Rho side declares — bind, then run — expressed in the terms
// the driver uses.
//
// A value is kept in the order it was bound rather than by index, because a
// database takes its arguments positionally and a statement that binds 1, 2, 3
// is a statement whose third argument is the third value bound.
func stdSqlSqlBind(stmt SqlStmt, index uint32, value SqlValue) uint32 {
	rhoSqlMu.Lock()
	held, ok := rhoSqlRows[stmt.raw]
	rhoSqlMu.Unlock()
	if !ok {
		return 0
	}
	// The value is a plain copy, so a caller that reuses its own storage after
	// binding still bound the value it had at the time.
	//
	// A gap in the positions is a null rather than a zero: a statement that
	// binds its second parameter and not its first has been given a NULL, and
	// that is what a database does with the value in that position.
	bound := value
	for int(index) >= len(held.args) {
		held.args = append(held.args, SqlValue{kind: 0, isNull: true})
	}
	held.args[index] = bound
	return 1
}

// rhoSqlArgsOf unpacks bound values as driver arguments.
func rhoSqlArgsOf(values []SqlValue) []any {
	out := make([]any, 0, len(values))
	for i := range values {
		out = append(out, rhoSqlArg(values[i]))
	}
	return out
}

// rhoSqlReprepare prepares a statement's text against the handle it came from.
func rhoSqlReprepare(text string) (*sql.Stmt, error) {
	rhoSqlMu.Lock()
	handle, ok := rhoSqlHandles[rhoSqlRebindDB]
	rhoSqlMu.Unlock()
	if !ok {
		return nil, fmt.Errorf("the database handle this statement belonged to is gone")
	}
	return handle.Prepare(text)
}

// rhoSqlHandle is the connection behind an opaque Rho handle, or nothing.
//
// It is the only way a generated function reaches a database, so a handle that
// was never handed out is a handle that resolves to nothing rather than to a
// connection some other request opened.
func rhoSqlHandle(raw uint64) (*sql.DB, bool) {
	rhoSqlMu.Lock()
	defer rhoSqlMu.Unlock()
	handle, ok := rhoSqlHandles[raw]
	return handle, ok
}

// rhoSqlBind is one generated parameter as a driver argument.
//
// The kind is written out at the call site because the parameter's own type is
// known there: a number is bound as a number, and a column that comes back as
// text where a number was declared is a fact about the database rather than a
// conversion this layer would paper over.
func rhoSqlBind(kind int, value any) any {
	if kind == 0 {
		return nil
	}
	return value
}

// rhoSqlText is one scanned column as text.
//
// A driver sends a string, bytes or a time for what a schema called text, and a
// caller that declared a string column should not have to know which of the
// three its driver chose. A NULL stays empty, because a column that is absent is
// a fact the row carries rather than a string it spells.
func rhoSqlText(value any) string {
	switch typed := value.(type) {
	case nil:
		return ""
	case string:
		return typed
	case []byte:
		return string(typed)
	case time.Time:
		return typed.Format(time.RFC3339Nano)
	case bool:
		if typed {
			return "true"
		}
		return "false"
	}
	return fmt.Sprint(value)
}

// rhoSqlArg is one Rho value as a driver argument.
//
// A value is typed rather than an untyped one because a value that crossed into
// a driver as text and came back as a float has already lost the digits the
// database was asked to store.
func rhoSqlArg(value SqlValue) any {
	switch value.kind {
	case 1:
		return value.integer
	case 2:
		return value.real
	case 3:
		return value.boolean
	case 4:
		return value.text
	case 5:
		return []byte(value.blob)
	}
	return nil
}

// rhoSqlArgs unpacks a Rho slice of values as driver arguments.
//
// A Rho slice is a raw address and a length rather than a Go slice, because the
// language does not promise the memory stays alive for as long as the reference
// does. The address is therefore used as what it is: a pointer to the first
// element, with the length deciding how many there are.
func rhoSqlArgs(values SliceSqlValue) []any {
	if values.ptr.raw == 0 || values.len == 0 {
		return nil
	}
	held := unsafe.Slice((*SqlValue)(unsafe.Pointer(uintptr(values.ptr.raw))), values.len)
	out := make([]any, 0, values.len)
	for i := range held {
		out = append(out, rhoSqlArg(held[i]))
	}
	return out
}

// rhoSqlScanInto reads one column of the current row into a Rho value.
//
// The row is scanned into an untyped value and then narrowed by what actually
// arrived, rather than scanned into the type the schema declared. A column that
// holds a string where a number was declared has to come back as what it is:
// coercing it would either fail or return a zero the caller would report as
// data.
func rhoSqlScanInto(rows *sql.Rows, index uint32, value *SqlValue) uint32 {
	// The whole row is scanned and one column is kept, because a driver scans a
	// row at a time and Rho has no way to say "give me the next one".
	columns, err := rows.Columns()
	if err != nil {
		return uint32(rhoSqlFail(err))
	}
	held := make([]any, len(columns))
	destinations := make([]any, len(columns))
	for i := range held {
		destinations[i] = &held[i]
	}
	if err := rows.Scan(destinations...); err != nil {
		return uint32(rhoSqlFail(err))
	}
	if int(index) >= len(held) {
		return 0
	}
	switch typed := held[index].(type) {
	case nil:
		value.isNull = true
	case int64:
		value.kind, value.integer = 1, typed
	case float64:
		value.kind, value.real = 2, typed
	case bool:
		value.kind, value.boolean = 3, typed
	case []byte:
		value.kind, value.text = 4, string(typed)
	case string:
		value.kind, value.text = 4, typed
	case time.Time:
		value.kind, value.text = 4, typed.Format(time.RFC3339Nano)
	default:
		value.kind, value.text = 4, fmt.Sprint(typed)
	}
	return 1
}
`

// sqlPortQueries renders one Go function per statement the project's generated
// Rho declares as an extern.
//
// The signature is the extern's, in Go's spelling, because that is the shape the
// compiler already emitted a call site for. A function that took something else
// would leave every call in the generated Rho referring to a function that does
// not exist.
//
// The body is the same three steps for every statement: prepare it, run it, and
// write the rows into the slice the caller owns. Nothing is allocated for a row
// and nothing is returned but a count, which is what lets the same function run
// on a device with a fixed heap and in a service with a collector.
func sqlPortQueries(ctx PortContext) string {
	if len(ctx.SQLQueries) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(`
// The statements this project generated. One function per named statement,
// each taking the values the statement takes, the handle, and a slice the
// caller owns, and answering how many rows it wrote into it.
`)
	for _, statement := range ctx.SQLQueries {
		writeSQLStatement(&b, statement)
	}
	return b.String()
}

// writeSQLStatement is one generated function.
func writeSQLStatement(b *strings.Builder, statement SQLStatement) {
	// The parameter order is the extern's: the values the statement takes, then
	// the handle, then the slice the caller owns. A call site the compiler
	// already emitted names them in this order, so a function that took them in
	// another would be called correctly and answered wrongly.
	parameters := []string{}
	for _, parameter := range statement.Parameters {
		parameters = append(parameters,
			fmt.Sprintf("%s %s", goFuncName(parameter.Name), parameter.GoType))
	}
	parameters = append(parameters, "db SqlDb")
	returnsRows := statement.Result != ""
	if returnsRows {
		parameters = append(parameters,
			fmt.Sprintf("out Slice%s", statement.Result), "capacity uint32")
	}

	if statement.Comment != "" {
		for _, line := range strings.Split(strings.TrimSpace(statement.Comment), "\n") {
			fmt.Fprintf(b, "// %s\n", line)
		}
	}
	fmt.Fprintf(b, "//\n//\t%s\n", oneLine(statement.SQL))
	// The name is lowered the way the compiler lowers a call site, because that
	// is what the generated Rho's call became. A port that spelled the extern as
	// it was written would define a function no call site names — the definition
	// would be there, and every call to it would be undefined.
	fmt.Fprintf(b, "func %s(%s) uint32 {\n", goFuncName(statement.Name), strings.Join(parameters, ", "))

	// A handle is a pointer to nothing, which a backend lowers to a raw
	// address. It is read as a number here rather than dereferenced, because
	// there is nothing on the other side that this side owns or may look at.
	b.WriteString("\thandle, ok := rhoSqlHandle(db.raw)\n")
	b.WriteString("\tif !ok {\n\t\treturn 0\n\t}\n")
	fmt.Fprintf(b, "\tprepared, err := handle.Prepare(%s)\n", goQuoted(statement.SQL))
	b.WriteString("\tif err != nil {\n\t\treturn 0\n\t}\n")
	b.WriteString("\tdefer prepared.Close()\n")

	// Each value is turned into the tagged form the driver is handed, so a
	// number is bound as a number and a string as a string. Coercing them all
	// to text is what makes a driver report a number back as a string and a
	// caller read a column that has quietly changed type.
	arguments := make([]string, 0, len(statement.Parameters))
	for _, parameter := range statement.Parameters {
		arguments = append(arguments,
			fmt.Sprintf("rhoSqlBind(%d, %s)", sqlValueKind(parameter), goFuncName(parameter.Name)))
	}

	if returnsRows {
		writeSQLSelect(b, statement, arguments)
	} else {
		writeSQLExec(b, statement, arguments)
	}
	b.WriteString("\treturn 0\n}\n")
}

// writeSQLExec is a statement that changes rows rather than returning them.
func writeSQLExec(b *strings.Builder, statement SQLStatement, arguments []string) {
	if !statement.Affected {
		fmt.Fprintf(b, "\tif _, err := prepared.Exec(%s); err == nil {\n\t\treturn 1\n\t}\n",
			strings.Join(arguments, ", "))
		return
	}
	// A write reports how many rows it changed, which is the only thing a caller
	// can judge it by: a write that returns nothing else succeeded or did not.
	fmt.Fprintf(b, "\tresult, err := prepared.Exec(%s)\n", strings.Join(arguments, ", "))
	b.WriteString("\tif err != nil {\n\t\treturn 0\n\t}\n")
	b.WriteString("\tif rows, err := result.RowsAffected(); err == nil && rows > 0 {\n")
	b.WriteString("\t\treturn uint32(rows)\n\t}\n")
}

// writeSQLSelect is a statement that returns rows.
func writeSQLSelect(b *strings.Builder, statement SQLStatement, arguments []string) {
	fmt.Fprintf(b, "\trows, err := prepared.Query(%s)\n", strings.Join(arguments, ", "))
	b.WriteString("\tif err != nil {\n\t\treturn 0\n\t}\n")
	b.WriteString("\tdefer rows.Close()\n")
	b.WriteString("\tvar wrote uint32\n")
	b.WriteString("\tfor wrote < capacity && rows.Next() {\n")
	b.WriteString("\t\tvar row " + statement.Result + "\n")
	// Every column is read into untyped storage first, because a driver hands
	// back what it has rather than what the schema declared. Narrowing happens
	// per column below, so a column holding text where a number was declared
	// comes back as text instead of being reported as a zero.
	fmt.Fprintf(b, "\t\tvar scanned [%d]any\n", len(statement.Fields))
	fmt.Fprintf(b, "\t\tif err := rows.Scan(%s); err == nil {\n",
		strings.Join(scanDestinations(statement.Fields), ", "))
	for index, field := range statement.Fields {
		writeSQLNarrow(b, field, index)
	}
	b.WriteString("\t\t\tif out.ptr.raw != 0 {\n")
	fmt.Fprintf(b, "\t\t\t\tunsafe.Slice((*%s)(unsafe.Pointer(uintptr(out.ptr.raw))), capacity)[wrote] = row\n", statement.Result)
	b.WriteString("\t\t\t}\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\twrote++\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn wrote\n")
}

// writeSQLNarrow moves one scanned column into its struct field.
func writeSQLNarrow(b *strings.Builder, field SQLField, index int) {
	source := fmt.Sprintf("scanned[%d]", index)
	target := fmt.Sprintf("row.%s", goFieldName(field.Name))
	switch {
	case field.IsBoolean:
		fmt.Fprintf(b, "\t\t\tif value, ok := %s.(bool); ok {\n\t\t\t\t%s = value\n\t\t\t}\n", source, target)
	case field.IsInteger:
		fmt.Fprintf(b, "\t\t\tif value, ok := %s.(int64); ok {\n\t\t\t\t%s = value\n\t\t\t}\n", source, target)
	case field.IsFloat:
		fmt.Fprintf(b, "\t\t\tif value, ok := %s.(float64); ok {\n\t\t\t\t%s = value\n\t\t\t}\n", source, target)
	case field.IsBlob:
		fmt.Fprintf(b, "\t\t\tif value, ok := %s.([]byte); ok {\n\t\t\t\t%s = string(value)\n\t\t\t}\n", source, target)
	default:
		// A text column is read from whatever the driver sent. A driver that
		// sends bytes, a string or a time all mean the same column, and a
		// caller that wanted text should not have to know which.
		fmt.Fprintf(b, "\t\t\t%s = rhoSqlText(%s)\n", target, source)
	}
}

// scanDestinations are the untyped cells a row is scanned into, in the order
// the columns were declared — which is the order the database returns them.
func scanDestinations(fields []SQLField) []string {
	out := make([]string, 0, len(fields))
	for index := range fields {
		out = append(out, fmt.Sprintf("&scanned[%d]", index))
	}
	return out
}

// sqlValueKind is the SqlValue kind a parameter is carried as, which is what
// the driver is told it is being handed.
func sqlValueKind(parameter SQLParameter) int {
	switch {
	case parameter.IsFloat:
		return 2
	case parameter.IsBoolean:
		return 3
	case parameter.IsText:
		return 4
	}
	return 1
}

// oneLine is a statement as a single comment line, because a multi-line comment
// inside a doc block reads as a different declaration.
func oneLine(text string) string {
	return strings.Join(strings.Fields(text), " ")
}
