// implementation behind it, supplied by the backend so a project that depends
// on the component gets the port without copying any of it.
//
// A project asks for the port by name:
//
//	targets:
//	  - id: go
//	    ports:
//	      - logemit
//
// The line written here matches the shape the formatter produces, so a record
// reads the same whether it came from the component's command or from a service.
