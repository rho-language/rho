//
// @file emit_go_docstore.go
// @brief The documentation-store port.
//
// A service that serves the repository's documentation needs three things a Rho
// source cannot do on its own: walk a directory of Markdown, render one of those
// files, and read the project's release notes. Rho has no file I/O, so those
// sit behind this port, the same way the registry's store sits behind fsstore.
//
// A project asks for the port by name:
//
//	targets:
//	  - id: go-server
//	    ports:
//	      - docstore
//
// Rendering goes through the rho-doc component rather than a second Markdown
// implementation: it is the generator the rest of the toolchain documents with,
// so a page served here and a page a build writes are the same page. The
// component is a separate process, reached the way every component is, and a
// service with no generator still serves its index and the pages it can.
//
// @project Rho Programming Language
// @version 0.1
// @date 2026
//
// SPDX-License-Identifier: Apache-2.0
//

package codegen

// emitDocStorePort renders the documentation-store port.
func emitDocStorePort(ctx PortContext) ([]string, string) {
	imports := []string{
		`"fmt"`,
		`"io"`,
		`"io/fs"`,
		`"os"`,
		`"os/exec"`,
		`"path/filepath"`,
		`"sort"`,
		`"strings"`,
		`"sync"`,
		`"time"`,
	}
	return imports, `// Generated by the docstore port: the documentation a service serves, read
// from the tree the sources are written in and rendered by the generator.

// clock_year is the current year, which a page's footer dates itself with.
func clockYear() uint32 {
	return uint32(time.Now().Year())
}

// siteTitle is what the site calls itself, from its deployment or its default.
func siteTitle() string {
	if value := strings.TrimSpace(os.Getenv("RHO_SITE_TITLE")); value != "" {
		return value
	}
	return "Rho language and toolchain"
}

// siteDocsDir is the tree a menu is listed from.
func siteDocsDir() string {
	if value := strings.TrimSpace(os.Getenv("RHO_DOCS_TREE")); value != "" {
		return value
	}
	return "docs"
}

// siteDocsRoot is the tree a site is built from: the project root, not the
// documentation directory inside it. A build reads a repository — the docs and
// the modules they document — so pointing it at docs alone would build a site
// with no pages in it.
func siteDocsRoot() string {
	if value := strings.TrimSpace(os.Getenv("RHO_DOCS_ROOT")); value != "" {
		return value
	}
	return "."
}

// siteReleasesPath is the release notes the overview reads, a file relative to
// where the service runs.
func siteReleasesPath() string {
	if value := strings.TrimSpace(os.Getenv("RHO_SITE_RELEASES")); value != "" {
		return value
	}
	return "CHANGELOG.md"
}

// siteRepository is the project the pages belong to, shown as a link.
func siteRepository() string {
	return strings.TrimSpace(os.Getenv("RHO_SITE_REPOSITORY"))
}

// siteVersion is the version of the project the pages belong to.
//
// It is set by a deployment, or read from the repository's own VERSION file —
// the file the toolchain keeps its version in — found beside the service or at
// any directory above it, because a service started through the toolchain runs
// in the generated project's directory rather than the repository's. One file,
// however the service is started from it.
func siteVersion() string {
	if value := strings.TrimSpace(os.Getenv("RHO_SITE_VERSION")); value != "" {
		return value
	}
	dir, err := os.Getwd()
	if err != nil {
		return ""
	}
	for {
		if data, readErr := os.ReadFile(filepath.Join(dir, "VERSION")); readErr == nil {
			return strings.TrimSpace(string(data))
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}
		dir = parent
	}
}

// docsList lists a documentation tree as tab-separated lines: the path relative
// to the root, the page's title, and the section it is in. A Rho handler cannot
// walk a directory, so the walk happens here and the answer is lines it can read.
//
// The lines are ordered by section and then by path, so a section is one run of
// lines and a menu built by grouping them cannot show the same heading twice.
func docsList(dir string) string {
	root := filepath.Clean(dir)
	if root == "" {
		return ""
	}
	type entry struct {
		section string
		rel     string
		line    string
	}
	entries := []entry{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		// A dot directory holds tooling, not documentation; skipping it keeps
		// build output and version-control data out of the menu.
		if d.IsDir() {
			if path != root && strings.HasPrefix(d.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(strings.ToLower(d.Name()), ".md") {
			return nil
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return nil
		}
		rel = filepath.ToSlash(rel)
		title := docTitle(path)
		if title == "" {
			title = strings.TrimSuffix(d.Name(), filepath.Ext(d.Name()))
		}
		section := "."
		if at := strings.Index(rel, "/"); at >= 0 {
			section = rel[:at]
		}
		entries = append(entries, entry{section: section, rel: rel, line: rel + "\t" + title + "\t" + section})
		return nil
	})
	if err != nil || len(entries) == 0 {
		return ""
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].section != entries[j].section {
			return entries[i].section < entries[j].section
		}
		return entries[i].rel < entries[j].rel
	})
	lines := make([]string, len(entries))
	for i, e := range entries {
		lines[i] = e.line
	}
	return strings.Join(lines, "\n") + "\n"
}

// docTitle is a page's own title: the first level-one heading it has, or "" when
// it has none. A page that names itself in its first heading is named that in a
// menu; a file name is a poorer answer but a truthful one.
func docTitle(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	for _, line := range strings.Split(string(data), "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "# ") {
			return strings.TrimSpace(strings.TrimPrefix(trimmed, "# "))
		}
	}
	return ""
}

// The site is built once, on the first request that needs a page, and served
// from where it was written.
//
// It is built rather than rendered a page at a time because a page's links to
// other pages are resolved by the build: rendered alone, a cross-reference has
// no page to point at and becomes an anchor on the page that names it — a link
// that goes nowhere. Building the site gives every page the links a build would
// give it, at the price of building once instead of rendering per request.
var (
	docsOnce sync.Once
	docsSite string
	docsBuilt bool
)

// docsEnsure builds the site if it has not been built, and reports where it is.
func docsEnsure() (string, bool) {
	docsOnce.Do(func() {
		root := siteDocsRoot()
		out := strings.TrimSpace(os.Getenv("RHO_SITE_BUILD"))
		if out == "" {
			out = filepath.Join(os.TempDir(), "rho-docsite-site")
		}
		if err := os.RemoveAll(out); err != nil {
			fmt.Fprintf(os.Stderr, "docstore: clearing %s: %v\n", out, err)
			return
		}
		if err := os.MkdirAll(out, 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "docstore: creating %s: %v\n", out, err)
			return
		}
		binary := docstoreBinary()
		if binary == "" {
			fmt.Fprintln(os.Stderr, "docstore: no documentation generator found; install the rho-doc component")
			return
		}
		arguments := []string{"doc", "--fragment", "write", root, out, siteTitle()}
		// Where the site is published, so a page it writes links back to the
		// service that serves it rather than to nothing. The label is what the
		// link says; "back" is the generator's fallback and reads as a fragment
		// of a sentence, so a service names the thing it links to.
		if home := strings.TrimSpace(os.Getenv("RHO_SITE_HOME")); home != "" {
			arguments = append(arguments, "--home", home)
			label := strings.TrimSpace(os.Getenv("RHO_SITE_HOME_TITLE"))
			if label == "" {
				label = "Rho"
			}
			arguments = append(arguments, "--home-title", label)
		}
		command := exec.Command(binary, arguments...)
		command.Stdout = io.Discard
		command.Stderr = os.Stderr
		if err := command.Run(); err != nil {
			fmt.Fprintf(os.Stderr, "docstore: building the site: %v\n", err)
			return
		}
		docsSite, docsBuilt = out, true
	})
	return docsSite, docsBuilt
}

// docsRender returns the built page for a request path, or "" when there is
// none. The path comes from a URL, so it is confined to the built site: a path
// that climbs out of it names a file the service was never asked to serve.
//
// A path without an extension is a page, not a file, so it is looked up as
// path.html and then as path/index.html: a reader types a page, not a file
// name, and the site has both shapes.
func docsRender(path string) string {
	out, ok := docsEnsure()
	if !ok {
		return ""
	}
	rel := filepath.Clean(filepath.FromSlash(strings.Trim(strings.TrimSpace(path), "/")))
	if rel == "." || rel == "" {
		rel = "index.html"
	}
	if filepath.IsAbs(rel) || strings.HasPrefix(rel, "..") {
		return ""
	}
	candidates := []string{rel}
	if !strings.Contains(filepath.Base(rel), ".") {
		candidates = []string{rel + ".html", filepath.Join(rel, "index.html")}
	}
	for _, candidate := range candidates {
		full := filepath.Join(out, candidate)
		if !withinDir(out, full) {
			continue
		}
		if data, err := os.ReadFile(full); err == nil {
			return string(data)
		}
	}
	return ""
}

// docsRootPage is the site's own index, for the one address that needs it:
// /docs without the trailing slash. A page's links are relative, so a browser
// resolving them against /docs would look beside the site rather than inside
// it; a base tells it otherwise. At /docs/ the same page needs nothing, which
// is why this is a function apart from docsRender.
func docsRootPage() string {
	out, ok := docsEnsure()
	if !ok {
		return ""
	}
	data, err := os.ReadFile(filepath.Join(out, "index.html"))
	if err != nil {
		return ""
	}
	page := string(data)
	const base = "<base href=\"/docs/\">"
	if at := strings.Index(page, "<head>"); at >= 0 {
		insert := at + len("<head>")
		return page[:insert] + base + page[insert:]
	}
	return base + page
}

// docsReleases reads a changelog and returns one line per release: the version,
// the date, and the note flattened onto one line. A Rho handler cannot parse a
// document, so the parsing happens here and the answer is lines it can render.
func docsReleases(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	lines := strings.Split(string(data), "\n")
	out := []string{}
	version, date := "", ""
	body := []string{}
	flush := func() {
		if version == "" {
			return
		}
		note := strings.Join(strings.Fields(strings.Join(body, " ")), " ")
		out = append(out, version+"\t"+date+"\t"+note)
		version, date, body = "", "", nil
	}
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "## ") && !strings.HasPrefix(trimmed, "### ") {
			flush()
			version, date = releaseHeading(trimmed)
			continue
		}
		if version != "" {
			body = append(body, trimmed)
		}
	}
	flush()
	if len(out) == 0 {
		return ""
	}
	return strings.Join(out, "\n") + "\n"
}

// releaseHeading pulls the version and date out of a "## [1.2.3] - 2026-01-01"
// heading, in either the bracketed or the bare form.
func releaseHeading(line string) (string, string) {
	text := strings.TrimSpace(strings.TrimPrefix(line, "## "))
	version := ""
	if strings.HasPrefix(text, "[") {
		if end := strings.Index(text, "]"); end > 0 {
			version = text[1:end]
			text = text[end+1:]
		}
	} else if fields := strings.Fields(text); len(fields) > 0 {
		version = fields[0]
		text = strings.TrimPrefix(text, fields[0])
	}
	date := ""
	for _, field := range strings.Fields(text) {
		trimmed := strings.Trim(field, "()")
		if len(trimmed) == 10 && trimmed[4] == '-' && trimmed[7] == '-' {
			date = trimmed
			break
		}
	}
	return version, date
}

// withinDir reports whether a path is inside a directory, and not beside it.
func withinDir(dir, path string) bool {
	rel, err := filepath.Rel(dir, path)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

// docstoreBinary is the generator a page is rendered by.
//
// The Rho CLI is preferred, because it is what publishes the component's
// command; a project reached from a copy of the component directly still has
// RHO_BIN set to it, so one of the two is always there.
func docstoreBinary() string {
	if binary := strings.TrimSpace(os.Getenv("RHO_BIN")); binary != "" {
		return binary
	}
	for _, candidate := range []string{"rho", "rho-doc"} {
		if resolved, err := exec.LookPath(candidate); err == nil {
			return resolved
		}
	}
	return ""
}
`
}
