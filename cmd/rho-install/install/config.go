package install

import (
    "fmt"
    "os"
    "path/filepath"
)

/* -------------------------------------------------------------------------- */
/*  Templates                                                                  */
/* -------------------------------------------------------------------------- */

const settingsTemplate = `
# Rho Global Settings
# This file contains global configuration values for the Rho ecosystem.

[general]
version = "0.1"
`

// pathsTemplate is generated dynamically because it depends on user HOME.
func generatePathsTemplate(home string) string {
    return fmt.Sprintf(`
# Rho Global Paths
# Automatically generated by rho-install.

[paths]
home = "%s"
bin = "%s/bin"
modules = "%s/modules/installed"
registry = "%s/registry/local"
cache = "%s/cache"
config = "%s/config"
auth = "%s/auth"
pkg_mod = "%s/pkg/mod"
`, home, home, home, home, home, home, home, home)
}

/* -------------------------------------------------------------------------- */
/*  Public API                                                                 */
/* -------------------------------------------------------------------------- */

// InitConfig creates settings.toml and paths.toml.
func InitConfig() error {
    configPath, err := GetConfigPath()
    if err != nil {
        return err
    }

    home, err := GetRhoHome()
    if err != nil {
        return err
    }

    files := map[string]string{
        "settings.toml": settingsTemplate,
        "paths.toml":    generatePathsTemplate(home),
    }

    for name, content := range files {
        file := filepath.Join(configPath, name)

        // Avoid overwriting existing config
        if _, err := os.Stat(file); err == nil {
            continue
        }

        if err := os.WriteFile(file, []byte(content), 0o644); err != nil {
            return fmt.Errorf("failed to write config file %s: %w", name, err)
        }
    }

    return nil
}

// ConfigExists checks if both settings.toml and paths.toml exist.
func ConfigExists() bool {
    configPath, err := GetConfigPath()
    if err != nil {
        return false
    }

    files := []string{
        "settings.toml",
        "paths.toml",
    }

    for _, f := range files {
        if _, err := os.Stat(filepath.Join(configPath, f)); os.IsNotExist(err) {
            return false
        }
    }

    return true
}
